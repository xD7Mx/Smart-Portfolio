# العائد المحقَّق — فإن كان الميلُ صفراً فالمحرّك مولّدُ أرقامٍ أنيق، ويُعرف
# ذلك بالقياس لا بالجدل.
_RUNS = Path(__file__).resolve().parents[3] / "data" / "valuation_runs.jsonl"


def _log_run(symbol: str | None, out: dict, price, r, g) -> None:
    if not symbol or not out.get("methods"):
        return
    try:
        _RUNS.parent.mkdir(parents=True, exist_ok=True)
        row = {
            "symbol": str(symbol).replace(".SR", ""),
            "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "price": price,
            "value": out.get("value"),
            "low": out.get("low"), "high": out.get("high"),
            "r": round(r, 4), "g": round(g, 4),
            "confidence": out.get("confidence"),
            "entry_price": out.get("entry_price"),
            "methods": [{"n": m.get("name"), "v": m.get("value"),
                         "i": m.get("inputs")} for m in out.get("methods", [])],
            "asof": out.get("asof"),
        }
        with _RUNS.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
    except Exception:                                             # noqa: BLE001
        pass


def arbitrate(buckets: dict, vals: list) -> tuple[dict, list, str | None]:
    """تحكيمٌ بين مساراتٍ متضاربة: الأغلبيةُ حولَ الوسيط (D337).

    ══ الامتناعُ عند أوّل خلافٍ اعتذارٌ لا حكم ══
    قال المالك: «المبدأُ ليس الاعتذارَ إن وُجد نقصٌ وإنما اكتشافُ البديل
    المكمِّل». وقِيس على خادمه بعد إكمال المدخلات (‏D336) أن الامتناع
    ارتفع من ٦ إلى ٩ من ٦١: مساراتٌ صارت **قابلةً للحساب** فظهر خلافُها،
    وأحدُها ‎16.11× (‏5.57–89.71) — وذاك مدخلٌ شاذٌّ لا خلافٌ حقيقيّ.

    فالقاعدةُ **معلَنةٌ ومتناظرةٌ** لا انتقاءٌ بالهوى: يُحسَب وسيطُ
    المسارات، ويُستبعَد كلُّ ما بَعُد عنه أكثرَ من الضِّعف صعوداً أو
    نزولاً. فإن بقي مسارانِ فأكثرُ يتّفقون دون ثلاثة أضعاف حُكِّم الباقي
    وسُمّي المستبعَد وخُفضت الثقة؛ وإن لم تبقَ أغلبيةٌ فلا تحكيمَ —
    ويبقى الامتناعُ حكماً. ومسارانِ متباعدان لا أغلبيةَ فيهما أصلاً.

    تُعاد: (المساراتُ الباقية، قيمُها، نصُّ الاستبعاد أو None).
    """
    if len(vals) < 3 or min(vals) <= 0 or max(vals) / min(vals) < 3.0:
        return buckets, vals, None
    med = median(vals)
    keep = {k: v for k, v in buckets.items() if med / 2.0 <= v <= med * 2.0}
    drop = {k: v for k, v in buckets.items() if k not in keep}
    kv = list(keep.values())
    if not (len(kv) >= 2 and drop and min(kv) > 0 and max(kv) / min(kv) < 3.0):
        return buckets, vals, None
    why = ("خارجَ حساب النقطة (شذَّ عن وسيط المسارات بأكثرَ من الضِّعف): "
           + " · ".join(f"{k} ({round(v, 2)})" for k, v in drop.items())
           + f" — والوسيطُ {round(med, 2)}.")
    return keep, kv, why


def risk_flags(archetype: str | None, periods: list[dict] | None,
               info: dict | None = None) -> tuple[list[dict], list[str]]:
    """شروطُ الخطر المُعلَنة — تُقاس وتُخفض الثقةَ ولا تمنع التقدير (‏D408).

    ══ لماذا ══
    في `archetype_spec.VALUATION` اثنتا عشرةَ قائمةِ `abstain_if`: رافعةٌ
    فوق اثني عشر · خسارةُ سنتين · ريتٌ بلا توزيع · حقوقٌ سالبة · تغطيةُ
    فوائدَ دون واحد… وقِيس أنّها **لا يقرؤها محرّكٌ واحد** (‏D405). فشركةٌ
    حقوقُها سالبةٌ تخرج اليومَ بسعرٍ عادلٍ ثقتُه «مرتفعة» كأنّها سليمة —
    وذاك أخطرُ من الامتناع: **رقمٌ واثقٌ على أرضٍ رخوة**، والقرارُ يُبنى
    على الثقةِ لا على الرقم وحدَه.

    ══ ولماذا خافضةً لا مانعة ══
    قضى المالك: «جميعُ الشركات مُلزَمةٌ بالإفصاح فلا امتناعَ مفهوم»،
    و«غيرُ متوفّر عجزُ بناءٍ من طرفك». فالخطرُ **يُسعَّر** لا يُسكَت عنه
    ولا يُفرِّغ الخانة: يُعلَن باسمه، وتنزل الثقة، فيتّسع هامشُ الأمان
    تلقائياً — أي **سعرُ دخولٍ أدنى**، وهو ترجمةُ الخطر التي تُفيد قراراً.

    ══ وما لا يُقاس يُقال ══
    شرطٌ لا تصله مدخلاتُه لا يُعَدّ سليماً ولا مخالفاً: يُعاد في القائمة
    الثانية «غيرُ مقيس»، فلا تُقرأ الخضرةُ على أنّها شهادة.
    """
    try:
        from app.data.archetype_spec import VALUATION as _V
    except Exception:                                             # noqa: BLE001
        return [], [], []
    want = list((_V.get(archetype or "") or {}).get("abstain_if") or [])
    # ══ وعددُ المخرَجات واحدٌ في كلّ مسار ══ (D424)
    # أُضيفت السلّةُ الثالثةُ (‏فجواتُ البيان · D422) إلى مخرَج النهاية
    # وحدَه، وبقي المخرَجانِ المبكّرانِ بقيمتَين. وكلُّ نمطٍ لا
    # `abstain_if` له يمرّ بهما — وهو أكثرُ السوق. فرفع `compute`
    # `ValueError` في **كلّ** ورقةٍ تقريباً: «تعذّرت 268 من 273» وصفرُ
    # سعرٍ عادلٍ للسوق كلِّه.
    #
    # وحارسي لم يمسّ هذا المسار: اختبر `bank` و`capital_infra` و`reit`
    # — وكلُّها ذاتُ شروط — فخرج أخضرَ على شفرةٍ تسقط في الأغلبية.
    # فالحارسُ الذي لا يمرّ بالمسار الخالي يشهد لما لم يره.
    if not want:
        return [], [], []
    ps = [p for p in (periods or []) if isinstance(p, dict)]
    ps.sort(key=lambda p: str(p.get("as_of") or ""), reverse=True)
    last = ps[0] if ps else {}
    info = info or {}

    def _n(src: dict, *keys):
        for k in keys:
            v = src.get(k)
            if isinstance(v, (int, float)):
                return float(v)
        return None

    eq = _n(last, "equity")
    assets = _n(last, "total_assets")
    ebit = _n(last, "ebit")
    intx = _n(last, "interest_expense")
    ni = [_n(p, "net_income") for p in ps[:3]]
    div = _n(info, "dividend_rate", "dividend_yield", "trailing_annual_dividend_rate")

    # ══ ونقصُ حقلٍ شرطٌ لا «لم يُقَس» ══ (D422)
    # قِيس على الكون: `total_debt` ناقصٌ في ‎40 ورقة. وشرطُ `no_debt_field`
    # في أربعةِ أنماطٍ **يعني هذا النقصَ بعينه** — فلا هو مخالفةٌ تُدين
    # الشركةَ ولا هو «شرطٌ لم تصله مدخلاتُه». وكان يسقط في سلّة
    # «لم يُقَس» فيُخصم من **ثقة الرقم** (‏D411) بلا بيانٍ لسببه.
    #
    # وأوّلُ ما جرّبتُه كان أسوأ: جدولُ «لا ينطبق» لشروطٍ ظننتُها على
    # البنوك، فقِيس أنّ `coverage_lt_1` **ليست في شروط البنك أصلاً** —
    # فرضيةٌ سقطت، ولا يُبقى جدولٌ ميّتٌ بعدها (درسُ D405).
    #
    # فالصوابُ أن يُقال ما هو: **فجوةُ بيانٍ مُعلَنةٌ باسمها**، تُخصم
    # خصماً مقدَّراً ولا تحبس الدرجةَ دون النصف — فالورقةُ ليست خطرةً،
    # إنّما لم يصلنا أحدُ حقولها.
    _DATA_GAP = {
        "no_debt_field": ("total_debt", "حقلُ الدَّين لم يصلنا — فلا رافعةَ"
                                        " تُقاس ولا تغطيةَ فوائد"),
        "no_published_nav": ("nav_per_unit", "صافي أصولِ الوحدة لم يُنشَر"),
    }

    hit: list[dict] = []
    unmeasured: list[str] = []
    data_gaps: list[dict] = []

    def _judge(code: str, bad: bool | None, text: str) -> None:
        if bad is None:
            unmeasured.append(code)
        elif bad:
            hit.append({"code": code, "نصّ": text})

    for c in want:
        if c in _DATA_GAP:
            _fld, _txt = _DATA_GAP[c]
            if not isinstance(last.get(_fld), (int, float)):
                data_gaps.append({"code": c, "نصّ": _txt})
            continue
        if c == "negative_equity":
            _judge(c, None if eq is None else eq < 0,
                   "حقوقُ الملكية سالبة — الأساسُ الذي يُقاس عليه مفقود")
        elif c == "no_roe":
            _judge(c, (eq is None or ni[0] is None) or eq == 0,
                   "لا عائدَ على الحقوق يُحسب — مدخلُه غائب")
        elif c == "loss_last_year":
            _judge(c, None if ni[0] is None else ni[0] < 0,
                   "خسارةٌ في أحدث فترة")
        elif c in ("two_loss_years", "three_years_negative_ccr"):
            _vals = [v for v in ni[:2] if v is not None]
            _judge(c, None if len(_vals) < 2 else all(v < 0 for v in _vals),
                   "خسارةٌ في فترتين متتاليتين")
        elif c in ("leverage_gt_12", "leverage_gt_9"):
            lim = 12.0 if c.endswith("12") else 9.0
            _lev = (assets / eq) if (assets and eq and eq > 0) else None
            _judge(c, None if _lev is None else _lev > lim,
                   f"الرافعةُ {_lev:.1f}× فوق حدّ الصنف {lim:.0f}×"
                   if _lev else "")
        elif c == "coverage_lt_1":
            _cov = (ebit / intx) if (ebit is not None and intx) else None
            _judge(c, None if _cov is None else _cov < 1.0,
                   f"تغطيةُ الفوائد {_cov:.2f}× دون واحد" if _cov else "")
        elif c == "no_dividend":
            _judge(c, None if div is None else div <= 0,
                   "ريتٌ بلا توزيعٍ — وتوزيعُه جوهرُ عائده")
        elif c in ("negative_normalized_eps",):
            _vals = [v for v in ni if v is not None]
            _judge(c, None if not _vals else (sum(_vals) / len(_vals)) < 0,
                   "متوسّطُ الأرباح سالبٌ عبر الفترات")
        elif c == "negative_avg_profit":
            _vals = [v for v in ni if v is not None]
            _judge(c, None if not _vals else (sum(_vals) / len(_vals)) < 0,
                   "متوسّطُ الربح سالب")
        else:
            unmeasured.append(c)
    return hit, unmeasured, data_gaps


def compute(info: dict, price: float | None,
            sector_avg_pe: float | None = None,
            sector_avg_pb: float | None = None,
            asof: str | None = None,
            periods: list[dict] | None = None,
            peer_count: int | None = None,
            archetype: str | None = None,
            latest_quarter: dict | None = None,
            ttm: dict | None = None,
            symbol: str | None = None) -> dict:
    """القيمة العادلة بمساراتها. تُعاد دائماً بنية كاملة حتى عند التعذّر.

    و`asof` تاريخُ آخر تحديثٍ للأرقام المالية المستعملة. يُعاد دائماً —
    ويُعرض في البطاقة — لأن تقييماً لا يُعرف عمر مدخلاته لا يُبنى عليه
    قرار (بند ٢٤ من الميثاق). فالمدخلات تُخزَّن ثلاثين يوماً، وقائمةٌ
    مالية جديدة تُغيّر النتيجة كلَّها.
    """
    # ══ الصندوقُ المتداول لا قيمةَ عادلةَ له ══
    # وعاءٌ يتبع مؤشّراً أو أصلاً (ذهبٌ · صكوكٌ · أسهمٌ أمريكية) — سعرُه
    # صافي أصوله، ولا أرباحَ له ولا تدفّقَ حرٌّ ولا قيمةٌ دفترية تُقاس.
    # فتقديرُ «قيمةٍ عادلة» له اختلاقٌ بشكل رقم.
    # ══ التأمينُ لا تُقدَّر قيمتُه بمضاعف دفترية ══
    # النسبةُ المجمّعة (خسائر + مصاريف ÷ أقساط) هي **النموذج الاقتصاديّ**
    # لشركة التأمين لا مؤشّرٌ مساند: من نسبتُها 105٪ تخسر على كل ريالٍ
    # تكتتبه وتعيش على عائد استثماراتها. وربحُها المعلَن دالّةٌ في كفاية
    # الاحتياطيات — أي في **تقديرٍ إداريّ** يمكن تأجيله سنوات. فعائدٌ على
    # حقوق ملكيةٍ لا نعرف مصدره ليس تقديراً منخفض الثقة بل رقماً بلا معنى،
    # ومضاعفُ دفتريةٍ مبنيٌّ عليه أسوأ من الامتناع.
    # ودرجةُ الحوكمة تبقى — فهي تقيس أشياء أخرى تُقاس فعلاً.
    # ══ ولا يُمتنَع عن مُصدِرٍ مُلزَمٍ بالإفصاح ══ (D371)
    # كان الامتناعُ هنا نهائياً متى غابت النسبةُ المجمّعة. وقضى المالك
    # بمبدأَين: كلُّ شركةٍ في الرئيسيّ ملزَمةٌ بالإفصاح فلا امتناعَ
    # مفهوم، والفراغُ يُحارَب لا يُبرَّر. والصوابُ المهنيُّ أن شركةَ
    # التأمين تُقيَّم كالبنك — بالدخل المتبقّي ومضاعفِ الدفترية — وأن
    # غيابَ النسبةِ المجمّعة **تحفّظٌ يُعلَن ويُسعَّر** بخفض الثقة
    # وتوسيع هامش الأمان، لا سبباً لإلغاء التقدير كلِّه.
    _ins_no_cr = (archetype == "insurance"
                  and not (info or {}).get("_regulatory_ratios", {})
                  .get("combined_ratio"))

    if archetype == "fund":
        return {"value": None, "low": None, "high": None, "methods": [],
                "asof": asof, "stale": None,
                "unavailable_reason": (
                    "صندوقٌ متداول — سعرُه صافي أصوله، ولا تُقدَّر له قيمةٌ "
                    "عادلة بمقاييس الشركات.")}

    # ══ التدقيق قبل الحساب ══ (بأمر المالك: جودةٌ استثمارية)
    # الأساسيات تُدقَّق مقابل القوائم أوّلاً، فالقوائم بنودٌ مدقَّقة والملخَّص
    # مشتقٌّ قد يتأخّر أو يُحسب على عدد أسهمٍ قديم بعد منحةٍ أو تجزئة.
    # وأيُّ تصحيحٍ يُسجَّل ويُعرض — لا يُبتلع صامتاً.
    from app.services.data_quality import audit as _audit
    _q = _audit(info or {}, periods or [])
    info = _q["values"]
    out: dict = {"value": None, "low": None, "high": None, "methods": [],
                 "asof": asof, "stale": None,
                 "audit": {"corrected": _q["corrected"], "notes": _q["notes"]},
                 "assumptions": {
                     "العائد الخالي من المخاطر": f"{RISK_FREE * 100:.1f}%",
                     "علاوة مخاطر السوق": f"{EQUITY_PREMIUM * 100:.1f}%",
                     "سقف النموّ المستدام": f"{MAX_SUSTAINABLE_GROWTH * 100:.1f}%",
                     "معدّل الخصم": None,
                 },
                 "unavailable_reason": None}

    # ══ لا قيمةَ بلا قوائم ══ (قرارُ مجلس نِصاب — كشفه `value_check.py`)
    # كان التقديرُ يخرج من حقول الملخّص وحدها (ربحيةُ سهمٍ · دفترية ·
    # عائدُ حقوق) بلا قائمةٍ مالية واحدة: لا سلسلةَ تُتحقّق منها، ولا
    # اتّجاهَ يُقرأ، ولا سبيلَ لمعرفة أربحٌ متكرّرٌ هو أم واقعةُ سنة.
    # وبوّابةُ القرار في التطبيق نفسه تمتنع دون سنتين — فكانت الشاشةُ
    # تعرض قيمةً عادلة لشركةٍ ترفض أن تُدرّجها. تناقضٌ بين شطري شاشةٍ
    # واحدة، والحدُّ الآن واحدٌ لهما.
    # ══ والورقةُ المؤشِّرةُ لا تُحاكَم بمسطرة شركة ══ (D349)
    # قِيس على خادم المالك: عشرُ أوراقٍ في «صناديق المؤشرات المتداولة»
    # تمتنع بجملة «لم تصلنا إلا ٠ قائمةٍ مالية… والنقصُ في وصولها إلينا
    # لا في الشركة» — وهي جملةٌ **كاذبةٌ في حقّها**: لا قوائمَ لصندوقٍ
    # يتبع مؤشّراً بطبيعته، ولا شركةَ أصلاً. فالامتناعُ صوابٌ والسببُ
    # خطأ، والسببُ الخطأُ يرسل القارئَ يبحث عن مصدرٍ لا وجودَ له.
    from app.services.statement_merge import archetype_of as _arch
    if _arch(symbol) == "fund":
        out["unavailable_reason"] = (
            "ورقةٌ مؤشِّرة: لا قوائمَ مالية لها بطبيعتها — قيمتُها صافي "
            "أصولها، وهو سعرُها تقريباً بحكم إنشاء الوحدات وإلغائها. "
            "فلا تُقدَّر بمضاعفاتٍ ولا بخصمِ تدفّق، ولا نقصَ في مصدر.")
        return out

    if len(periods or []) < 2:
        out["unavailable_reason"] = (
            f"لم تصلنا إلا {len(periods or [])} قائمةٍ مالية لهذه الورقة — "
            "والتقديرُ من حقول الملخّص وحدها لا سلسلةَ تسنده ولا اتّجاهَ "
            "يُقرأ منه. والقوائمُ مُلزِمةٌ لكل مدرَج، فالنقصُ في وصولها "
            "إلينا لا في الشركة.")
        return out

    def num(k):
        v = info.get(k)
        return v if isinstance(v, (int, float)) else None

    # ══ لا رأيَ للمحللين في الحساب — ولو من نافذة ══
    # طُرد «السعر المستهدف» من الباب (‏D047) ثم دخل تقديرُهم للربحية
    # المستقبلية (`forward_eps`) من النافذة. وانحيازُه التفاؤليّ موثَّق
    # وأشدُّ في الأسواق الناشئة. فالمحقَّقةُ وحدها.
    eps = num("eps")
    # ══ وربحيةُ السهم من اثني عشرَ شهراً لا من سنةٍ مضت ══ (D414)
    # مضاعفُ الربحية يقرأ ربحيةَ سنةٍ ختامُها قد يكون قبل ثلاثةِ أرباع،
    # وعندنا أرباعٌ أحدث. والجمعُ **مُتحقَّقٌ منه لكلّ رمزٍ على حدة**
    # (‏`_ttm_from`): أرباعُ سنةٍ كاملةٍ تُقارَن بسنويّها المنشور، فإن
    # تطابقا في حدود العُشر فالأرباعُ منفصلةٌ وجمعُها صحيح. وما لم
    # يُتحقَّق منه لا يُستعمَل — ويُقال لماذا.
    bvps = num("book_value")
    # ══ ودفتريةٌ ألفَ ضعفِ السعر ليست فرصةً بل خطأُ وحدة ══ (D392)
    #
    # قِيس بعيّنةٍ من كلّ قطاعٍ على خادم المالك: أربعُ أوراقٍ خرجت بسعرٍ
    # «عادلٍ» بين ألفٍ وعشرين ألفَ ضعفٍ من سعرها — 4003 = 108,075 والسعرُ
    # 65.85 (‏1641×) · 4040 = 13,474 والسعرُ 11.01 (‏1224×) · 4001 = 5,475
    # والسعرُ 4.59 (‏1193×) · 2082 = 19,362 والسعرُ 178.6. وكلُّها من
    # **مسارٍ واحدٍ منفردٍ** مدفوعٍ بالقيمة الدفترية للسهم.
    #
    # والعطبُ في المدخل لا النموذج: `book_value` يُقرأ من ملخّص المزوّد
    # بلا مقارنةٍ بالقوائم، فخطأُ وحدةٍ فيه (حقوقٌ بالريال ÷ أسهمٍ
    # بالآلاف) يضرب المسارَ والسقفَ والأرضيةَ معاً. ونسبٌ حول الألف
    # شهادةٌ على الوحدة لا على السوق.
    #
    # فتُقارَن الدفتريةُ **بالقوائم أوّلاً** (حقوقٌ ÷ أسهم — وهما مقيسانِ
    # بمِرساة تداول في طبقة الإكمال)، فإن تباعدا نُسبةً تتجاوز الرُبع
    # اعتُمدت القوائمُ وسُمّي التصحيح. وإن لم تكن قوائمُ فحدُّ المعقولية
    # من السعر: دفتريةٌ تفوق السعرَ خمسةَ عشرَ ضعفاً **تُرفَض ولا تُستعمل**
    # — فلا مسارَ دفتريةٍ ولا سقفَ ولا أرضيةَ مبنيّةٌ على رقمٍ معطوب،
    # ويُقال إنه رُفض ولماذا. والرفضُ هنا أصدقُ من وسمٍ على رقمٍ يُعرَض.
    _bv_note = None
    _bv_stmt = None
    _sh_ok = None            # عددُ الأسهم الذي اجتاز شروطَ القوائم
    # ══ والميزانيةُ من أحدثِ إفصاحٍ لا من أحدثِ سنة ══ (D412-ب)
    # حقوقُ الملكية **رقمٌ عند لحظة** لا مجموعُ فترة، فأحدثُ ربعٍ منشورٍ
    # أصدقُ من ختام سنةٍ مضى عليها ثلاثةُ أرباع. وقِيس أنّ ‎25 من ‎30
    # ورقةً تملك ربعيّاً أحدثَ — فكنّا نبني الدفتريةَ على ميزانيةٍ
    # عمرُها ‎266 يوماً وعندنا واحدةٌ عمرُها ‎85.
    # ولا يُقاس بغير شروط القوائم نفسِها: الأسهمُ موجبةٌ، والحقوقُ
    # موجبة، ولا فجوةَ وحدةٍ ولا تضاربَ في عدد الأسهم.
    _lq = latest_quarter if isinstance(latest_quarter, dict) else None
    if _lq:
        _eq, _sh = _lq.get("equity"), _lq.get("shares_outstanding")
        if (isinstance(_eq, (int, float)) and isinstance(_sh, (int, float))
                and _sh > 0 and _eq > 0
                and not _lq.get("shares_unit_gap")
                and not _lq.get("shares_mismatch")):
            _bv_stmt = _eq / _sh
            _sh_ok = _sh
            out["book_value_from_quarter"] = str(_lq.get("as_of") or "")[:10]
    for _p in ([] if _bv_stmt else reversed(periods or [])):
        _eq, _sh = _p.get("equity"), _p.get("shares_outstanding")
        if (isinstance(_eq, (int, float)) and isinstance(_sh, (int, float))
                and _sh > 0 and _eq > 0
                and not _p.get("shares_unit_gap")
                and not _p.get("shares_mismatch")):
            _bv_stmt = _eq / _sh
            _sh_ok = _sh
            break
    if bvps and _bv_stmt and _bv_stmt > 0 and out.get("book_value_from_quarter"):
        # ══ والرسميُّ المدقَّق يتقدّم المزوّد بلا عتبة ══ (D412-ب)
        # كانت العتبةُ رُبعاً: يُعتمد ملخّصُ المزوّد ما لم يتباعدا ‎25٪.
        # وهي صوابٌ حين يكون البديلُ ختامَ سنةٍ مضى عليها ثلاثةُ أرباع —
        # فالفارقُ قد يكون **نموّاً حقيقياً** لا خطأً. أمّا حين يكون
        # البديلُ إفصاحَ الشركة نفسِها عن أحدثِ ربع، فهو أحدثُ وأوثقُ
        # معاً، وترتيبُ المصادر المُعلَن يقضي بتقدّمه: تداول ← أرقام ←
        # ياهو. فيُعتمَد ويُسمّى — ولا يُبدَّل رقمٌ صامتاً.
        if abs(bvps - _bv_stmt) / _bv_stmt > 0.001:
            _bv_note = (f"القيمة الدفترية للسهم: الملخَّص {bvps:,.2f}"
                        f" وإفصاحُ {out['book_value_from_quarter']}"
                        f" {_bv_stmt:,.2f} — اعتُمد الرسميُّ الأحدث")
            bvps = _bv_stmt
    elif bvps and _bv_stmt and _bv_stmt > 0:
        if abs(bvps - _bv_stmt) / _bv_stmt > 0.25:
            _bv_note = (f"القيمة الدفترية للسهم: الملخَّص {bvps:,.2f}"
                        f" والقوائم {_bv_stmt:,.2f} — اعتُمدت القوائم")
            bvps = _bv_stmt
    elif bvps and price and price > 0 and bvps > price * 15:
        _bv_note = (f"القيمة الدفترية للسهم {bvps:,.2f} تفوق السعر"
                    f" {price:,.2f} بـ{bvps / price:,.0f}× — خطأُ وحدةٍ"
                    f" أرجحُ من فرصة، فرُفضت ولم يُبنَ عليها مسار")
        bvps = None
    # ══ والمدخلُ الغائبُ يُشتقّ من منشورٍ لا يُنتظَر ══ (D400)
    #
    # قِيس بعيّنةِ كلّ قطاعٍ بعد تصحيح الأصناف: ‎13 امتناعاً من ‎43 سببُها
    # **واحدٌ** — «يلزم ربحيةُ سهمٍ مع مضاعف قطاع، أو دفتريةٌ مع عائد
    # حقوق، أو توزيعٌ مستقرّ». أي أن المحرّكَ يمتنع لغياب مدخلٍ **نملكه
    # منشوراً** ولم نصله به:
    #
    #   · **الدفتريةُ للسهم** = السعر ÷ مضاعفِ الدفترية — والمضاعفُ منشورٌ
    #     في لقطة «تداول» لكلّ ورقة (‏`price_to_book`). وهي الهويّةُ نفسُها
    #     التي تُشتقّ بها الحقوقُ في طبقة الإكمال، فلا مسطرةَ ثانية.
    #   · **عائدُ حقوق الملكية** = صافي الربح ÷ الحقوق — من القوائم نفسِها.
    #
    # ولا يُستبدَل منشورٌ بمشتقّ: الاشتقاقُ للفراغ وحدَه، ويُعلَن مصدرُه
    # في `derived_inputs` — فرقمٌ لا يُعرف أصلُه لا يُبنى عليه قرار.
    _derived_in: list[str] = []
    if not bvps:
        _pb = num("price_to_book")
        if _pb and _pb > 0 and price and price > 0:
            bvps = round(price / _pb, 4)
            _derived_in.append(f"دفتريةُ السهم = السعر ÷ مضاعفِ الدفترية"
                               f" المنشور ({_pb:.2f}) = {bvps:,.2f}")
    if not bvps and _bv_stmt and _bv_stmt > 0:
        bvps = _bv_stmt
        _derived_in.append(f"دفتريةُ السهم = حقوقٌ ÷ أسهمٌ من القوائم"
                           f" = {bvps:,.2f}")
    # وكلُّ تصحيحٍ يُعلَن — الصامتُ ممنوعٌ في الميثاق
    if _bv_note:
        out["book_value_note"] = _bv_note

    _ttm = ttm if isinstance(ttm, dict) else None
    if _ttm and not _ttm.get("unverified"):
        _te = _ttm.get("eps")
        # ══ والمقامُ من مصدرٍ مُتحقَّقٍ لا من صفٍّ كما جاء ══ (D418-ب)
        # قِيس بعد أوّل إصلاح: **34 من 195** ربحيةً ما زالت بالمئات، بل
        # ساء أحدُها (‎1050: من ‎1.95 إلى ‎2,210) — فعددُ الأسهم مغلوطٌ في
        # **السنويّ أيضاً**، والسقوطُ إليه زاد العطب. فالمخزَنُ نفسُه
        # غيرُ موثوقٍ في هذا الحقل لهذه الرموز.
        # والمحرّكُ يملك مقاماً **اجتاز شروطَ القوائم** أصلاً: ذاك الذي
        # بُنيت عليه الدفترية (‏حقوقٌ موجبةٌ · أسهمٌ موجبةٌ · لا فجوةَ
        # وحدةٍ ولا تضارب). فيُعاد حسابُ الربحية عليه، ولا يُؤخذ رقمٌ
        # حسبه غيرُنا من مقامٍ لم يُتحقَّق منه.
        _tni = _ttm.get("net_income")
        if (isinstance(_tni, (int, float)) and isinstance(_sh_ok, (int, float))
                and _sh_ok > 0):
            _te = _tni / _sh_ok
            out["eps_ttm_denominator"] = "المقامُ المُتحقَّقُ من القوائم"
        # ══ وبوّابةُ معقوليةٍ على الربحية نفسِها ══ (D415)
        # قِيس على الكون: المسارُ نال ‎3 من ‎273، وأحدُ الثلاثة خرج
        # بربحيةِ سهمٍ **7,184.76 ريالاً** — مستحيلٌ في سهمٍ سعرُه عشرات.
        # وسببُه عددُ أسهمٍ بوحدةٍ مغلوطةٍ في صفّ الربع. فالتحقّقُ من
        # **الجمع** لا يكفي: رقمٌ صحيحُ الجمعِ قد يكون معطوبَ المقام.
        # فتُقاس الربحيةُ بالسعر: ما يفوقه ثلاثةَ أضعافٍ ليس ربحيةَ سهمٍ
        # بل خطأُ وحدة، ويُرفَض ويُسمّى — ولا يُستعمل في مضاعفٍ ولا قيمة.
        if (isinstance(_te, (int, float)) and price and price > 0
                and abs(_te) > price * 3):
            out["eps_ttm_rejected"] = (
                f"ربحيةُ اثني عشرَ شهراً {_te:,.2f} تفوق السعرَ "
                f"{price:,.2f} بـ{abs(_te) / price:,.0f}× — خطأُ وحدةٍ في "
                f"عدد الأسهم لا ربحيةٌ، فلم تُستعمل")
            _te = None
        if isinstance(_te, (int, float)) and _te != 0:
            out["eps_ttm"] = round(_te, 4)
            out["eps_ttm_quarters"] = _ttm.get("quarters")
            out["eps_source"] = (
                f"اثنا عشرَ شهراً حتى {_ttm.get('as_of')} — "
                f"مُتحقَّقٌ بسنة {_ttm.get('verified_on')}")
            eps = _te
    elif _ttm and _ttm.get("note"):
        out["eps_ttm_note"] = _ttm["note"]

    roe = num("roe")
    if roe is None and bvps:
        for _p in reversed(periods or []):
            _ni, _eq = _p.get("net_income"), _p.get("equity")
            if (isinstance(_ni, (int, float)) and isinstance(_eq, (int, float))
                    and _eq > 0):
                roe = round(_ni / _eq * 100, 2)
                _derived_in.append(f"عائدُ حقوق الملكية = صافي الربح ÷"
                                   f" الحقوق = {roe:.1f}%")
                break
    if _derived_in:
        out["derived_inputs"] = _derived_in
    dps = num("dividend_per_share")
    growth = num("earnings_growth")
    beta = num("beta")
    r = _required_return(beta)
    out["assumptions"]["معدّل الخصم"] = f"{r * 100:.1f}%"
    _DROPPED["n"] = 0

    # نموٌّ مستدام مُقيَّد: نموّ الأرباح التاريخيّ يُستعمل مُقصوصاً عند
    # السقف، وسالبُه يُصفَّر — نموذجُ خصمٍ بنموٍّ سالب دائم يُنتج عبثاً.
    g = 0.0
    if growth is not None:
        g = max(0.0, min(growth / 100.0, MAX_SUSTAINABLE_GROWTH))

    # ══ النموُّ الدائم يُشتقّ من الاحتجاز لا يُفترض صفراً ══
    # ‏«ثمار» (‏2200): عائدُ حقوق 22.6٪ وتوزيعٌ رُبعُ الربح — ثم يُخصم
    # توزيعُها بنموٍّ **صفر**. وذلك تناقضٌ في ذاته: من يحتجز ثلاثةَ أرباع
    # ربحٍ يعود على رأسماله 22.6٪ لا يبقى ثابتاً إلى الأبد؛ المالُ المحتجَز
    # إمّا ينمو وإمّا يتبخّر، ونموٌّ صفرٌ يعني أنه يتبخّر.
    # والصيغةُ المعروفة: g = العائدُ على حقوق الملكية × نسبةُ الاحتجاز.
    # وتُشتقّ نسبةُ الاحتجاز من التوزيع والربح **المحسوبَين هنا** لا من
    # حقل المصدر: قِيس على «ثمار» فقال المصدرُ إن التوزيع 51.5٪ من الربح،
    # والتوزيعُ والدفتريةُ والعائدُ تقول 25.4٪ — ومن يخلط مصدرين متناقضين
    # يبني نموذجاً على رملٍ ويسمّي الفرقَ «اختلافَ مناهج».
    eps_from_book = (roe / 100.0 * bvps) if (roe is not None and bvps) else None
    eps_used = eps_from_book or eps
    # ══ من لا يوزّع يحتجز كلَّ ربحه ══
    # كان الاحتجازُ يبقى `None` حين يغيب التوزيع، فتتدحرج الدفتريةُ في
    # نموذج الدخل المتبقّي بصفر — أي أن أرباحَ خمسَ عشرةَ سنةً **تتبخّر**
    # من الميزانية. والشركةُ التي لا توزّع تحتجز مئةً بالمئة لا صفراً.
    # وقِيس أثرُه على السوق: مسارُ النموّ الدائم خرج بوسيطٍ ‎0.720 من السعر
    # (‏٢٢٩ شركة) بينما المضاعف ‎1.141 والخصم ‎0.869 — فهو وحده من يسحب
    # الوسيطَ العامّ، وهذا سببُه.
    retention = None
    if eps_used and eps_used > 0:
        if dps is None or dps <= 0:
            retention = 1.0
        else:
            retention = max(0.0, min(1.0, 1.0 - dps / eps_used))
    if roe is not None and retention is not None:
        g_sust = max(0.0, roe / 100.0 * retention)
        g = min(max(g, g_sust), MAX_SUSTAINABLE_GROWTH)

    # ══ أنماطٌ لا يصحّ فيها خصمُ التدفّق الحرّ ══ (بأمر المالك)
    # محرّك الحوكمة يعرف هذا منذ حين ويُعطّل كلَّ قواعد التدفّق الحرّ
    # للبنوك والتأمين والتمويل: نموُّ دفتر القروض يظهر تدفّقاً تشغيليّاً
    # **سالباً** وهو نموٌّ صحّيّ لا ضعف، والعكس في سنة الانكماش. فكان
    # محرّك التقييم يخصم رقماً يعرف المحرّكُ الآخرُ أنه بلا معنى — وهو
    # عينُ العطب الذي عولج في التدقيق (D031): محرّكٌ يعلم وآخر لا يعلم.
    #
    # والبديلُ ليس فراغاً بل الطريقةَ المعترف بها لكل نمط:
    #   • البنوك والتأمين والتمويل — خصمُ التوزيعات ومضاعفُ الدفترية
    #     المبرَّر (‏ROE−g)÷(r−g). وهو نهجُ التقييم المتّبع لها عالمياً،
    #     لأن حقوق الملكية والعائد عليها هما محلُّ القيمة فيها.
    #   • الصناديق العقارية — الدفتريّة تقريبُ صافي الأصول (عقاراتها
    #     بالقيمة العادلة وفق المعايير)، والتوزيعُ جوهرُ دخلها. وربحُها
    #     المحاسبيُّ وتدفّقُها مشوّهان بالإهلاك وإعادة التقييم.
    NO_DCF = {"bank", "insurance", "financial", "reit"}

    # ── ٠) التدفّق النقدي المخصوم — المعيار ─────────────────────────────
    # يُقدَّم على المضاعفات لأنه يُقيّم الشركة **في ذاتها**، والمضاعفات
    # تُقيّمها بما يدفعه السوق لنظائرها. فإن كان القطاع كلُّه مبالغاً فيه
    # صادقت المضاعفاتُ على المبالغة، والخصمُ وحده يكشفها.
    try:
        d = None if archetype in NO_DCF else _dcf(
            periods or [], info, price, r,
            cyclical=(archetype == "cyclical"),
            roe_for_reinv=(roe / 100.0 if roe else None))
    except Exception:                                             # noqa: BLE001
        d = None
    if d:
        out["methods"].append(d)
        if (d.get("terminal_share") or 0) > 0.75:
            out["terminal_heavy"] = True

    # ── ١) مضاعف الربحية العادل: ربحيةُ السهم × مضاعف القطاع ────────────
    # المنطق: ما دام السهم يكسب EPS ويُسعّر نظراؤه عند مضاعفٍ معلوم، فسعره
    # العادل هو حاصلُ ضربهما. ومضاعف القطاع من نظائرَ حقيقية في المحفظة
    # لا من رقمٍ عامّ — فإن غاب سقط المسار.
    if eps and eps > 0 and sector_avg_pe and 0 < sector_avg_pe < 60:
        v = _sane(eps * sector_avg_pe, price)
        if v:
            out["methods"].append({
                "name": "مضاعف الربحية العادل",
                "value": v,
                # عددُ الأقران جزءٌ من الرقم لا حاشية: مضاعفٌ من ثلاثة أقران
                # ليس كمضاعفٍ من ثلاثين، والمستثمر يزن الرقم بمصدره.
                "inputs": (f"ربحية السهم {eps:.2f} × وسيط القطاع "
                           f"{sector_avg_pe:.1f}"
                           + (f" ({peer_count} قريناً)" if peer_count else "")),
            })

    # ── ٢) نموٌّ دائم — مسارٌ واحد لا مساران ─────────────────────────────
    # ══ خطأٌ في بناء المحرّك نفسه، كشفته أرقامُ المسح ══
    # كان «مضاعفُ الدفترية المبرَّر» و«خصمُ التوزيعات» مسارين مستقلَّين
    # يُقاس اختلافُهما تشتّتاً. وهما **النموذجُ نفسه**: مضاعفُ الدفترية
    # المبرَّر ‏(ROE−g)÷(r−g) مشتقٌّ من جوردون بعينه حين يكون
    # ‏g = ROE × الاحتجاز. فلا يفترقان إلا إذا غُذّيا بمدخلاتٍ متناقضة —
    # وهو ما كان يقع: يُحسب المضاعفُ بعائد الشركة كاملاً ويُخصم التوزيعُ
    # بنموٍّ صفر، أي أن الشيفرةَ تفترض في السطر الأوّل أن الاحتجاز يُثمر
    # وتفترض في الثاني أنه يتبخّر.
    # وقياسُ الفرق بين افتراضين متناقضين ليس «اختلافَ مناهج» يُحتَرم — بل
    # خطؤنا نحن، معروضاً على المالك امتناعاً عن التسعير.
    # فصارا مساراً واحداً بنموٍّ واحدٍ مشتقٍّ من الاحتجاز. والصيغةُ الدفترية
    # هي المعروضة لأنها أثبت (الدفتريةُ أقلُّ تقلّباً من توزيعِ سنةٍ بعينها).
    if bvps and bvps > 0 and roe is not None and r > g:
        # ══ العائدُ لا يدوم — نموذجُ الدخل المتبقّي بتلاشٍ ══
        # كانت الصيغةُ ‏(ROE−g)÷(r−g) تفترض بقاءَ العائد الحاليّ **إلى
        # الأبد**. وهو أشدُّ افتراضٍ تفاؤلاً في التقييم: العوائدُ ترتدّ إلى
        # الوسط، والمنافسةُ تأكل الفائض، فتتآكل عوائدُ الشركات المرتفعة نحو
        # كلفة رأس المال خلال خمسٍ إلى عشر سنوات. (‏قِيس على الحالة (أ):
        # 42.91 بدل 21.74 — انتفاخٌ ‎97٪.)
        # فالقيمة = الدفترية + مجموعُ الدخل المتبقّي المخصوم، والعائدُ
        # يتلاشى خطّياً من الحاليّ إلى ‎r+2٪ في عشر سنوات ثم يستقرّ — فلا
        # فائضَ بعدها يُخصم إلى الأبد.
        # ══ هدفُ التلاشي دالّةٌ في ميزةٍ مُثبَتة لا ثابتٌ للجميع ══
        # كان الهدفُ ‎r+2٪ لكل شركة — أي أن **كلَّ** شركةٍ تفقد ميزتها كاملةً
        # في عشر سنوات. وذلك صحيحٌ للمتوسّط وخاطئٌ للاستثناء، والاستثناءُ هو
        # ما نبحث عنه. وقِيست الحساسية: الهدفُ وحده ينقل المضاعف من ‎1.61
        # إلى ‎2.14 — أثرٌ أكبر من نقطتين في معدّل الخصم.
        # فالميزةُ تُثبَت بالسجلّ: عائدٌ يفوق المطلوبَ بخمس نقاطٍ خمسَ سنواتٍ
        # متتالية خندقٌ ضيّق، وعشرَ سنواتٍ خندقٌ واسع — وهو إطارُ الخنادق
        # المعتاد. ومن لا سجلَّ له يبقى على الافتراض المتحفّظ.
        # خمسَ عشرةَ سنةً لعامّة الشركات: عشرٌ أقصر من عمر ميزةٍ حقيقية،
        # وهو ما كان يسحق التقنية.
        # ══ والبنوك أقصر ══
        # قِيس على السوق: وسيطُ القيمة÷السعر للبنوك ‎1.489 — أي أن المحرّك
        # يقول عن البنك الوسطى إنها أرخصُ من قيمتها ‎49٪، وذلك انتفاخٌ لا
        # فرصة. وسببُه أن فائضَ عائد البنك يُخصم خمسَ عشرةَ سنة، والبنكُ
        # مؤسّسةٌ مرفوعةُ الرافعة منظَّمةٌ في سوقٍ مفتوح: فائضُها يتآكل
        # أسرعَ من فائض صاحبة العلامة أو الشبكة.
        FADE_YEARS = 10 if archetype in ("bank", "financial") else 15
        roe0 = roe / 100.0
        streak = 0
        for p_ in reversed(periods or []):
            ni, eq = p_.get("net_income"), _eq_of(p_)
            if not (isinstance(ni, (int, float)) and isinstance(eq, (int, float)) and eq > 0):
                break
            if ni / eq >= r + 0.05:
                streak += 1
            else:
                break
        # ══ مُعايَرٌ بالقياس لا بالرأي ══
        # قِيس على السوق كلِّه بعد شدّ القيود: وسيطُ القيمة÷السعر خرج
        # ‎0.761 والمرجَّحُ بالقيمة السوقية ‎0.653 — أي أن المحرّك صار يقول
        # عن الشركة الوسطى إنها أغلى من قيمتها ‎24٪، و«شراء قوي» صفر.
        # والهدفُ المعلَن ‎0.95–1.10. وأشدُّ القيود أثراً هدفُ التلاشي
        # (‏r+2٪ ينقل المضاعف من ‎1.61 إلى ‎2.14 عند r+6٪)، فرُفع درجةً:
        # ‎r+4٪ بلا دليلِ ميزة، و‎r+6٪ لخمس سنواتٍ متتالية، و‎r+8٪ لعشر.
        # وأرضيةُ العلاوة من ‎5.0٪ إلى ‎4.5٪. والاتّجاهُ متحفّظٌ عمداً: أن
        # نقف دون الواحد خيرٌ من أن نتجاوزه.
        spread = 0.08 if streak >= 10 else 0.06 if streak >= 5 else 0.04
        # ══ التلاشي نزولٌ لا صعود ══
        # كان الهدفُ يُستوفى مباشرةً، فشركةٌ عائدُها ‎6٪ تُنمذَج على أنها
        # **تتحسّن** إلى ‎13.5٪ خلال الأفق — تحسّنٌ مختلَق لا تلاشٍ. وظهر
        # أثرُه في المرافق (‏1.27 من قياسنا، و‎1.26 من إعادة حسابه — تطابقٌ
        # يشخّص العطب لا يصادفه). فالهدفُ لا يتجاوز العائدَ الحاليّ.
        roe_end = min(roe / 100.0, r + spread)
        bv, pv_ri = bvps, 0.0
        for t in range(1, FADE_YEARS + 1):
            roe_t = roe0 + (roe_end - roe0) * (t / FADE_YEARS)
            ri = (roe_t - r) * bv
            pv_ri += ri / ((1 + r) ** t)
            # ══ الدفتريةُ تتدحرج بالاحتجاز الفعليّ ══
            # كانت تتدحرج بـ`g` المسقوف عند ‎3٪ — وذلك قيدٌ مزدوج: السقفُ
            # وُضع لأن مقام جوردون ينفجر، ولا انفجارَ في نموذجٍ صريحٍ لعشر
            # سنوات. وأثرُه مقيس: دفتريةُ السنة العاشرة تخرج ‎13.4 بدل ‎18.9،
            # أي أن أرباحاً محتجزةً حقيقية **تتبخّر من الميزانية** فتُنقص
            # القيمة ‎7٪ بلا سبب.
            b_ret = retention if retention is not None else 0.0
            bv *= (1 + max(0.0, roe_t) * b_ret)
        # القيمة النهائية: فائضٌ ثابتٌ صغير يُخصم أبديّاً بلا نموّ.
        pv_ri += ((roe_end - r) * bv / r) / ((1 + r) ** FADE_YEARS)
        v_raw = bvps + pv_ri
        # ══ قيدٌ رياضيّ لا يُخترق ══
        # إن كان العائدُ دون المطلوب فالشركةُ تُدمّر قيمةً، فمضاعفُ دفتريتها
        # أقلُّ من واحدٍ حتماً — ولا يجوز أن يخرج تقديرُها فوق دفتريتها.
        if roe0 < r:
            v_raw = min(v_raw, bvps)
        v_raw = min(v_raw, bvps * MAX_JUSTIFIED_PB)
        v = _sane(v_raw, price) if v_raw > 0 else None
        if v:
            bits = (f"دفترية السهم {bvps:.2f} + دخلٌ متبقٍّ مخصوم "
                    f"(عائد حقوق {roe:.1f}% يتلاشى إلى {roe_end * 100:.1f}% "
                    f"في {FADE_YEARS} سنة · مطلوب {r * 100:.1f}%)")
            if retention is not None:
                bits += f" · احتجاز {retention * 100:.0f}%"
            out["methods"].append({
                "name": "نموٌّ دائم (دفترية وتوزيع)",
                "value": v,
                "inputs": bits,
            })

    # ── ٣) العائدُ التوزيعيّ المرسمَل — عدسةُ الصندوق العقاريّ الأولى ────
    # الصندوقُ العقاريّ يُشترى بدخله لا بأرباحه المحاسبية: نظامُه يُلزمه
    # توزيعَ تسعين بالمئة من صافي دخله، فالتوزيعُ هو المُخرَج الاقتصاديّ
    # كاملاً تقريباً، والربحُ والتدفّقُ مشوّهان بالإهلاك وإعادة التقييم.
    # وطريقةُ السوق العقاريّ لتقييم دخلٍ كهذا هي الرسملة: القيمة =
    # التوزيع ÷ معدّل الرسملة، ومعدّلُ الرسملة هو العائدُ المطلوب ناقصَ
    # نموِّ الإيجارات. وكانت المواصفةُ تنصّ عليه ولم يكن في الشيفرة، فكان
    # الريتُ يُقاس بعدستين لا تخصّانه.
    if archetype == "reit" and dps and dps > 0:
        g_rent = min(g, 0.02)          # نموُّ إيجارٍ متحفّظ لا نموُّ أرباح
        cap = r - g_rent
        if cap > 0.02:
            v = _sane(dps / cap, price)
            if v:
                out["methods"].append({
                    "name": "عائدٌ توزيعيّ مرسمَل",
                    "value": v,
                    "inputs": (f"توزيع السهم {dps:.2f} ÷ معدّل رسملة "
                               f"{cap * 100:.1f}% (مطلوب {r * 100:.1f}% − "
                               f"نموّ إيجار {g_rent * 100:.1f}%)"),
                })

    # ── ٤) إجماع أهداف المحللين — **حُذف من مسارات القيمة** ─────────────
    # كان مساراً رابعاً يدخل في حساب القيمة. وثلاثةُ أسباب تُخرجه:
    #
    # ١) **يناقض مبدأ هذا الملفّ نفسه**، المكتوب في صدره: هدفُ سعرٍ
    #    لاثني عشر شهراً ليس تقديرَ قيمةٍ جوهرية. فكان الملفّ ينهى عنه
    #    في أعلاه ويستعمله في أسفله.
    # ٢) **يستورد السعر السوقيّ إلى التقدير**: المحلّلون يضعون أهدافهم
    #    منسوبةً إلى السعر القائم، فإدخالُها يجعل التقييمَ يقيس السوقَ
    #    بنفسه — وهو نقيضُ ما وُجد له.
    # ٣) **ازدواجُ الاحتساب**: إجماعُ المحللين محتسَبٌ أصلاً في درجة
    #    الحوكمة (‏v_analyst_upside)، فيدخل الإشارةُ الواحدة مرّتين.
    #
    # وأثرُه قِيس على حالةٍ عرضها المالك («سلوشنز»): بوجوده القيمةُ
    # 217.05 والسعرُ 206.90 فيُقرأ «عادل»، وبحذفه القيمةُ 180.60 فيُقرأ
    # «أعلى من قيمته بـ12.7٪». الحكمُ ينقلب — على رأيٍ لا حساب.
    #
    # ورأيُ المحللين لا يضيع: يبقى في ميزان الخبراء حيث موضعُه، ويبقى
    # «تقدير المحللين» رقماً في البيانات المالية.

    # عمرُ المدخلات: فوق خمسة وأربعين يوماً يعني أن قائمةً ربعية جديدة
    # ربما صدرت ولم تصل بعد — فيُوسَم التقدير «قديم» ولا يُحذف.
    # ══ والعمرُ عمرُ **القوائم** لا عمرُ الجلب ══ (D380)
    #
    # قِيس على خادم المالك: 8010 خرجت بقيمةٍ 30.34 مقابل سعرٍ 92.05،
    # ومدخلاتُها فتراتُ **2020 · 2021 · 2022**، والسطرُ يقول «العمر:
    # 2026-09-16 · شائخ=False». أي أن تقديراً على أرقامٍ عمرُها أربعُ
    # سنواتٍ عُرِض **طازجاً**: لا وسمَ قِدَمٍ، ولا هامشَ أمانٍ موسَّعاً،
    # ولا تحذيرَ. والسببُ أن `asof` تاريخُ **آخر جلبٍ للأساسيات** —
    # وهو يتجدّد كلَّ ليلةٍ وإن لم تُصدِر الشركةُ قائمةً منذ سنوات.
    #
    # فالعمرُ يُحسَب من **أحدثِ فترةٍ ماليةٍ استُعملت فعلاً**، وتاريخُ
    # الجلب يبقى معروضاً باسمه لا مكانَ العمر. وهذا يمسّ 54 ورقةً في
    # السوق الرئيسيّ (25 تأميناً · 6 ريتات · 23 متفرّقة) كانت كلُّها
    # تُعرَض «غيرَ شائخة».
    _per_dates = [str(p.get("as_of") or "")
                  for p in (periods or []) if p.get("as_of")]
    _newest = max(_per_dates) if _per_dates else None
    # ══ وعمرُ الأرقام من أحدثِ إفصاحٍ لا من أحدثِ سنةٍ مستعمَلة ══ (D412)
    # قِيس: ‎25 من ‎30 ورقةً تملك ربعيّاً أحدثَ من سنويّها — وسيطُ
    # المستعمَل ‎266 يوماً ووسيطُ المتاح ‎85. فالسلسلةُ السنويةُ تبقى
    # للنماذج (‏لا يُخلط أساسان في نموٍّ مركّب)، لكنّ **متى آخرُ ما
    # أفصحت عنه الشركة** يُقرأ من أحدثِ ربعٍ منشور. فكنّا نَصِمُ السوقَ
    # بالشيخوخة بحقٍّ والعلّةُ عندنا: أرقامٌ نملك أحدثَ منها ولا نقرؤه.
    _lq_asof = str((latest_quarter or {}).get("as_of") or "")[:10] or None
    if _lq_asof and (not _newest or _lq_asof > _newest):
        _newest = _lq_asof
        out["asof_from_quarter"] = True
    _basis = _newest or asof
    out["fetched_at"] = asof
    out["data_asof"] = _newest
    if _basis:
        try:
            from datetime import date
            age = (date.today() - date.fromisoformat(_basis[:10])).days
            out["age_days"] = age
            # ══ الشيخوخةُ تُقاس بدورة الإفصاح لا بالتقويم ══ (D409)
            # كان الحدُّ ‎45 يوماً، فوُسمت **268 من 270** ورقةً بالشيخوخة.
            # وقِيس على المصدر: أحدثُ ملفّات ‎1010 بتاريخ ‎2026-08-24
            # وفترتُها تنتهي ‎2026-06-30 — أي ‎84 يوماً، **وهي في أوان
            # إفصاحها**. فشركةٌ تُفصح ربعياً يستحيل أن تكون أرقامُها
            # أحدثَ من ذلك: الربعُ يُقفل ثمّ يُمهَل للنشر نحوَ شهرَين،
            # ثمّ تمضي ثلاثةُ أشهرَ حتى الربع التالي.
            # فالحدُّ ‎45 كان يَصِمُ السليمَ بالشيخوخة، فيخفض ثقتَه،
            # فيوسّع هامشَ أمانه، فيرفع **سعرَ دخول المالك ظلماً** —
            # إنذارٌ كاذبٌ على نطاق السوق كلِّه، وأسوأُ من الصمت لأنه
            # يُفقد الإنذارَ الصادقَ معناه.
            #
            # والحدُّ الصادق: ربعٌ (‏92) + مهلةُ نشرٍ (‏45) = ‎137 يوماً.
            # فما تجاوزه **تأخّرَ عن دورته** فعلاً — كـ‎2300 (‏2025-11-17)
            # و‎7204 (‏2024-05-28) في العيّنة المقيسة.
            out["stale"] = age > STALE_AFTER_DAYS
            out["stale_basis"] = (
                f"ربعٌ ({_Q_DAYS}) + مهلةُ نشرٍ ({_FILE_DAYS}) "
                f"= {STALE_AFTER_DAYS} يوماً")
            out["age_basis"] = ("أحدثُ فترةٍ ماليةٍ مستعملة" if _newest
                                else "تاريخُ جلب الأساسيات")
        except Exception:                                         # noqa: BLE001
            pass

    # ══ والخاسرةُ تُقيَّم بأصولها لا بأرباحها ══ (D401)
    #
    # قِيس بعيّنةِ كلّ قطاعٍ: الثمانيةُ الممتنعون **كلُّهم خاسرون** —
    # ربحيةُ السهم سالبةٌ (‏-0.36 إلى -4.82) وعائدُ الحقوق سالبٌ (‏-5.5
    # إلى -296.7) ولا توزيعَ إلا لواحد. فامتناعُ المحرّك صوابٌ في
    # المبدأ: لا تُقيَّم خاسرةٌ بمضاعفِ ربحيةٍ ولا بعائدٍ على حقوقٍ سالب.
    #
    # لكنّ الامتناعَ **ليس جواباً مهنياً**: المحلّلُ يقيّم الخاسرةَ
    # بأصولها — صافي أصولها للسهم — ويعلن أنها مُقاسةٌ بالأصول لا
    # بالأرباح. وهو معيارٌ قائمٌ في المواصفة أصلاً (‏`NAV_FACTOR`:
    # الريتُ 1.00 والمطوّرُ العقاريُّ 0.85 لأن أرضَه بالتكلفة التاريخية).
    #
    # ولا يُخترَع خصمٌ من عندي لغير المدرَجَين: المعامِلُ الافتراضيُّ
    # واحدٌ — أي **الدفتريةُ كما هي** — والثقةُ منخفضةٌ حتماً فيوسَّع
    # هامشُ الأمان. وشرطُه دفتريةٌ **اجتازت بوّابةَ المعقولية** (‏D392)،
    # فلا يُبنى على رقمٍ مرفوض.
    if not out["methods"] and bvps and bvps > 0:
        try:
            from app.data.archetype_spec import NAV_FACTOR as _NAVF
        except Exception:                                         # noqa: BLE001
            _NAVF = {}
        _f = float(_NAVF.get(archetype or "", 1.0) or 1.0)
        _nav = round(bvps * _f, 2)
        _loss = (eps is not None and eps < 0) or (roe is not None and roe < 0)
        out["methods"].append({
            "name": "صافي الأصول للسهم",
            "value": _nav,
            "inputs": (f"دفترية السهم {bvps:,.2f}"
                       + (f" × معامل {_f:.2f}" if _f != 1.0 else "")
                       + (" — شركةٌ خاسرةٌ فتُقاس بأصولها لا بأرباحها"
                          if _loss else
                          " — لا مسارَ أرباحٍ متاحٌ فتُقاس بأصولها")),
        })
        out["asset_based"] = True
        out["asset_based_note"] = (
            "قُيِّمت بصافي أصولها للسهم: "
            + ("ربحيتُها سالبةٌ فلا يصحّ فيها مضاعفُ ربحيةٍ ولا عائدٌ"
               " على حقوق" if _loss else
               "لم يتوفّر مسارُ أرباحٍ أو توزيعٍ مستقرّ")
            + " — والثقةُ منخفضةٌ فيوسَّع هامشُ الأمان.")

    vals = [m["value"] for m in out["methods"]]
    if not vals:
        out["unavailable_reason"] = (
            "لا تكفي البيانات المالية المتاحة لحساب قيمةٍ عادلة "
            "(يلزم ربحية سهمٍ مع مضاعف قطاع، أو دفترية مع عائد حقوق، "
            "أو توزيعٌ مستقرّ)."
        )
        return out

    # الوسيط يبقى للتلخيص، لكن وجودَ الخصم يُذكر صراحةً: تقديرٌ يقوم على
    # المضاعفات وحدها ليس كتقديرٍ يسنده نموذجُ خصمٍ من قوائم الشركة.
    out["has_dcf"] = any(m["name"] == "التدفّق النقدي المخصوم"
                         for m in out["methods"])
    # ══ بيانُ المصدر ══ (بأمر المالك: جودةٌ استثمارية)
    # لا يكفي أن يكون الرقم صحيحاً — يجب أن يكون **قابلاً للوزن**. فيُعاد
    # مع كل تقدير: عدد سنوات القوائم التي بُني عليها، وعدد أقران القطاع،
    # ومصدر الأساسيات. مستثمرٌ يعرف هذه الثلاثة يعرف كم يثق بالرقم.
    out["provenance"] = {
        "سنوات القوائم": len(periods or []),
        "أقران القطاع": peer_count,
        "مصدر الأساسيات": "ياهو",
        "تاريخ الأساسيات": asof,
    }
    # ══ نماذجُ آفاقٍ مختلفة لا تُجمع بوسيطٍ أعمى ══
    # (بأمر المالك: قراءةٌ استثمارية صحيحة)
    #
    # عرض المالك حالةً حقيقية: أربعةُ مسارات بين 35.56 و93.63 — ‏2.63×
    # بين أعلاها وأدناها. الخصمُ يقول إن السهم قريبٌ من قيمته (+6٪ عن
    # السعر)، والوسيطُ يقول إنه مبالغٌ فيه ‏42٪. فرقٌ يقلب القرار.
    #
    # والسبب ليس خطأً في مسارٍ منها — كلٌّ صحيحٌ في ذاته — بل **اختلافُ
    # الأفق**:
    #   • خصمُ التدفّقات يمنح الشركة خمسَ سنواتِ نموٍّ من تاريخها (حتى
    #     ‏12٪) قبل أن تستقرّ عند ‏2.5٪ دائماً.
    #   • أمّا مضاعفُ الدفترية المبرَّر وخصمُ التوزيعات فنماذجُ نموٍّ
    #     **دائم**: تفترض معدّلاً واحداً إلى الأبد، مسقوفاً عند ‏4٪
    #     لأن الدوام يمنع أكثر.
    # فالشركةُ النامية تخرج من الأوّل أعلى ومن الآخرَين أدنى — حتماً، لا
    # صدفةً. وجمعُها بوسيطٍ يسوّي بين أفقين مختلفين ويُنتج رقماً لا يمثّل
    # أيّاً منهما.
    #
    # والعلاج: تُجمع نماذجُ النموّ الدائم في صوتٍ واحد (فهي من طبيعةٍ
    # واحدة)، ويُرجَّح النموذجُ متعدّد المراحل عليها لأنه يقرأ تاريخ
    # الشركة لا يفترض ثباتها، ويبقى مضاعفُ القطاع صوتاً أصغر لأنه يقيس
    # ما يدفعه السوق للنظائر لا ما تستحقّه الشركة. والأوزان **مُعلَنة**
    # في المخرَج لا مخفيّة.
    #
    # والوسيطُ يبقى حارساً: بلا نموذجٍ متعدّد المراحل يعود التلخيصُ
    # وسيطاً كما كان — لا يُرجَّح ما لا أصل له.
    # ══ الأنماطُ المالية لها عدستُها الأولى ══
    # كان الترجيحُ مشروطاً بوجود النموذج متعدّد المراحل، والبنكُ والتأمين
    # والريت لا خصمَ تدفّقٍ لها أصلاً (‏D039) — فتسقط جميعاً إلى **الوسيط
    # الأعمى** الذي أدانه هذا الملفّ نفسه. ولهذا خرج «الراجحي» بمدى
    # 59.60–127.00 و«الأهلي» بـ20.37–96.27 في مسح السوق: قطاعٌ كامل
    # يُلخَّص بالطريقة التي مُنع غيرُه منها.
    # وعدسةُ البنك الأولى في التقييم المصرفيّ المعتاد هي **مضاعف الدفترية
    # المبرَّر** — العائدُ على حقوق الملكية مقابل كلفته — ثم خصمُ
    # التوزيعات (والبنوكُ موزِّعةٌ ناضجة فله وزنٌ حقيقيّ)، ويبقى مضاعفُ
    # القطاع أصغرَها لأنه يقيس ما يدفعه السوق للنظائر لا ما تستحقّه هي.
    _PB, _PE = "نموٌّ دائم (دفترية وتوزيع)", "مضاعف الربحية العادل"
    by_name = {m["name"]: m["value"] for m in out["methods"]}
    buckets: dict[str, float] = {}
    _CAP = "عائدٌ توزيعيّ مرسمَل"
    if archetype == "reit":
        # ══ الريتُ يُرجَّح بدخله ══
        # عدستُه الأولى الرسملة، ثم الدخلُ المتبقّي على صافي الأصول، ثم
        # مضاعفُ الربحية أصغرَها لأن ربح الريت المحاسبيّ أضعفُ ما فيه.
        WEIGHTS = {_CAP: 0.55, _PB: 0.25, _PE: 0.20}
        for k in (_CAP, _PB, _PE):
            if k in by_name:
                buckets[k] = by_name[k]
        primary = _CAP if _CAP in by_name else _PB
    elif archetype in NO_DCF:
        # ══ ترجيحٌ متكافئ للبنك والتأمين والتمويل ══
        # كان ‎65/35 لمضاعف الدفترية المبرَّر، وهو مسارُ الدخل المتبقّي
        # نفسُه الذي قِيس منتفخاً في البنوك (‎1.489). فإسنادُ ثلثي الوزن
        # إلى أضعف الشاهدَين مضاعفةٌ للانحياز، ومضاعفُ الربحية شاهدٌ
        # سوقيٌّ يكذّبه. فتكافآ.
        WEIGHTS = {_PB: 0.50, _PE: 0.50}
        for k in (_PB, _PE):
            if k in by_name:
                buckets[k] = by_name[k]
        primary = _PB
    else:
        WEIGHTS = {"متعدّد المراحل": 0.45, "نموّ دائم": 0.35, "مضاعف القطاع": 0.20}
        perpetual = [by_name[k] for k in (_PB,) if k in by_name]
        if "التدفّق النقدي المخصوم" in by_name:
            buckets["متعدّد المراحل"] = by_name["التدفّق النقدي المخصوم"]
        if perpetual:
            buckets["نموّ دائم"] = sum(perpetual) / len(perpetual)
        if _PE in by_name:
            buckets["مضاعف القطاع"] = by_name[_PE]
        primary = "متعدّد المراحل"

    # ══ تقديرٌ متضاربٌ ليس تقديراً ══
    # (وجده مسحُ السوق: ١٧٤ شركة من ٣٩٦ بتشتّتٍ ≥2×، وأحدها 11.2×)
    #
    # «١١٨٠» مثالٌ صريح: المسارات بين 20.37 و227.28. خصمُ التوزيعات يقول
    # عشرين لأن الشركة توزّع جزءاً من ربحها، ومضاعفُ الدفترية المبرَّر
    # يقول مئتين لأن عائدها على حقوق الملكية يفوق كلفةَ رأس المال. وكلٌّ
    # صحيحٌ في منطقه، ولا وسطَ بينهما يُمثّلهما — فمتوسّطُ الطرفين رقمٌ
    # لا يقول به أيُّ نموذج.
    #
    # وقد عالج الترجيحُ (‏D046) **الانحياز**، ولا يعالج **التضارب**: لا
    # وزنَ يجعل من رقمين متباعدين ثلاثةَ أضعافٍ رقماً واحداً موثوقاً.
    # فالصادقُ أن تُعلَن القيمةُ غيرَ متاحة ويبقى المدى معروضاً — كما
    # يمتنع محرّك الحوكمة حين لا تكفي البيانات. والامتناعُ حكمٌ لا فراغ.
    # ══ الشاهدُ الأضعف يُستبعد قبل الامتناع ══
    # بقيت أربعون شركةً ممتنعةً بعد علاج D062 و D063. ومضاعفُ القطاع هو
    # المسارُ الوحيدُ **غيرُ الجوهريّ** بينها: يقيس ما يدفعه السوق لنظائر
    # الشركة لا ما تستحقّه هي، ولذلك أعطي أدنى وزنٍ منذ البداية. فإن كان
    # هو الشاذَّ وحده — واتّفق المسارانِ الجوهريّان — فالامتناعُ عن التسعير
    # تنازلٌ عن معرفةٍ نملكها إرضاءً لشاهدٍ نعرف ضعفَه.
    # فيُستبعد من **حساب النقطة** ويبقى معروضاً في المسارات، ويُقال إنه
    # استُبعد. وما بقي تضاربُه بعد استبعاده يبقى ممتنعاً.
    if (len(vals) >= 3 and min(vals) > 0 and max(vals) / min(vals) >= 3.0
            and _PE in by_name):
        core = [m["value"] for m in out["methods"] if m["name"] != _PE]
        if len(core) >= 2 and min(core) > 0 and max(core) / min(core) < 3.0:
            # المدى يبقى محسوباً من **كل** المسارات: من حذف الخلاف ثم ضيّق
            # مداه كافأ نفسه على الحذف. ويُسجَّل الاستبعادُ ليخفض الثقة.
            out["_all_vals"] = list(vals)
            out["excluded_penalty"] = True
            vals = core
            buckets.pop("مضاعف القطاع", None)
            buckets.pop(_PE, None)
            out["excluded"] = (
                f"مضاعفُ القطاع ({by_name[_PE]}) خارجَ حساب النقطة: شذَّ عن "
                f"المسارات الجوهرية، وهو يقيس سعرَ النظائر لا قيمةَ الشركة.")

    # التحكيمُ قبل الامتناع — القاعدةُ في `arbitrate` لتُقاس وحدَها (D337)
    _b2, _v2, _why = arbitrate(buckets, vals)
    if _why:
        out["_all_vals"] = list(vals)
        out["excluded_penalty"] = True
        out["excluded"] = _why
        buckets, vals = _b2, _v2
        if primary not in buckets:
            primary = next(iter(buckets))

    # ══ والتضاربُ يُقارَب بأوزان الصنف — لا يُترك فراغاً ══ (D371)
    #
    # قال المالك: «نريد العملَ باحترافية: أن نسدّد ونقارب وجهاتِ النظر
    # وليس إبقاءَها فارغة — فأنا أحارب الفراغَ والبياناتِ غيرَ الكافية».
    # والاعتراضُ صائبٌ على ما كان هنا: كنتُ أمتنع عند خلافٍ ثلاثةِ أضعاف
    # بحجّة أن «متوسّطَ الطرفين رقمٌ لا يقول به أيُّ نموذج» — وهذا صحيحٌ
    # في المتوسّطِ الحِسابيّ، **وليس هو المقاربةَ المهنية**.
    #
    # فالمقاربةُ المهنيةُ أن يُحكَّم النموذجُ الذي يليق بصنفِ الورقة:
    # البنكُ يُقيَّم بالدخل المتبقّي ومضاعفِ الدفترية لا بتدفّقٍ حرٍّ
    # مخصوم، والريتُ برسملةِ عائده. وهذه الأوزانُ **مكتوبةٌ عندنا أصلاً**
    # في `VALUATION` بمواصفة الأنماط — فكان الخلافُ يُهدر قرارَ مواصفتنا
    # نفسِها ويخرج فراغاً.
    #
    # ولا يُشترى الرقمُ بكذب: التشتّتُ يُعلَن بمقداره، والمدى يبقى من
    # **كلّ** المسارات، والثقةُ تُحبَس على «منخفضة» — فتترجمها منظومةُ
    # هامش الأمان تلقائياً إلى ‎35% أي سعرِ دخولٍ أدنى. فالخلافُ يُسعَّر
    # ولا يُخفى. والامتناعُ يبقى لموضعه الصحيح: **غيابُ مدخلٍ**، لا
    # اختلافُ نموذجَين قائمَين.
    if len(vals) >= 2 and min(vals) > 0 and max(vals) / min(vals) >= 3.0:
        out["dispersion"] = round(max(vals) / min(vals), 2)
        out["_all_vals"] = list(vals)
        # ══ مصدرُ الأوزان واحدٌ: `WEIGHTS` أعلاه ══ (D405)
        # كان هنا `_spec` يُقرأ من `VALUATION` ثمّ **لا يُستعمل**: فرعان
        # متطابقان كلاهما يأخذ `WEIGHTS`. فالسلوكُ صحيحٌ — `WEIGHTS`
        # مفرَّعةٌ بالنمط فوقَه — لكنّ الدعوى كاذبةٌ وتُضلّل من يقرأ:
        # قارئٌ يحسب أنّ تعديلَ ملفّ المواصفة يغيّر الترجيح، ولا يغيّره.
        # فحُذف الميّت، والمواصفةُ تبقى **وثيقةَ الهيكلة** يجب أن تُطابق
        # ما هنا حرفاً — وحارسُها يقيس التطابق لا يأخذه تسليماً.
        _named = {k: v for k, v in buckets.items() if k in WEIGHTS}
        _w = {k: WEIGHTS[k] for k in _named} if _named else {}
        if _w:
            _s = sum(_w.values())
            out["value"] = round(
                sum(_named[k] * w for k, w in _w.items()) / _s, 2)
            out["weighting"] = {k: f"{w / _s * 100:.0f}%"
                                for k, w in _w.items()}
        else:
            out["value"] = round(median(vals), 2)
        out["reconciled"] = (
            f"مساراتُ التقدير متباعدةٌ {out['dispersion']}× — قُورِبت "
            f"بأوزان صنف الورقة لا بمتوسّطٍ حِسابيّ، والثقةُ منخفضةٌ "
            f"حتماً فيوسَّع هامشُ الأمان.")
        out["dispersion_demote"] = True

    # ولا يُحسَب الترجيحُ مرّتَين: المتضاربُ رُجِّح أعلاه بوسمه (D371)
    if out.get("dispersion_demote"):
        pass
    elif primary in buckets and len(buckets) > 1:
        wsum = sum(WEIGHTS[k] for k in buckets)
        out["value"] = round(sum(v * WEIGHTS[k] for k, v in buckets.items()) / wsum, 2)
        out["weighting"] = {k: f"{WEIGHTS[k] / wsum * 100:.0f}%" for k in buckets}
    else:
        out["value"] = round(median(vals), 2)
    # ══ قيدٌ رياضيّ يحكم النقطةَ لا مساراً واحداً ══
    # شركةٌ عائدُها دون المطلوب تُدمّر قيمةً، فلا يجوز أن يخرج تقديرُها فوق
    # دفتريتها مهما قال مضاعفُ القطاع. وكان المضاعفُ يرفعها فوق الدفترية
    # (‏الحالة (ج): 23.46 والسقف 20.00) لأن القيد كان داخل مسارٍ واحد.
    if (roe is not None and bvps and bvps > 0
            and roe / 100.0 < r and out.get("value")
            and out["value"] > bvps):
        out["value"] = round(bvps, 2)
        out["capped_at_book"] = True

    # ══ وأرضيةٌ من الأصول تقابل السقف ══ (D175)
    # كان القيدُ أعلاه سقفاً بلا أرضية، فينهار التقديرُ إلى الصفر متى
    # انضغطت الأرباح: قِيس على الخادم ‎0.07 ريالٍ لورقةٍ هدفُ محلّليها
    # ‎35، و‎0.56 لِـ‎23.50 — سبعٌ من أسوأ عشرٍ عند الصفر. والمساراتُ كلُّها
    # مدفوعةٌ بالأرباح أو التدفّق، فسنةٌ ضعيفةٌ تُصفّر النتيجة.
    #
    # وشركةٌ عاملةٌ حقوقُ ملكيتها موجبة لا تساوي جزءاً من مئةٍ من دفتريتها.
    # فأرضيةٌ عند **نصف** القيمة الدفترية: حدٌّ متحفّظ لا تقدير — لا يرفع
    # تقديراً معقولاً ولا يخترع قيمةً لمن حقوقُه سالبة.
    #
    # والأرضيةُ من الميزانية لا من السعر، فتبقى المسطرةُ مستقلّةً عن
    # السوق — وهو المبدأ الذي بُني عليه `_sane`.
    if (bvps and bvps > 0 and out.get("value")
            and out["value"] < bvps * BOOK_FLOOR_RATIO):
        out["floored_at_book"] = True
        out["floor_from"] = out["value"]
        out["value"] = round(bvps * BOOK_FLOOR_RATIO, 2)

    # ══ خصمُ سيولةٍ للسوق الموازية «نمو» ══
    # كشفه المسحُ الكامل: من ‎406 صفّاً ‎136 من «نمو» (رموزُها 9xxx)،
    # ووسيطُ القيمة÷السعر فيها ‎0.879 مقابل ‎0.738 للسوق الرئيسة — أي أن
    # المحرّك يراها أقربَ إلى قيمتها، وهو عكسُ الحقيقة: أسهمُ «نمو» رقيقةُ
    # التداول محدودةُ الإفصاح مقصورةٌ على المؤهَّلين، فبيعُ مركزٍ فيها قد
    # يتعذّر أصلاً. وقيمةٌ لا يمكن تسييلُها ليست قيمةً كاملة.
    # فيُخصم ثلاثون بالمئة من التقدير، ولا يُبنى عليه قرارُ شراء بحال —
    # لأن الخصم يعالج السعرَ ولا يعالج تعذّرَ الخروج.
    _base = (symbol or "").replace(".SR", "")
    from app.data.universe import is_nomu
    if is_nomu(_base):
        out["nomu"] = True
        if out.get("value"):
            out["value"] = round(out["value"] * 0.70, 2)
            out["liquidity_discount_pct"] = 30

    # ══ حدُّ العقل على المزيج لا على المسار وحده ══
    # كشفه فحصٌ خارجيّ: تسعةَ عشرَ صفّاً خرجت نسبتُها عن ‎0.40×–2.50× من
    # السعر **بعد** الترجيح، لأن الحدَّ كان يُفحص عند كلّ مسارٍ ثم يُجمع
    # الناجون. فمسارٌ عند ‎0.42 وآخرُ عند ‎0.38 يمرّ أوّلُهما ويُسقط الثاني،
    # ثم تخرج النقطةُ ‎0.42 وهي عند حافّة اللامعقول.
    if out.get("value") is not None and price:
        _r = out["value"] / price
        if not (SANE_LOW <= _r <= SANE_HIGH):
            # ══ الشذوذُ يُعلَن ولا يُمحى ══ (قرارُ مجلس نِصاب)
            # كان التقديرُ يُلغى ويُقال «بيانات غير كافية» — وذلك كذبٌ على
            # القارئ: نحن حسبناه ثم رفضناه، فالمعرفةُ موجودةٌ والادّعاءُ
            # أنها معدومة. وأسوأُ من ذلك أنه يقع **عند أعمق خصم**، أي
            # يصمت التطبيقُ في أوضح ما يكون فرصةً أو أوضح ما يكون فخّاً.
            # فصار الرقمُ يبقى معروضاً موسوماً بشذوذه، ولا يُبنى عليه
            # قرارُ شراء: يرى المستثمرُ ما حسبناه ويرى تحفّظَنا عليه.
            out["implausible"] = True
            out["confidence"] = "منخفضة"
            out["note"] = (
                f"التقديرُ ({out['value']:,.2f}) يعادل {_r:.2f}× السعرَ "
                f"القائم — خارج النطاق المعقول ({SANE_LOW:.2f}–"
                f"{SANE_HIGH:.2f}). فارقٌ بهذا الحجم مصدرُه غالباً خللٌ في "
                f"مُدخَلٍ لا فرصةٌ حقيقية، فلا يُبنى عليه قرار.")

    # ══ مسارٌ واحد ليس تقييماً ══
    # ‏١١٦ شركة أنتجت قيمةً وقراراً من مسارٍ واحد، ووسيطُ نسبتها ‎0.613
    # مقابل ‎0.960 لمسارين — فالمسارُ اليتيم هو مصدرُ الانحياز النزوليّ
    # الأكبر، ولا شاهدَ يكذّبه. فتُعرض قيمتُه ولا يُبنى عليها قرارُ شراء.
    out["single_path"] = len(vals) < 2

    _span = list(out.get("_all_vals") or vals)
    # ══ وقيمةٌ خارجَ مداها تناقضٌ ══ (D393)
    # قِيس: 2340 قيمتُه 6.58 ومداه 1.03–1.03 — لأن «أرضيةَ الأصول» ترفع
    # القيمةَ إلى نصف الدفترية بعد حساب المدى، فيبقى المدى على المسارات
    # وحدَها. والمدى عهدٌ للقارئ: القيمةُ داخلَه، فيُوسَّع ليشملها.
    if out.get("value") is not None:
        _span.append(out["value"])
    out["low"], out["high"] = round(min(_span), 2), round(max(_span), 2)
    out.pop("_all_vals", None)
    if price:
        out["upside_pct"] = round((out["value"] / price - 1) * 100, 1)
        # اتّساعُ التشتّت رسالةٌ في ذاته: مساراتٌ متباعدة تعني أن التقدير
        # ضعيف الثقة مهما بدا وسيطُه دقيقاً.
        spread = (out["high"] - out["low"]) / out["value"] if out["value"] else 0
        # ══ الثقةُ تنزل حين نحذف خلافاً أو نتّكئ على الأبدية ══
        # كان حذفُ المسار المخالف يضيّق التشتّت فيرفع الثقة فيقلّ هامشُ
        # الأمان فيرتفع سعرُ الدخول — آليّةٌ تكافئ على حذف الخلاف. وكذلك
        # نموذجٌ ثلاثةُ أرباع قيمته قيمةٌ نهائية ليس خصمَ خمس سنواتٍ بل
        # تخميناً للأبدية بقشرةٍ قصيرة.
        # والتقديرُ الشاذُّ النسبة ثقتُه منخفضةٌ حتماً: وُسم قبل هذا السطر
        # فكان يُدهس هنا — فالوسمُ يُكتب ثم يُطمس بحسابٍ يليه.
        if _ins_no_cr:
            # تحفّظٌ مُعلَنٌ ومُسعَّر: ربحُ المؤمِّن دالّةٌ في كفاية
            # الاحتياطيات، وبلا النسبة المجمّعة يبقى التقديرُ ضعيفَ الثقة.
            out["caveat"] = (
                "النسبةُ المجمّعة — جوهرُ اقتصاد شركة التأمين — لم تصلنا،"
                " فالتقديرُ قائمٌ على الدخل المتبقّي ومضاعفِ الدفترية"
                " وثقتُه منخفضةٌ ويُطلَب له هامشُ أمانٍ أوسع.")
        # ══ شروطُ الخطر المُعلَنة تُقرأ أخيراً ══ (D408)
        # كانت في الميثاق ولا يقرؤها محرّك. فتُقاس هنا، وتُعلَن بأسمائها،
        # وتُخفض الثقةَ — ولا تمنع التقدير. والخطرُ يُسعَّر في هامش
        # الأمان: ثقةٌ منخفضةٌ تعني سعرَ دخولٍ أدنى، وتلك ترجمتُه المفيدة.
        _rf, _rf_unmeasured, _rf_gaps = risk_flags(archetype, periods, info)
        if _rf_gaps:
            # فجوةُ بيانٍ تُعلَن باسمها: ليست خطراً يُدين الورقةَ ولا
            # شرطاً سليماً — حقلٌ لم يصلنا، وأثرُه خصمٌ مقدَّرٌ لا سقف.
            out["data_gaps"] = _rf_gaps
            out["data_gap_note"] = " · ".join(x["نصّ"] for x in _rf_gaps)
        if _rf:
            out["risk_flags"] = _rf
            out["risk_note"] = " · ".join(
                x["نصّ"] for x in _rf if x.get("نصّ"))
        if _rf_unmeasured:
            # شرطٌ لا تصله مدخلاتُه لا يُعَدّ سليماً: يُعلَن غيرَ مقيس
            # فلا تُقرأ الخضرةُ شهادةً.
            out["risk_unmeasured"] = _rf_unmeasured

        _demote = (bool(_rf)
                   # ومن تأخّر عن دورة إفصاحه يُكلّفه تأخّرُه (‏D409):
                   # كان الوسمُ يُطبع ولا يُغيّر ثقةً ولا هامشاً — وسمٌ
                   # بلا أثرٍ يُقرأ ويُنسى. والقرارُ يُبنى على الثقة.
                   or bool(out.get("stale"))
                   or bool(out.get("excluded_penalty"))
                   or bool(out.get("terminal_heavy"))
                   or bool(out.get("implausible"))
                   # خلافُ المسارات يُسعَّر ولا يُخفى: ثقتُه منخفضةٌ حتماً
                   # فيتّسع هامشُ الأمان إلى 35% (D371)
                   or bool(out.get("dispersion_demote"))
                   or bool(_ins_no_cr)
                   or bool(out.get("asset_based")))
        # ══ الثقةُ تُعايَر وتُبرَّر — والكلمةُ تُشتَقّ من الدرجة ══ (D411)
        # القرارُ الاستثماريُّ يقوم على الثقة لا على الرقم وحدَه، وكانت
        # تخرج **كلمةً** واحدةً بلا أن يعرف المالكُ لماذا ولا كم — فلا
        # يزن ثقةً بأخرى ولا يرى ما نقصها.
        #
        # وأوّلُ ما جرّبتُه كان عطباً بنفسه: درجةٌ تُحسب **بجانب** الكلمة
        # فتناقضها — ‎88/100 تُسمّى «متوسطة» و‎73 تُسمّى «منخفضة». رقمان
        # يختلفان على معنىً واحد، وهو ما يحاربه هذا الملفُّ كلُّه. فصارت
        # الكلمةُ **مشتقّةً من الدرجة** حتماً: مصدرٌ واحدٌ لا اثنان.
        #
        # والموانعُ الجوهريةُ **سقوفٌ** لا خصومات: مسارٌ واحدٌ، أو تباعدٌ
        # فوق النصف، أو تأخّرٌ عن دورة الإفصاح، أو شرطُ خطرٍ قائم — كلٌّ
        # منها يحبس الدرجةَ دون ‎50 مهما حسُن ما سواه. فلا تُشترى ثقةٌ
        # بتكديس محاسنَ فوق عيبٍ جوهريّ.
        _sc, _why, _cap = 100, [], 100

        def _cut(n: int, txt: str, cap: int | None = None) -> None:
            nonlocal _sc, _cap
            _sc -= n
            if cap is not None:
                _cap = min(_cap, cap)
            _why.append({"خصم": n, "السبب": txt,
                         **({"سقف": cap} if cap is not None else {})})

        _np = len(vals)
        if _np <= 1:
            _cut(25, "مسارُ تقديرٍ واحدٌ — لا شاهدَ يكذّبه أو يؤيّده", 49)
        elif _np == 2:
            _cut(12, "مساران فقط")
        if spread > 0.5:
            _cut(25, f"تباعدُ المسارات {spread * 100:.0f}٪", 49)
        elif spread > 0.25:
            _cut(12, f"تباعدُ المسارات {spread * 100:.0f}٪")
        _age = out.get("age_days") or 0
        if out.get("stale"):
            _cut(25, f"تأخّرٌ عن دورة الإفصاح — {_age} يوماً", 49)
        if _rf:
            _cut(min(30, 15 * len(_rf)),
                 "شروطُ خطرٍ قائمة: " + "، ".join(x["code"] for x in _rf), 49)
        if out.get("dispersion_demote"):
            _cut(20, f"مساراتٌ متعارضةٌ {out.get('dispersion')}× قُورِبت "
                     f"بالأوزان", 49)
        if out.get("asset_based"):
            _cut(20, "قُيِّمت بأصولها — لا ربحَ يُقاس عليه", 49)
        if _ins_no_cr:
            _cut(15, "النسبةُ المجمّعة غائبةٌ في مؤمِّن", 49)
        if out.get("implausible"):
            _cut(40, "التقديرُ خارج النطاق المعقول", 30)
        if _demote and _cap > 89:
            # ما يمنع «مرتفعة» دون أن يكون جوهرياً: يحبسها تحت عتبتها.
            _cut(10, "شاهدٌ محذوفٌ أو اتّكاءٌ على قيمةٍ نهائية", 89)
        if out.get("derived_inputs"):
            _cut(8, "مدخلاتٌ مشتقّةٌ لا منشورة")
        if out.get("data_gaps"):
            _cut(8, "فجوةُ بيانٍ: " + ("، ".join(
                x["code"] for x in out["data_gaps"])))
        if out.get("risk_unmeasured"):
            _cut(5, "شروطُ خطرٍ لم تصلها مدخلاتُها: "
                    + "، ".join(out["risk_unmeasured"]))

        out["confidence_score"] = max(0, min(_cap, _sc))
        out["confidence_why"] = _why
        out["confidence_scale"] = "مرتفعة ≥ 90 · متوسطة ≥ 50 · دونها منخفضة"
        out["confidence"] = ("مرتفعة" if out["confidence_score"] >= 90
                             else "متوسطة" if out["confidence_score"] >= 50
                             else "منخفضة")

        # ══ هامشُ الأمان — من تقديرٍ إلى قاعدةِ دخول ══ (بأمر المالك)
        # قال إنه يحدّد بها **وقت دخوله**. والقيمة العادلة وحدها لا تقول
        # ذلك: الشراء عندها يعني دفعَ كامل ما تستحقّه الشركة بشرط أن يكون
        # التقدير صائباً — وكلُّ تقييمٍ يخطئ.
        # وهامشُ الأمان (غراهام) هو الفرق المطلوب بين السعر والقيمة ليحتمل
        # التقديرُ خطأه. وهو هنا ليس رقماً ثابتاً بل **دالّةُ ثقة**: كلّما
        # اتّسع تشتّت المسارات أو قلّ عددها أو قدُمت أرقامها اتّسع الهامش
        # المطلوب. فالثقة المنخفضة تُترجَم إلى سعرٍ أدنى لا إلى تحذيرٍ
        # يُقرأ ويُنسى.
        mos = {"مرتفعة": 0.15, "متوسطة": 0.25}.get(out["confidence"], 0.35)
        if not out.get("has_dcf") and archetype not in NO_DCF:
            # مضاعفاتٌ بلا نموذج خصم: تقديرٌ نسبيّ يقيس ما يدفعه السوق
            # للنظائر، فيُطلب له هامشٌ أوسع.
            # ولا يُعاقَب النمطُ الذي لا يصحّ فيه الخصمُ أصلاً: غيابُ
            # النموذج فيه صوابٌ منهجيّ لا نقصُ بيانات، وتوسيعُ الهامش
            # عليه يرفع سعرَ دخول قطاعٍ كامل بلا سبب.
            mos += 0.05
        if (out.get("age_days") or 0) > 180:
            mos += 0.05                      # أرقامٌ تجاوزت نصف عام
        mos = min(mos, 0.45)
        out["margin_of_safety_pct"] = round(mos * 100)
        out["entry_price"] = round(out["value"] * (1 - mos), 2)
        out["entry_gap_pct"] = round((out["entry_price"] / price - 1) * 100, 1)
        # حكمٌ في كلمتين لا جملةٌ تشرح نفسها (بأمر المالك).
        out["entry_verdict"] = (
            "دون سعر الدخول" if price <= out["entry_price"] else
            "بلا هامش أمان" if price < out["value"] else
            "فوق القيمة العادلة")
    out["dropped_paths"] = _DROPPED["n"]
    _log_run(symbol, out, price, r, g)
    return out
