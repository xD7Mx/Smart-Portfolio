def _fcf_series(periods: list[dict]) -> list[float]:
    """سلسلةُ التدفّق النقدي الحرّ من الأقدم إلى الأحدث.

    ويُشتقّ عند غيابه من (تشغيليّ + رأسماليّ): المصروف الرأسماليّ يُبلَّغ
    سالباً، فالجمع طرحٌ. ولا يُقبل مسارٌ ببندٍ واحد — سنةٌ واحدة لا تُنتج
    نموّاً ولا اتجاهاً.
    """
    out = []
    for p in periods or []:
        f = p.get("free_cash_flow")
        if f is None:
            ocf, capex = p.get("operating_cash_flow"), p.get("capex")
            f = (ocf + capex) if (ocf is not None and capex is not None) else None
        if isinstance(f, (int, float)):
            out.append(float(f))
    return out


def _dcf(periods: list[dict], info: dict, price: float | None,
         r: float, cyclical: bool = False,
         roe_for_reinv: float | None = None) -> dict | None:
    """قيمةُ السهم بخصم تدفّقاته الحرّة — نموذجُ مرحلتين.

    هذا هو المعيار الذي تُبنى عليه التقييمات المهنية: قيمةُ الشركة هي ما
    تُنتجه من نقدٍ حرٍّ مستقبلاً، مخصوماً إلى اليوم بمعدّلٍ يعكس مخاطرها.
    وما سواه من مضاعفاتٍ يقيس **ما يدفعه السوق للنظائر** لا ما تستحقّه
    الشركة في ذاتها.

    ولماذا مرحلتان: نموٌّ صريحٌ خمسَ سنوات من واقع تاريخ الشركة، ثم نموٌّ
    دائمٌ متواضع. ونموٌّ واحدٌ إلى الأبد افتراضٌ لا يصحّ لأي شركة.

    والقيود المفروضة هنا ليست تزيّداً — كلٌّ منها يمنع رقماً كاذباً:
      • تدفّقٌ حرٌّ سالب في آخر سنة ⇒ لا نموذج. شركةٌ تحرق النقد لا تُقيَّم
        بخصم تدفّقاته؛ ورقمٌ من خصم سالبٍ عبثٌ يُقرأ قيمةً.
      • نموُّ التاريخ يُقصّ في [0٪ , 12٪]. تاريخٌ استثنائيّ لا يُمدّ خمس
        سنواتٍ بلا سقف، وسالبُه لا يُخصم إلى الأبد.
      • النموّ الدائم دون معدّل الخصم بهامشٍ واضح، وإلا انفجر المقام.
      • صافي الدين يُطرح والنقد يُضاف: القيمة المخصومة قيمةُ **المنشأة**،
        وحاملُ السهم يملك ما يبقى بعد الدائن.
    """
    fcfs = _fcf_series(periods)
    if len(fcfs) < 2:
        return None
    base = fcfs[-1]
    if base <= 0:
        return None

    # ══ تسويةُ الدورة ══ (بأمر المالك: جودةٌ استثمارية)
    # ‏١٥٧ شركة في السوق دوريّة — أربعون بالمئة منه. وأخطرُ خطأٍ في تقييم
    # الدوريّ هو بناءُ التقدير على سنةٍ واحدة: فيُقيَّم في القمّة بأرباح
    # القمّة فيبدو رخيصاً وهو في ذروته، ويُقيَّم في القاع بأرباح القاع
    # فيبدو غالياً وهو في أرخص أوقاته. وهذا يقلب الأداة على صاحبها: تدفعه
    # إلى الشراء حيث يجب أن يبيع.
    # والعلاج المتّبع منذ غراهام: **تسويةُ الأساس إلى متوسّط الدورة** بدل
    # آخر سنة (وهي فكرة CAPE نفسها). والمتاح هنا ثلاثُ سنواتٍ إلى خمس، وهي
    # أقصرُ من دورةٍ كاملة — فيُقال ذلك ولا يُدّعى غيره.
    cycle_note = ""
    if cyclical and len(fcfs) >= 3:
        # ══ الدورةُ تشمل سنة الخسارة ══
        # كان المتوسّط على السنوات الموجبة وحدها — وذلك تجميلٌ لا تطبيع:
        # على دورةٍ واقعية (6.5 · 4.0 · 0.2 · −1.0 · 3.8) يُخرج 3.62 بدل
        # 2.70، أي انحيازٌ صعوديّ 34٪ في الأساس يتضاعف في القيمة.
        pos = [f for f in fcfs if f > 0]
        if len(pos) >= 3:
            norm = sum(fcfs) / len(fcfs)
            if norm <= 0:
                return None
            # لا تُرفع الأساسُ فوق آخر سنة إلا بحدّ: تسويةٌ ترفع القيمة
            # لشركةٍ في قاعٍ حقيقيّ مقبولة، أمّا مضاعفتُها فمراهنةٌ على
            # انقلاب الدورة لا تقييم.
            norm = min(norm, base * 1.5)
            cycle_note = (f" · أساسٌ مسوّىً على متوسّط {len(pos)} سنوات "
                          f"(كان {base / 1e6:,.0f}م)")
            base = norm
    shares = None
    for p in reversed(periods or []):
        # ══ عددٌ يخالف ربحيةَ السهم لا يُقسَم عليه ══ (D347)
        # قِيس على خادم المالك بعد D339: مدى ‎2290 صار **0.04–0.14** ريالاً،
        # وهي في قائمة «فرقُ عددٍ أُعلِن». فقد أبقيتُ المنشورَ وسمّيتُ
        # الفرقَ — وذلك صوابٌ (لا يُستبدَل منشورٌ بمشتقّ) — لكنّي تركتُ
        # المحرّكَ **يقسم عليه** فخرج سعرُ سهمٍ بأربعِ هللات. فالتسميةُ
        # وحدَها لا تكفي: رقمٌ للسهم مبنيٌّ على عددٍ يخالف تعريفَ ربحية
        # السهم اختلاقٌ، والامتناعُ المعلَنُ أصدقُ منه. فتُتخطّى الفترةُ
        # الموسومةُ إلى فترةٍ متوافقة، وإن لم تكن فلا قيمةَ — ويُعلَن.
        if p.get("shares_mismatch") or p.get("shares_unit_gap"):
            continue
        if isinstance(p.get("shares_outstanding"), (int, float)) and p["shares_outstanding"] > 0:
            shares = float(p["shares_outstanding"])
            break
    if not shares:
        return None

    # نموُّ التاريخ: معدّلٌ مركّبٌ بين أوّل سلسلةٍ موجبة وآخرها.
    # النموّ يُقاس من السلسلة الأصلية لا من الأساس المسوّى: الأساس المسوّى
    # متوسّطُ دورةٍ، ونسبتُه إلى أوّل السلسلة ليست نموّاً.
    first = next((f for f in fcfs if f > 0), None)
    n = len(fcfs) - 1
    if first and n >= 1:
        g1 = (fcfs[-1] / first) ** (1 / n) - 1
    else:
        g1 = 0.0
    g1 = max(0.0, min(g1, 0.12))
    # وعلى أساسٍ مسوّىً لا يُضاف نموٌّ مرتفع: المتوسّط يفترض عودةً إلى
    # الوسط، وإضافةُ نموّ القمّة فوقه احتسابٌ للشيء مرّتين.
    if cycle_note:
        g1 = min(g1, TERMINAL_GROWTH)
    # ══ النموُّ ليس مجّانياً · والتدفّقُ لا يفوق طاقةَ الأرباح دواماً ══
    # كان الأساسُ يُسقَّف عند ‎1.25 من متوسّط الربح **مع نموٍّ حتى ‎12٪ خمسَ
    # سنوات** — أي نموٌّ بلا إنفاقٍ رأسماليّ، وهو مستحيلٌ حسابياً. وشركةٌ
    # تنمو ‎g بعائدٍ على رأس المال ‎ROIC يلزمها إعادةُ استثمار ‎g÷ROIC من
    # ربحها، فلا يبقى حرّاً إلا الباقي. (‏قِيس على الحالة (ب): 126.47 بدل
    # 67.59 — انتفاخٌ ‎87٪.)
    # وفي الحالة المستقرّة يقارب الإهلاكُ الإنفاقَ الصيانيّ فيقارب التدفّقُ
    # الحرّ صافيَ الربح — فالسقفُ ‎1.0 لا ‎1.25، وما فوقه نقدٌ عابر لا طاقةُ
    # كسبٍ دائمة. ومن لا ربحَ له لا يُخصم تدفّقُه: الخاسرةُ تُقيَّم بأصولها.
    last = periods[-1] if periods else {}
    debt_last = last.get("total_debt") if isinstance(last, dict) else None
    profits = [p.get("net_income") for p in (periods or [])
               if isinstance(p.get("net_income"), (int, float))]
    earn_note = ""
    keep = 1.0
    if profits:
        # ══ طاقةُ الكسب الحاليّة لا متوسّطُها الخلفيّ ══
        # كان السقفُ يُقاس على **متوسّط** أرباح السنوات — وهو للشركة النامية
        # أدنى من ربحها الحاليّ بكثير، فيجتمع تحفّظان: متوسّطٌ خلفيّ ثم قصُّ
        # إعادة الاستثمار فوقه. وقِيس أثرُ الاجتماع: وسيطُ القيمة÷السعر
        # ‎0.786 والهدف ‎0.98.
        # والدوريُّ وحده يبقى على المتوسّط — فذاك عينُ تسوية الدورة.
        avg_profit = sum(profits) / len(profits)
        if not cyclical and profits[-1] and profits[-1] > 0:
            avg_profit = max(avg_profit, profits[-1])
        if avg_profit <= 0:
            return None
        # ══ إعادةُ الاستثمار تُقاس بعائد رأس المال المستثمر لا بحقوق الملكية ══
        # التدفّقُ الحرّ للمنشأة يُموَّل من رأس المال المستثمر كلِّه — دَيناً
        # وحقوقاً — لا من حقوق الملكية وحدها. فشركةٌ عائدُها على حقوق
        # الملكية ‎20٪ وعلى رأس المال المستثمر ‎12٪ يلزمها إعادةُ استثمارٍ
        # ‎67٪ لا ‎40٪. وقياسُها بحقوق الملكية يجعل أحدَ قيودنا «المتحفّظة»
        # سخيّاً للشركات المرفوعة تحديداً — وهي أحوجُها إلى التحفّظ.
        roic = None
        eq_last = _eq_of(last)
        if (isinstance(eq_last, (int, float)) and eq_last > 0
                and isinstance(debt_last, (int, float)) and debt_last >= 0):
            cap_emp = eq_last + debt_last
            if cap_emp > 0:
                roic = avg_profit / cap_emp
        base_return = roic if (roic and roic > 0) else roe_for_reinv
        keep = 1.0
        if base_return and base_return > 0:
            keep = max(0.10, 1.0 - min(0.9, g1 / base_return))
        cap = avg_profit * keep
        if base > cap:
            earn_note = (f" · أساسٌ مقيَّدٌ بإعادة الاستثمار "
                         f"({keep * 100:.0f}٪ من متوسّط الربح · "
                         f"كان {base / 1e6:,.0f}م)")
            base = cap

    g_term = min(TERMINAL_GROWTH, r - 0.02)
    if g_term <= 0 or r <= g_term:
        return None

    # ══ معدّلا إعادة استثمارٍ لا معدّلٌ واحد ══
    # القيدُ الصحيح: ما يُعاد استثمارُه يتناسب مع **النموّ المطلوب في تلك
    # المرحلة**. وكنتُ أطبّق معدّل مرحلة النموّ (‏g1÷ROIC) على المرحلة
    # الدائمة أيضاً — وهي تنمو ‎3٪ لا ‎8٪. فشركةٌ تعيد استثمار ‎80٪ في
    # سنواتها الخمس تبقى عندي معيدةً ‎80٪ إلى الأبد، وذلك يسحق القيمة
    # النهائية سحقاً (‏3.82 مقابل 10.27 للمسار الآخر في القياس).
    # فللمرحلة الدائمة معدّلُها: ‎1 − g_term÷ROIC.
    keep_term = 1.0
    if base_return and base_return > 0:
        keep_term = max(0.10, 1.0 - min(0.9, g_term / base_return))
    nopat = base / keep if keep > 0 else base      # الربحُ قبل قصّ الاستثمار

    pv, cf = 0.0, base
    for t in range(1, DCF_YEARS + 1):
        cf *= (1 + g1)
        pv += cf / ((1 + r) ** t)
    nopat_end = nopat * ((1 + g1) ** DCF_YEARS)
    terminal = nopat_end * keep_term * (1 + g_term) / (r - g_term)
    pv_terminal = terminal / ((1 + r) ** DCF_YEARS)
    pv += pv_terminal
    # نسبةُ القيمة النهائية: فوق ثلاثة أرباع لا يكون النموذجُ خصمَ خمس
    # سنواتٍ بل تخميناً للأبدية بقشرةٍ قصيرة — فتُعلَن وتخفض الثقة.
    terminal_share = pv_terminal / pv if pv > 0 else 0.0

    # من قيمة المنشأة إلى حقّ المساهم
    last = periods[-1] if periods else {}
    # ══ الدينُ الغائب يُسقط المسار ══
    # كان `or 0` يُسعّر دينَ الشركة **صفراً بصمت**، فتصير قيمةُ المساهم
    # قيمةَ المنشأة كاملةً. وحقلُ الدين ضعيفُ التغطية لرموز `.SR`، فالحالةُ
    # شائعةٌ لا نادرة. وأثرُها مقيس: شركةٌ بدينٍ 800م تخرج 22.60 بدل 14.60
    # — أي شراءُ شركةٍ مثقلةٍ بالدين على أنها بلا دين.
    debt = last.get("total_debt")
    if debt is None:
        debt = info.get("total_debt")
    if debt is None:
        return None
    cash = last.get("ending_cash") or info.get("total_cash") or 0
    equity_value = pv - float(debt or 0) + float(cash or 0)
    if equity_value <= 0:
        return None
    v = _sane(equity_value / shares, price)
    if not v:
        return None
    return {
        "name": "التدفّق النقدي المخصوم",
        "terminal_share": round(terminal_share, 3),
        "value": v,
        "inputs": (f"تدفّق حرّ {base / 1e6:,.0f}م · نموّ {g1 * 100:.1f}% "
                   f"لخمس سنوات ثم {g_term * 100:.1f}% دائماً · "
                   f"خصم {r * 100:.1f}%" + cycle_note + earn_note),
    }


# ══ سجلُّ التشغيلات — ما يجعل المحرّك قابلاً للتكذيب ══
# أخطرُ ما قيل في مراجعةٍ خارجية لهذا الملفّ: **لا يمكن إثبات خطأ أيّ ثابتٍ
