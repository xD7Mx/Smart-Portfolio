_RUNS = Path(__file__).resolve().parents[3] / "data" / "valuation_runs.jsonl"


def _log_run(symbol: str | None, out: dict, price, r, g) -> None:
    if not symbol or not out.get("methods"):
        return
    try:
        _RUNS.parent.mkdir(parents=True, exist_ok=True)
        row = {
            "symbol": str(symbol).replace(".SR", ""),
            "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "price": price,
            "value": out.get("value"),
            "low": out.get("low"), "high": out.get("high"),
            "r": round(r, 4), "g": round(g, 4),
            "confidence": out.get("confidence"),
            "entry_price": out.get("entry_price"),
            "methods": [{"n": m.get("name"), "v": m.get("value"),
                         "i": m.get("inputs")} for m in out.get("methods", [])],
            "asof": out.get("asof"),
        }
        with _RUNS.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
    except Exception:                                             # noqa: BLE001
        pass


def compute(info: dict, price: float | None,
            sector_avg_pe: float | None = None,
            sector_avg_pb: float | None = None,
            asof: str | None = None,
            periods: list[dict] | None = None,
            peer_count: int | None = None,
            archetype: str | None = None,
            symbol: str | None = None) -> dict:
    """القيمة العادلة بمساراتها. تُعاد دائماً بنية كاملة حتى عند التعذّر.

    و`asof` تاريخُ آخر تحديثٍ للأرقام المالية المستعملة. يُعاد دائماً —
    ويُعرض في البطاقة — لأن تقييماً لا يُعرف عمر مدخلاته لا يُبنى عليه
    قرار (بند ٢٤ من الميثاق). فالمدخلات تُخزَّن ثلاثين يوماً، وقائمةٌ
    مالية جديدة تُغيّر النتيجة كلَّها.
    """
    # ══ الصندوقُ المتداول لا قيمةَ عادلةَ له ══
    # وعاءٌ يتبع مؤشّراً أو أصلاً (ذهبٌ · صكوكٌ · أسهمٌ أمريكية) — سعرُه
    # صافي أصوله، ولا أرباحَ له ولا تدفّقَ حرٌّ ولا قيمةٌ دفترية تُقاس.
    # فتقديرُ «قيمةٍ عادلة» له اختلاقٌ بشكل رقم.
    # ══ التأمينُ لا تُقدَّر قيمتُه بمضاعف دفترية ══
    # النسبةُ المجمّعة (خسائر + مصاريف ÷ أقساط) هي **النموذج الاقتصاديّ**
    # لشركة التأمين لا مؤشّرٌ مساند: من نسبتُها 105٪ تخسر على كل ريالٍ
    # تكتتبه وتعيش على عائد استثماراتها. وربحُها المعلَن دالّةٌ في كفاية
    # الاحتياطيات — أي في **تقديرٍ إداريّ** يمكن تأجيله سنوات. فعائدٌ على
    # حقوق ملكيةٍ لا نعرف مصدره ليس تقديراً منخفض الثقة بل رقماً بلا معنى،
    # ومضاعفُ دفتريةٍ مبنيٌّ عليه أسوأ من الامتناع.
    # ودرجةُ الحوكمة تبقى — فهي تقيس أشياء أخرى تُقاس فعلاً.
    if archetype == "insurance" and not (info or {}).get("_regulatory_ratios", {}).get("combined_ratio"):
        return {"value": None, "low": None, "high": None, "methods": [],
                "asof": asof, "stale": None,
                "unavailable_reason": (
                    "النسبةُ المجمّعة جوهرُ اقتصاد شركة التأمين ولم تصلنا "
                    "لهذه الشركة — فلا تُقدَّر قيمتُها بمضاعف دفترية. "
                    "ومتى وصلت النسبةُ قُدِّرت.")}

    if archetype == "fund":
        return {"value": None, "low": None, "high": None, "methods": [],
                "asof": asof, "stale": None,
                "unavailable_reason": (
                    "صندوقٌ متداول — سعرُه صافي أصوله، ولا تُقدَّر له قيمةٌ "
                    "عادلة بمقاييس الشركات.")}

    # ══ التدقيق قبل الحساب ══ (بأمر المالك: جودةٌ استثمارية)
    # الأساسيات تُدقَّق مقابل القوائم أوّلاً، فالقوائم بنودٌ مدقَّقة والملخَّص
    # مشتقٌّ قد يتأخّر أو يُحسب على عدد أسهمٍ قديم بعد منحةٍ أو تجزئة.
    # وأيُّ تصحيحٍ يُسجَّل ويُعرض — لا يُبتلع صامتاً.
    from app.services.data_quality import audit as _audit
    _q = _audit(info or {}, periods or [])
    info = _q["values"]
    out: dict = {"value": None, "low": None, "high": None, "methods": [],
                 "asof": asof, "stale": None,
                 "audit": {"corrected": _q["corrected"], "notes": _q["notes"]},
                 "assumptions": {
                     "العائد الخالي من المخاطر": f"{RISK_FREE * 100:.1f}%",
                     "علاوة مخاطر السوق": f"{EQUITY_PREMIUM * 100:.1f}%",
                     "سقف النموّ المستدام": f"{MAX_SUSTAINABLE_GROWTH * 100:.1f}%",
                     "معدّل الخصم": None,
                 },
                 "unavailable_reason": None}

    # ══ لا قيمةَ بلا قوائم ══ (قرارُ مجلس نِصاب — كشفه `value_check.py`)
    # كان التقديرُ يخرج من حقول الملخّص وحدها (ربحيةُ سهمٍ · دفترية ·
    # عائدُ حقوق) بلا قائمةٍ مالية واحدة: لا سلسلةَ تُتحقّق منها، ولا
    # اتّجاهَ يُقرأ، ولا سبيلَ لمعرفة أربحٌ متكرّرٌ هو أم واقعةُ سنة.
    # وبوّابةُ القرار في التطبيق نفسه تمتنع دون سنتين — فكانت الشاشةُ
    # تعرض قيمةً عادلة لشركةٍ ترفض أن تُدرّجها. تناقضٌ بين شطري شاشةٍ
    # واحدة، والحدُّ الآن واحدٌ لهما.
    if len(periods or []) < 2:
        out["unavailable_reason"] = (
            f"لم تصلنا إلا {len(periods or [])} قائمةٍ مالية لهذه الورقة — "
            "والتقديرُ من حقول الملخّص وحدها لا سلسلةَ تسنده ولا اتّجاهَ "
            "يُقرأ منه. والقوائمُ مُلزِمةٌ لكل مدرَج، فالنقصُ في وصولها "
            "إلينا لا في الشركة.")
        return out

    def num(k):
        v = info.get(k)
        return v if isinstance(v, (int, float)) else None

    # ══ لا رأيَ للمحللين في الحساب — ولو من نافذة ══
    # طُرد «السعر المستهدف» من الباب (‏D047) ثم دخل تقديرُهم للربحية
    # المستقبلية (`forward_eps`) من النافذة. وانحيازُه التفاؤليّ موثَّق
    # وأشدُّ في الأسواق الناشئة. فالمحقَّقةُ وحدها.
    eps = num("eps")
    bvps = num("book_value")
    roe = num("roe")
    dps = num("dividend_per_share")
    growth = num("earnings_growth")
    beta = num("beta")
    r = _required_return(beta)
    out["assumptions"]["معدّل الخصم"] = f"{r * 100:.1f}%"
    _DROPPED["n"] = 0

    # نموٌّ مستدام مُقيَّد: نموّ الأرباح التاريخيّ يُستعمل مُقصوصاً عند
    # السقف، وسالبُه يُصفَّر — نموذجُ خصمٍ بنموٍّ سالب دائم يُنتج عبثاً.
    g = 0.0
    if growth is not None:
        g = max(0.0, min(growth / 100.0, MAX_SUSTAINABLE_GROWTH))

    # ══ النموُّ الدائم يُشتقّ من الاحتجاز لا يُفترض صفراً ══
    # ‏«ثمار» (‏2200): عائدُ حقوق 22.6٪ وتوزيعٌ رُبعُ الربح — ثم يُخصم
    # توزيعُها بنموٍّ **صفر**. وذلك تناقضٌ في ذاته: من يحتجز ثلاثةَ أرباع
    # ربحٍ يعود على رأسماله 22.6٪ لا يبقى ثابتاً إلى الأبد؛ المالُ المحتجَز
    # إمّا ينمو وإمّا يتبخّر، ونموٌّ صفرٌ يعني أنه يتبخّر.
    # والصيغةُ المعروفة: g = العائدُ على حقوق الملكية × نسبةُ الاحتجاز.
    # وتُشتقّ نسبةُ الاحتجاز من التوزيع والربح **المحسوبَين هنا** لا من
    # حقل المصدر: قِيس على «ثمار» فقال المصدرُ إن التوزيع 51.5٪ من الربح،
    # والتوزيعُ والدفتريةُ والعائدُ تقول 25.4٪ — ومن يخلط مصدرين متناقضين
    # يبني نموذجاً على رملٍ ويسمّي الفرقَ «اختلافَ مناهج».
    eps_from_book = (roe / 100.0 * bvps) if (roe is not None and bvps) else None
    eps_used = eps_from_book or eps
    # ══ من لا يوزّع يحتجز كلَّ ربحه ══
    # كان الاحتجازُ يبقى `None` حين يغيب التوزيع، فتتدحرج الدفتريةُ في
    # نموذج الدخل المتبقّي بصفر — أي أن أرباحَ خمسَ عشرةَ سنةً **تتبخّر**
    # من الميزانية. والشركةُ التي لا توزّع تحتجز مئةً بالمئة لا صفراً.
    # وقِيس أثرُه على السوق: مسارُ النموّ الدائم خرج بوسيطٍ ‎0.720 من السعر
    # (‏٢٢٩ شركة) بينما المضاعف ‎1.141 والخصم ‎0.869 — فهو وحده من يسحب
    # الوسيطَ العامّ، وهذا سببُه.
    retention = None
    if eps_used and eps_used > 0:
        if dps is None or dps <= 0:
            retention = 1.0
        else:
            retention = max(0.0, min(1.0, 1.0 - dps / eps_used))
    if roe is not None and retention is not None:
        g_sust = max(0.0, roe / 100.0 * retention)
        g = min(max(g, g_sust), MAX_SUSTAINABLE_GROWTH)

    # ══ أنماطٌ لا يصحّ فيها خصمُ التدفّق الحرّ ══ (بأمر المالك)
    # محرّك الحوكمة يعرف هذا منذ حين ويُعطّل كلَّ قواعد التدفّق الحرّ
    # للبنوك والتأمين والتمويل: نموُّ دفتر القروض يظهر تدفّقاً تشغيليّاً
    # **سالباً** وهو نموٌّ صحّيّ لا ضعف، والعكس في سنة الانكماش. فكان
    # محرّك التقييم يخصم رقماً يعرف المحرّكُ الآخرُ أنه بلا معنى — وهو
    # عينُ العطب الذي عولج في التدقيق (D031): محرّكٌ يعلم وآخر لا يعلم.
    #
    # والبديلُ ليس فراغاً بل الطريقةَ المعترف بها لكل نمط:
    #   • البنوك والتأمين والتمويل — خصمُ التوزيعات ومضاعفُ الدفترية
    #     المبرَّر (‏ROE−g)÷(r−g). وهو نهجُ التقييم المتّبع لها عالمياً،
    #     لأن حقوق الملكية والعائد عليها هما محلُّ القيمة فيها.
    #   • الصناديق العقارية — الدفتريّة تقريبُ صافي الأصول (عقاراتها
    #     بالقيمة العادلة وفق المعايير)، والتوزيعُ جوهرُ دخلها. وربحُها
    #     المحاسبيُّ وتدفّقُها مشوّهان بالإهلاك وإعادة التقييم.
    NO_DCF = {"bank", "insurance", "financial", "reit"}

    # ── ٠) التدفّق النقدي المخصوم — المعيار ─────────────────────────────
    # يُقدَّم على المضاعفات لأنه يُقيّم الشركة **في ذاتها**، والمضاعفات
    # تُقيّمها بما يدفعه السوق لنظائرها. فإن كان القطاع كلُّه مبالغاً فيه
    # صادقت المضاعفاتُ على المبالغة، والخصمُ وحده يكشفها.
    try:
        d = None if archetype in NO_DCF else _dcf(
            periods or [], info, price, r,
            cyclical=(archetype == "cyclical"),
            roe_for_reinv=(roe / 100.0 if roe else None))
    except Exception:                                             # noqa: BLE001
        d = None
    if d:
        out["methods"].append(d)
        if (d.get("terminal_share") or 0) > 0.75:
            out["terminal_heavy"] = True

    # ── ١) مضاعف الربحية العادل: ربحيةُ السهم × مضاعف القطاع ────────────
    # المنطق: ما دام السهم يكسب EPS ويُسعّر نظراؤه عند مضاعفٍ معلوم، فسعره
    # العادل هو حاصلُ ضربهما. ومضاعف القطاع من نظائرَ حقيقية في المحفظة
    # لا من رقمٍ عامّ — فإن غاب سقط المسار.
    if eps and eps > 0 and sector_avg_pe and 0 < sector_avg_pe < 60:
        v = _sane(eps * sector_avg_pe, price)
        if v:
            out["methods"].append({
                "name": "مضاعف الربحية العادل",
                "value": v,
                # عددُ الأقران جزءٌ من الرقم لا حاشية: مضاعفٌ من ثلاثة أقران
                # ليس كمضاعفٍ من ثلاثين، والمستثمر يزن الرقم بمصدره.
                "inputs": (f"ربحية السهم {eps:.2f} × وسيط القطاع "
                           f"{sector_avg_pe:.1f}"
                           + (f" ({peer_count} قريناً)" if peer_count else "")),
            })

    # ── ٢) نموٌّ دائم — مسارٌ واحد لا مساران ─────────────────────────────
    # ══ خطأٌ في بناء المحرّك نفسه، كشفته أرقامُ المسح ══
    # كان «مضاعفُ الدفترية المبرَّر» و«خصمُ التوزيعات» مسارين مستقلَّين
    # يُقاس اختلافُهما تشتّتاً. وهما **النموذجُ نفسه**: مضاعفُ الدفترية
    # المبرَّر ‏(ROE−g)÷(r−g) مشتقٌّ من جوردون بعينه حين يكون
    # ‏g = ROE × الاحتجاز. فلا يفترقان إلا إذا غُذّيا بمدخلاتٍ متناقضة —
    # وهو ما كان يقع: يُحسب المضاعفُ بعائد الشركة كاملاً ويُخصم التوزيعُ
    # بنموٍّ صفر، أي أن الشيفرةَ تفترض في السطر الأوّل أن الاحتجاز يُثمر
    # وتفترض في الثاني أنه يتبخّر.
    # وقياسُ الفرق بين افتراضين متناقضين ليس «اختلافَ مناهج» يُحتَرم — بل
    # خطؤنا نحن، معروضاً على المالك امتناعاً عن التسعير.
    # فصارا مساراً واحداً بنموٍّ واحدٍ مشتقٍّ من الاحتجاز. والصيغةُ الدفترية
    # هي المعروضة لأنها أثبت (الدفتريةُ أقلُّ تقلّباً من توزيعِ سنةٍ بعينها).
    if bvps and bvps > 0 and roe is not None and r > g:
        # ══ العائدُ لا يدوم — نموذجُ الدخل المتبقّي بتلاشٍ ══
        # كانت الصيغةُ ‏(ROE−g)÷(r−g) تفترض بقاءَ العائد الحاليّ **إلى
        # الأبد**. وهو أشدُّ افتراضٍ تفاؤلاً في التقييم: العوائدُ ترتدّ إلى
        # الوسط، والمنافسةُ تأكل الفائض، فتتآكل عوائدُ الشركات المرتفعة نحو
        # كلفة رأس المال خلال خمسٍ إلى عشر سنوات. (‏قِيس على الحالة (أ):
        # 42.91 بدل 21.74 — انتفاخٌ ‎97٪.)
        # فالقيمة = الدفترية + مجموعُ الدخل المتبقّي المخصوم، والعائدُ
        # يتلاشى خطّياً من الحاليّ إلى ‎r+2٪ في عشر سنوات ثم يستقرّ — فلا
        # فائضَ بعدها يُخصم إلى الأبد.
        # ══ هدفُ التلاشي دالّةٌ في ميزةٍ مُثبَتة لا ثابتٌ للجميع ══
        # كان الهدفُ ‎r+2٪ لكل شركة — أي أن **كلَّ** شركةٍ تفقد ميزتها كاملةً
        # في عشر سنوات. وذلك صحيحٌ للمتوسّط وخاطئٌ للاستثناء، والاستثناءُ هو
        # ما نبحث عنه. وقِيست الحساسية: الهدفُ وحده ينقل المضاعف من ‎1.61
        # إلى ‎2.14 — أثرٌ أكبر من نقطتين في معدّل الخصم.
        # فالميزةُ تُثبَت بالسجلّ: عائدٌ يفوق المطلوبَ بخمس نقاطٍ خمسَ سنواتٍ
        # متتالية خندقٌ ضيّق، وعشرَ سنواتٍ خندقٌ واسع — وهو إطارُ الخنادق
        # المعتاد. ومن لا سجلَّ له يبقى على الافتراض المتحفّظ.
        # خمسَ عشرةَ سنةً لعامّة الشركات: عشرٌ أقصر من عمر ميزةٍ حقيقية،
        # وهو ما كان يسحق التقنية.
        # ══ والبنوك أقصر ══
        # قِيس على السوق: وسيطُ القيمة÷السعر للبنوك ‎1.489 — أي أن المحرّك
        # يقول عن البنك الوسطى إنها أرخصُ من قيمتها ‎49٪، وذلك انتفاخٌ لا
        # فرصة. وسببُه أن فائضَ عائد البنك يُخصم خمسَ عشرةَ سنة، والبنكُ
        # مؤسّسةٌ مرفوعةُ الرافعة منظَّمةٌ في سوقٍ مفتوح: فائضُها يتآكل
        # أسرعَ من فائض صاحبة العلامة أو الشبكة.
        FADE_YEARS = 10 if archetype in ("bank", "financial") else 15
        roe0 = roe / 100.0
        streak = 0
        for p_ in reversed(periods or []):
            ni, eq = p_.get("net_income"), _eq_of(p_)
            if not (isinstance(ni, (int, float)) and isinstance(eq, (int, float)) and eq > 0):
                break
            if ni / eq >= r + 0.05:
                streak += 1
            else:
                break
        # ══ مُعايَرٌ بالقياس لا بالرأي ══
        # قِيس على السوق كلِّه بعد شدّ القيود: وسيطُ القيمة÷السعر خرج
        # ‎0.761 والمرجَّحُ بالقيمة السوقية ‎0.653 — أي أن المحرّك صار يقول
        # عن الشركة الوسطى إنها أغلى من قيمتها ‎24٪، و«شراء قوي» صفر.
        # والهدفُ المعلَن ‎0.95–1.10. وأشدُّ القيود أثراً هدفُ التلاشي
        # (‏r+2٪ ينقل المضاعف من ‎1.61 إلى ‎2.14 عند r+6٪)، فرُفع درجةً:
        # ‎r+4٪ بلا دليلِ ميزة، و‎r+6٪ لخمس سنواتٍ متتالية، و‎r+8٪ لعشر.
        # وأرضيةُ العلاوة من ‎5.0٪ إلى ‎4.5٪. والاتّجاهُ متحفّظٌ عمداً: أن
        # نقف دون الواحد خيرٌ من أن نتجاوزه.
        spread = 0.08 if streak >= 10 else 0.06 if streak >= 5 else 0.04
        # ══ التلاشي نزولٌ لا صعود ══
        # كان الهدفُ يُستوفى مباشرةً، فشركةٌ عائدُها ‎6٪ تُنمذَج على أنها
        # **تتحسّن** إلى ‎13.5٪ خلال الأفق — تحسّنٌ مختلَق لا تلاشٍ. وظهر
        # أثرُه في المرافق (‏1.27 من قياسنا، و‎1.26 من إعادة حسابه — تطابقٌ
        # يشخّص العطب لا يصادفه). فالهدفُ لا يتجاوز العائدَ الحاليّ.
        roe_end = min(roe / 100.0, r + spread)
        bv, pv_ri = bvps, 0.0
        for t in range(1, FADE_YEARS + 1):
            roe_t = roe0 + (roe_end - roe0) * (t / FADE_YEARS)
            ri = (roe_t - r) * bv
            pv_ri += ri / ((1 + r) ** t)
            # ══ الدفتريةُ تتدحرج بالاحتجاز الفعليّ ══
            # كانت تتدحرج بـ`g` المسقوف عند ‎3٪ — وذلك قيدٌ مزدوج: السقفُ
            # وُضع لأن مقام جوردون ينفجر، ولا انفجارَ في نموذجٍ صريحٍ لعشر
            # سنوات. وأثرُه مقيس: دفتريةُ السنة العاشرة تخرج ‎13.4 بدل ‎18.9،
            # أي أن أرباحاً محتجزةً حقيقية **تتبخّر من الميزانية** فتُنقص
            # القيمة ‎7٪ بلا سبب.
            b_ret = retention if retention is not None else 0.0
            bv *= (1 + max(0.0, roe_t) * b_ret)
        # القيمة النهائية: فائضٌ ثابتٌ صغير يُخصم أبديّاً بلا نموّ.
        pv_ri += ((roe_end - r) * bv / r) / ((1 + r) ** FADE_YEARS)
        v_raw = bvps + pv_ri
        # ══ قيدٌ رياضيّ لا يُخترق ══
        # إن كان العائدُ دون المطلوب فالشركةُ تُدمّر قيمةً، فمضاعفُ دفتريتها
        # أقلُّ من واحدٍ حتماً — ولا يجوز أن يخرج تقديرُها فوق دفتريتها.
        if roe0 < r:
            v_raw = min(v_raw, bvps)
        v_raw = min(v_raw, bvps * MAX_JUSTIFIED_PB)
        v = _sane(v_raw, price) if v_raw > 0 else None
        if v:
            bits = (f"دفترية السهم {bvps:.2f} + دخلٌ متبقٍّ مخصوم "
                    f"(عائد حقوق {roe:.1f}% يتلاشى إلى {roe_end * 100:.1f}% "
                    f"في {FADE_YEARS} سنة · مطلوب {r * 100:.1f}%)")
            if retention is not None:
                bits += f" · احتجاز {retention * 100:.0f}%"
            out["methods"].append({
                "name": "نموٌّ دائم (دفترية وتوزيع)",
                "value": v,
                "inputs": bits,
            })

    # ── ٣) العائدُ التوزيعيّ المرسمَل — عدسةُ الصندوق العقاريّ الأولى ────
    # الصندوقُ العقاريّ يُشترى بدخله لا بأرباحه المحاسبية: نظامُه يُلزمه
    # توزيعَ تسعين بالمئة من صافي دخله، فالتوزيعُ هو المُخرَج الاقتصاديّ
    # كاملاً تقريباً، والربحُ والتدفّقُ مشوّهان بالإهلاك وإعادة التقييم.
    # وطريقةُ السوق العقاريّ لتقييم دخلٍ كهذا هي الرسملة: القيمة =
    # التوزيع ÷ معدّل الرسملة، ومعدّلُ الرسملة هو العائدُ المطلوب ناقصَ
    # نموِّ الإيجارات. وكانت المواصفةُ تنصّ عليه ولم يكن في الشيفرة، فكان
    # الريتُ يُقاس بعدستين لا تخصّانه.
    if archetype == "reit" and dps and dps > 0:
        g_rent = min(g, 0.02)          # نموُّ إيجارٍ متحفّظ لا نموُّ أرباح
        cap = r - g_rent
        if cap > 0.02:
            v = _sane(dps / cap, price)
            if v:
                out["methods"].append({
                    "name": "عائدٌ توزيعيّ مرسمَل",
                    "value": v,
                    "inputs": (f"توزيع السهم {dps:.2f} ÷ معدّل رسملة "
                               f"{cap * 100:.1f}% (مطلوب {r * 100:.1f}% − "
                               f"نموّ إيجار {g_rent * 100:.1f}%)"),
                })

    # ── ٤) إجماع أهداف المحللين — **حُذف من مسارات القيمة** ─────────────
    # كان مساراً رابعاً يدخل في حساب القيمة. وثلاثةُ أسباب تُخرجه:
    #
    # ١) **يناقض مبدأ هذا الملفّ نفسه**، المكتوب في صدره: هدفُ سعرٍ
    #    لاثني عشر شهراً ليس تقديرَ قيمةٍ جوهرية. فكان الملفّ ينهى عنه
    #    في أعلاه ويستعمله في أسفله.
    # ٢) **يستورد السعر السوقيّ إلى التقدير**: المحلّلون يضعون أهدافهم
    #    منسوبةً إلى السعر القائم، فإدخالُها يجعل التقييمَ يقيس السوقَ
    #    بنفسه — وهو نقيضُ ما وُجد له.
    # ٣) **ازدواجُ الاحتساب**: إجماعُ المحللين محتسَبٌ أصلاً في درجة
    #    الحوكمة (‏v_analyst_upside)، فيدخل الإشارةُ الواحدة مرّتين.
    #
    # وأثرُه قِيس على حالةٍ عرضها المالك («سلوشنز»): بوجوده القيمةُ
    # 217.05 والسعرُ 206.90 فيُقرأ «عادل»، وبحذفه القيمةُ 180.60 فيُقرأ
    # «أعلى من قيمته بـ12.7٪». الحكمُ ينقلب — على رأيٍ لا حساب.
    #
    # ورأيُ المحللين لا يضيع: يبقى في ميزان الخبراء حيث موضعُه، ويبقى
    # «تقدير المحللين» رقماً في البيانات المالية.

    # عمرُ المدخلات: فوق خمسة وأربعين يوماً يعني أن قائمةً ربعية جديدة
    # ربما صدرت ولم تصل بعد — فيُوسَم التقدير «قديم» ولا يُحذف.
    if asof:
        try:
            from datetime import date
            age = (date.today() - date.fromisoformat(asof)).days
            out["age_days"] = age
            out["stale"] = age > 45
        except Exception:                                         # noqa: BLE001
            pass

    vals = [m["value"] for m in out["methods"]]
    if not vals:
        out["unavailable_reason"] = (
            "لا تكفي البيانات المالية المتاحة لحساب قيمةٍ عادلة "
            "(يلزم ربحية سهمٍ مع مضاعف قطاع، أو دفترية مع عائد حقوق، "
            "أو توزيعٌ مستقرّ)."
        )
        return out

    # الوسيط يبقى للتلخيص، لكن وجودَ الخصم يُذكر صراحةً: تقديرٌ يقوم على
    # المضاعفات وحدها ليس كتقديرٍ يسنده نموذجُ خصمٍ من قوائم الشركة.
    out["has_dcf"] = any(m["name"] == "التدفّق النقدي المخصوم"
                         for m in out["methods"])
    # ══ بيانُ المصدر ══ (بأمر المالك: جودةٌ استثمارية)
    # لا يكفي أن يكون الرقم صحيحاً — يجب أن يكون **قابلاً للوزن**. فيُعاد
    # مع كل تقدير: عدد سنوات القوائم التي بُني عليها، وعدد أقران القطاع،
    # ومصدر الأساسيات. مستثمرٌ يعرف هذه الثلاثة يعرف كم يثق بالرقم.
    out["provenance"] = {
        "سنوات القوائم": len(periods or []),
        "أقران القطاع": peer_count,
        "مصدر الأساسيات": "ياهو",
        "تاريخ الأساسيات": asof,
    }
    # ══ نماذجُ آفاقٍ مختلفة لا تُجمع بوسيطٍ أعمى ══
    # (بأمر المالك: قراءةٌ استثمارية صحيحة)
    #
    # عرض المالك حالةً حقيقية: أربعةُ مسارات بين 35.56 و93.63 — ‏2.63×
    # بين أعلاها وأدناها. الخصمُ يقول إن السهم قريبٌ من قيمته (+6٪ عن
    # السعر)، والوسيطُ يقول إنه مبالغٌ فيه ‏42٪. فرقٌ يقلب القرار.
    #
    # والسبب ليس خطأً في مسارٍ منها — كلٌّ صحيحٌ في ذاته — بل **اختلافُ
    # الأفق**:
    #   • خصمُ التدفّقات يمنح الشركة خمسَ سنواتِ نموٍّ من تاريخها (حتى
    #     ‏12٪) قبل أن تستقرّ عند ‏2.5٪ دائماً.
    #   • أمّا مضاعفُ الدفترية المبرَّر وخصمُ التوزيعات فنماذجُ نموٍّ
    #     **دائم**: تفترض معدّلاً واحداً إلى الأبد، مسقوفاً عند ‏4٪
    #     لأن الدوام يمنع أكثر.
    # فالشركةُ النامية تخرج من الأوّل أعلى ومن الآخرَين أدنى — حتماً، لا
    # صدفةً. وجمعُها بوسيطٍ يسوّي بين أفقين مختلفين ويُنتج رقماً لا يمثّل
    # أيّاً منهما.
    #
    # والعلاج: تُجمع نماذجُ النموّ الدائم في صوتٍ واحد (فهي من طبيعةٍ
    # واحدة)، ويُرجَّح النموذجُ متعدّد المراحل عليها لأنه يقرأ تاريخ
    # الشركة لا يفترض ثباتها، ويبقى مضاعفُ القطاع صوتاً أصغر لأنه يقيس
    # ما يدفعه السوق للنظائر لا ما تستحقّه الشركة. والأوزان **مُعلَنة**
    # في المخرَج لا مخفيّة.
    #
    # والوسيطُ يبقى حارساً: بلا نموذجٍ متعدّد المراحل يعود التلخيصُ
    # وسيطاً كما كان — لا يُرجَّح ما لا أصل له.
    # ══ الأنماطُ المالية لها عدستُها الأولى ══
    # كان الترجيحُ مشروطاً بوجود النموذج متعدّد المراحل، والبنكُ والتأمين
    # والريت لا خصمَ تدفّقٍ لها أصلاً (‏D039) — فتسقط جميعاً إلى **الوسيط
    # الأعمى** الذي أدانه هذا الملفّ نفسه. ولهذا خرج «الراجحي» بمدى
    # 59.60–127.00 و«الأهلي» بـ20.37–96.27 في مسح السوق: قطاعٌ كامل
    # يُلخَّص بالطريقة التي مُنع غيرُه منها.
    # وعدسةُ البنك الأولى في التقييم المصرفيّ المعتاد هي **مضاعف الدفترية
    # المبرَّر** — العائدُ على حقوق الملكية مقابل كلفته — ثم خصمُ
    # التوزيعات (والبنوكُ موزِّعةٌ ناضجة فله وزنٌ حقيقيّ)، ويبقى مضاعفُ
    # القطاع أصغرَها لأنه يقيس ما يدفعه السوق للنظائر لا ما تستحقّه هي.
    _PB, _PE = "نموٌّ دائم (دفترية وتوزيع)", "مضاعف الربحية العادل"
    by_name = {m["name"]: m["value"] for m in out["methods"]}
    buckets: dict[str, float] = {}
    _CAP = "عائدٌ توزيعيّ مرسمَل"
    if archetype == "reit":
        # ══ الريتُ يُرجَّح بدخله ══
        # عدستُه الأولى الرسملة، ثم الدخلُ المتبقّي على صافي الأصول، ثم
        # مضاعفُ الربحية أصغرَها لأن ربح الريت المحاسبيّ أضعفُ ما فيه.
        WEIGHTS = {_CAP: 0.55, _PB: 0.25, _PE: 0.20}
        for k in (_CAP, _PB, _PE):
            if k in by_name:
                buckets[k] = by_name[k]
        primary = _CAP if _CAP in by_name else _PB
    elif archetype in NO_DCF:
        # ══ ترجيحٌ متكافئ للبنك والتأمين والتمويل ══
        # كان ‎65/35 لمضاعف الدفترية المبرَّر، وهو مسارُ الدخل المتبقّي
        # نفسُه الذي قِيس منتفخاً في البنوك (‎1.489). فإسنادُ ثلثي الوزن
        # إلى أضعف الشاهدَين مضاعفةٌ للانحياز، ومضاعفُ الربحية شاهدٌ
        # سوقيٌّ يكذّبه. فتكافآ.
        WEIGHTS = {_PB: 0.50, _PE: 0.50}
        for k in (_PB, _PE):
            if k in by_name:
                buckets[k] = by_name[k]
        primary = _PB
    else:
        WEIGHTS = {"متعدّد المراحل": 0.45, "نموّ دائم": 0.35, "مضاعف القطاع": 0.20}
        perpetual = [by_name[k] for k in (_PB,) if k in by_name]
        if "التدفّق النقدي المخصوم" in by_name:
            buckets["متعدّد المراحل"] = by_name["التدفّق النقدي المخصوم"]
        if perpetual:
            buckets["نموّ دائم"] = sum(perpetual) / len(perpetual)
        if _PE in by_name:
            buckets["مضاعف القطاع"] = by_name[_PE]
        primary = "متعدّد المراحل"

    # ══ تقديرٌ متضاربٌ ليس تقديراً ══
    # (وجده مسحُ السوق: ١٧٤ شركة من ٣٩٦ بتشتّتٍ ≥2×، وأحدها 11.2×)
    #
    # «١١٨٠» مثالٌ صريح: المسارات بين 20.37 و227.28. خصمُ التوزيعات يقول
    # عشرين لأن الشركة توزّع جزءاً من ربحها، ومضاعفُ الدفترية المبرَّر
    # يقول مئتين لأن عائدها على حقوق الملكية يفوق كلفةَ رأس المال. وكلٌّ
    # صحيحٌ في منطقه، ولا وسطَ بينهما يُمثّلهما — فمتوسّطُ الطرفين رقمٌ
    # لا يقول به أيُّ نموذج.
    #
    # وقد عالج الترجيحُ (‏D046) **الانحياز**، ولا يعالج **التضارب**: لا
    # وزنَ يجعل من رقمين متباعدين ثلاثةَ أضعافٍ رقماً واحداً موثوقاً.
    # فالصادقُ أن تُعلَن القيمةُ غيرَ متاحة ويبقى المدى معروضاً — كما
    # يمتنع محرّك الحوكمة حين لا تكفي البيانات. والامتناعُ حكمٌ لا فراغ.
    # ══ الشاهدُ الأضعف يُستبعد قبل الامتناع ══
    # بقيت أربعون شركةً ممتنعةً بعد علاج D062 و D063. ومضاعفُ القطاع هو
    # المسارُ الوحيدُ **غيرُ الجوهريّ** بينها: يقيس ما يدفعه السوق لنظائر
    # الشركة لا ما تستحقّه هي، ولذلك أعطي أدنى وزنٍ منذ البداية. فإن كان
    # هو الشاذَّ وحده — واتّفق المسارانِ الجوهريّان — فالامتناعُ عن التسعير
    # تنازلٌ عن معرفةٍ نملكها إرضاءً لشاهدٍ نعرف ضعفَه.
    # فيُستبعد من **حساب النقطة** ويبقى معروضاً في المسارات، ويُقال إنه
    # استُبعد. وما بقي تضاربُه بعد استبعاده يبقى ممتنعاً.
    if (len(vals) >= 3 and min(vals) > 0 and max(vals) / min(vals) >= 3.0
            and _PE in by_name):
        core = [m["value"] for m in out["methods"] if m["name"] != _PE]
        if len(core) >= 2 and min(core) > 0 and max(core) / min(core) < 3.0:
            # المدى يبقى محسوباً من **كل** المسارات: من حذف الخلاف ثم ضيّق
            # مداه كافأ نفسه على الحذف. ويُسجَّل الاستبعادُ ليخفض الثقة.
            out["_all_vals"] = list(vals)
            out["excluded_penalty"] = True
            vals = core
            buckets.pop("مضاعف القطاع", None)
            buckets.pop(_PE, None)
            out["excluded"] = (
                f"مضاعفُ القطاع ({by_name[_PE]}) خارجَ حساب النقطة: شذَّ عن "
                f"المسارات الجوهرية، وهو يقيس سعرَ النظائر لا قيمةَ الشركة.")

    if len(vals) >= 2 and min(vals) > 0 and max(vals) / min(vals) >= 3.0:
        out["low"], out["high"] = round(min(vals), 2), round(max(vals), 2)
        out["value"] = None
        out["dispersion"] = round(max(vals) / min(vals), 2)
        out["unavailable_reason"] = (
            f"مساراتُ التقدير متضاربة ({out['dispersion']}× بين أعلاها "
            f"وأدناها: {out['low']}–{out['high']}) — لا تُختصر في رقمٍ واحد.")
        return out

    if primary in buckets and len(buckets) > 1:
        wsum = sum(WEIGHTS[k] for k in buckets)
        out["value"] = round(sum(v * WEIGHTS[k] for k, v in buckets.items()) / wsum, 2)
        out["weighting"] = {k: f"{WEIGHTS[k] / wsum * 100:.0f}%" for k in buckets}
    else:
        out["value"] = round(median(vals), 2)
    # ══ قيدٌ رياضيّ يحكم النقطةَ لا مساراً واحداً ══
    # شركةٌ عائدُها دون المطلوب تُدمّر قيمةً، فلا يجوز أن يخرج تقديرُها فوق
    # دفتريتها مهما قال مضاعفُ القطاع. وكان المضاعفُ يرفعها فوق الدفترية
    # (‏الحالة (ج): 23.46 والسقف 20.00) لأن القيد كان داخل مسارٍ واحد.
    if (roe is not None and bvps and bvps > 0
            and roe / 100.0 < r and out.get("value")
            and out["value"] > bvps):
        out["value"] = round(bvps, 2)
        out["capped_at_book"] = True

    # ══ خصمُ سيولةٍ للسوق الموازية «نمو» ══
    # كشفه المسحُ الكامل: من ‎406 صفّاً ‎136 من «نمو» (رموزُها 9xxx)،
    # ووسيطُ القيمة÷السعر فيها ‎0.879 مقابل ‎0.738 للسوق الرئيسة — أي أن
    # المحرّك يراها أقربَ إلى قيمتها، وهو عكسُ الحقيقة: أسهمُ «نمو» رقيقةُ
    # التداول محدودةُ الإفصاح مقصورةٌ على المؤهَّلين، فبيعُ مركزٍ فيها قد
    # يتعذّر أصلاً. وقيمةٌ لا يمكن تسييلُها ليست قيمةً كاملة.
    # فيُخصم ثلاثون بالمئة من التقدير، ولا يُبنى عليه قرارُ شراء بحال —
    # لأن الخصم يعالج السعرَ ولا يعالج تعذّرَ الخروج.
    _base = (symbol or "").replace(".SR", "")
    from app.data.universe import is_nomu
    if is_nomu(_base):
        out["nomu"] = True
        if out.get("value"):
            out["value"] = round(out["value"] * 0.70, 2)
            out["liquidity_discount_pct"] = 30

    # ══ حدُّ العقل على المزيج لا على المسار وحده ══
    # كشفه فحصٌ خارجيّ: تسعةَ عشرَ صفّاً خرجت نسبتُها عن ‎0.40×–2.50× من
    # السعر **بعد** الترجيح، لأن الحدَّ كان يُفحص عند كلّ مسارٍ ثم يُجمع
    # الناجون. فمسارٌ عند ‎0.42 وآخرُ عند ‎0.38 يمرّ أوّلُهما ويُسقط الثاني،
    # ثم تخرج النقطةُ ‎0.42 وهي عند حافّة اللامعقول.
    if out.get("value") is not None and price:
        _r = out["value"] / price
        if not (SANE_LOW <= _r <= SANE_HIGH):
            # ══ الشذوذُ يُعلَن ولا يُمحى ══ (قرارُ مجلس نِصاب)
            # كان التقديرُ يُلغى ويُقال «بيانات غير كافية» — وذلك كذبٌ على
            # القارئ: نحن حسبناه ثم رفضناه، فالمعرفةُ موجودةٌ والادّعاءُ
            # أنها معدومة. وأسوأُ من ذلك أنه يقع **عند أعمق خصم**، أي
            # يصمت التطبيقُ في أوضح ما يكون فرصةً أو أوضح ما يكون فخّاً.
            # فصار الرقمُ يبقى معروضاً موسوماً بشذوذه، ولا يُبنى عليه
            # قرارُ شراء: يرى المستثمرُ ما حسبناه ويرى تحفّظَنا عليه.
            out["implausible"] = True
            out["confidence"] = "منخفضة"
            out["note"] = (
                f"التقديرُ ({out['value']:,.2f}) يعادل {_r:.2f}× السعرَ "
                f"القائم — خارج النطاق المعقول ({SANE_LOW:.2f}–"
                f"{SANE_HIGH:.2f}). فارقٌ بهذا الحجم مصدرُه غالباً خللٌ في "
                f"مُدخَلٍ لا فرصةٌ حقيقية، فلا يُبنى عليه قرار.")

    # ══ مسارٌ واحد ليس تقييماً ══
    # ‏١١٦ شركة أنتجت قيمةً وقراراً من مسارٍ واحد، ووسيطُ نسبتها ‎0.613
    # مقابل ‎0.960 لمسارين — فالمسارُ اليتيم هو مصدرُ الانحياز النزوليّ
    # الأكبر، ولا شاهدَ يكذّبه. فتُعرض قيمتُه ولا يُبنى عليها قرارُ شراء.
    out["single_path"] = len(vals) < 2

    _span = out.get("_all_vals") or vals
    out["low"], out["high"] = round(min(_span), 2), round(max(_span), 2)
    out.pop("_all_vals", None)
    if price:
        out["upside_pct"] = round((out["value"] / price - 1) * 100, 1)
        # اتّساعُ التشتّت رسالةٌ في ذاته: مساراتٌ متباعدة تعني أن التقدير
        # ضعيف الثقة مهما بدا وسيطُه دقيقاً.
        spread = (out["high"] - out["low"]) / out["value"] if out["value"] else 0
        # ══ الثقةُ تنزل حين نحذف خلافاً أو نتّكئ على الأبدية ══
        # كان حذفُ المسار المخالف يضيّق التشتّت فيرفع الثقة فيقلّ هامشُ
        # الأمان فيرتفع سعرُ الدخول — آليّةٌ تكافئ على حذف الخلاف. وكذلك
        # نموذجٌ ثلاثةُ أرباع قيمته قيمةٌ نهائية ليس خصمَ خمس سنواتٍ بل
        # تخميناً للأبدية بقشرةٍ قصيرة.
        # والتقديرُ الشاذُّ النسبة ثقتُه منخفضةٌ حتماً: وُسم قبل هذا السطر
        # فكان يُدهس هنا — فالوسمُ يُكتب ثم يُطمس بحسابٍ يليه.
        _demote = (bool(out.get("excluded_penalty"))
                   or bool(out.get("terminal_heavy"))
                   or bool(out.get("implausible")))
        out["confidence"] = ("منخفضة" if out.get("implausible")
                             else "مرتفعة" if len(vals) >= 3 and spread <= 0.25 and not _demote
                             else "متوسطة" if len(vals) >= 2 and spread <= 0.5
                             else "منخفضة")

        # ══ هامشُ الأمان — من تقديرٍ إلى قاعدةِ دخول ══ (بأمر المالك)
        # قال إنه يحدّد بها **وقت دخوله**. والقيمة العادلة وحدها لا تقول
        # ذلك: الشراء عندها يعني دفعَ كامل ما تستحقّه الشركة بشرط أن يكون
        # التقدير صائباً — وكلُّ تقييمٍ يخطئ.
        # وهامشُ الأمان (غراهام) هو الفرق المطلوب بين السعر والقيمة ليحتمل
        # التقديرُ خطأه. وهو هنا ليس رقماً ثابتاً بل **دالّةُ ثقة**: كلّما
        # اتّسع تشتّت المسارات أو قلّ عددها أو قدُمت أرقامها اتّسع الهامش
        # المطلوب. فالثقة المنخفضة تُترجَم إلى سعرٍ أدنى لا إلى تحذيرٍ
        # يُقرأ ويُنسى.
        mos = {"مرتفعة": 0.15, "متوسطة": 0.25}.get(out["confidence"], 0.35)
        if not out.get("has_dcf") and archetype not in NO_DCF:
            # مضاعفاتٌ بلا نموذج خصم: تقديرٌ نسبيّ يقيس ما يدفعه السوق
            # للنظائر، فيُطلب له هامشٌ أوسع.
            # ولا يُعاقَب النمطُ الذي لا يصحّ فيه الخصمُ أصلاً: غيابُ
            # النموذج فيه صوابٌ منهجيّ لا نقصُ بيانات، وتوسيعُ الهامش
            # عليه يرفع سعرَ دخول قطاعٍ كامل بلا سبب.
            mos += 0.05
        if (out.get("age_days") or 0) > 180:
            mos += 0.05                      # أرقامٌ تجاوزت نصف عام
        mos = min(mos, 0.45)
        out["margin_of_safety_pct"] = round(mos * 100)
        out["entry_price"] = round(out["value"] * (1 - mos), 2)
        out["entry_gap_pct"] = round((out["entry_price"] / price - 1) * 100, 1)
        # حكمٌ في كلمتين لا جملةٌ تشرح نفسها (بأمر المالك).
        out["entry_verdict"] = (
            "دون سعر الدخول" if price <= out["entry_price"] else
            "بلا هامش أمان" if price < out["value"] else
            "فوق القيمة العادلة")
    out["dropped_paths"] = _DROPPED["n"]
    _log_run(symbol, out, price, r, g)
    return out
