def _sane(value: float | None, price: float | None) -> float | None:
    """صحّةُ المسار في ذاته — لا بمقارنته بالسعر.

    ══ السعرُ كان يقرّر أيُّ المسارات ينجو ══ (كشفه `decision_check.py`)
    كان الشرطُ ‎`price × 0.40 ≤ value ≤ price × 2.50`، فيُسقَط كلُّ مسارٍ
    بعيدٍ عن السعر. وأثرُه — مقيسٌ على صندوقٍ عقاريّ واحد:

        سعر ‎30 → مسارُ الرسملة (‎10.0) يُسقَط، فتبقى ‎37.17 قيمةً معلَنة
        سعر ‎22 → المسارُ نفسُه ينجو، فتتضارب المسارات ونمتنع

    أي أن **القيمةَ الجوهرية صارت دالّةً في سعر السوق** — وهو نقيضُ ما
    وُجدت له: أن تكون مسطرةً مستقلّة يُقاس بها السعر. والانحيازُ منتظم:
    كلّما غلا السهمُ حُذف المسارُ القائل إنه أرخص، فتُنشر قيمةٌ أعلى؛
    وكلّما رخص نجا ذلك المسارُ فتضاربت المسارات وامتنعنا — أي أننا نصمت
    عند الفرصة وننطق عند الغلاء.

    فصار المسارُ يُفحص في ذاته: موجبٌ ومنتهٍ. والشذوذُ يُمسك بعدها
    بحارسين لا يعتمدان على السعر في **اختيار** المسارات:
      · تضاربُ المسارات ثلاثةَ أضعافٍ فأكثر ⇒ امتناعٌ صريح.
      · وحدُّ العقل يبقى على **النقطة المرجَّحة** وحدها بعد الترجيح —
        وهو حكمٌ على خلاصتنا لا على مدخلاتنا.
    """
    if value is None or value <= 0:
        return None
    if value != value or value in (float("inf"), float("-inf")):
        return None
    return round(value, 2)


