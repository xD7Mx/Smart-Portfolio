"""
فورمات قناة «صقر» — نظامُ تنسيقٍ واحد لكل رسالة.

## لماذا نظامٌ لا تنسيقٌ في كل موضع

الرسالة في تلغرام تُقرأ على شاشةٍ ضيّقة، بين رسائل أخرى، وبخطٍّ لا نتحكّم
فيه. فإن نُسِّقت كل رسالةٍ على حِدة اختلفت المسافات والعناوين بينها، وبدت
القناة كأنها من تطبيقات شتّى. هنا تُكتب القواعد مرّةً وتُبنى عليها الرسائل.

## القواعد التي أقرّتها لجنة القناة

١. **رأسٌ واحد**: أيقونةٌ واحدة + العنوان غليظاً + سطرُ فصل. لا أيقونات
   متناثرة في المتن — الأيقونة علامةُ قسمٍ لا زينة.
٢. **الأرقام في كتلةٍ ثابتة العرض** (`<pre>`): هي الطريقة الوحيدة التي
   تصطفّ بها خانات الآلاف في تلغرام. وبلا اصطفافٍ لا تُقارَن الأرقام
   بالنظر، وتصير القائمة نصّاً لا جدولاً.
٣. **العربية يميناً والأرقام لاتينية** — كما في التطبيق تماماً.
٤. **لحظة القياس في الذيل** (بند ٢٤): ما يُقرأ بعد ساعةٍ لا يُظنّ لحظياً.
٥. **لا سطر فارغ مزدوج**: الفراغ الزائد يجعل الرسالة تبدو مبعثرة على
   شاشة الجوّال.
٦. **الطول محدود**: تلغرام يقصّ عند ٤٠٩٦ حرفاً، والقصّ يقع في منتصف رقم.
   فالنصّ يُقصّ عندنا عند حدٍّ آمن وبعلامةٍ صريحة.
"""

import html
from datetime import datetime, timezone

MAX_LEN = 3800          # دون سقف تلغرام (٤٠٩٦) بهامشٍ يكفي الذيل
RULE = "──────────────"


def esc(v) -> str:
    return html.escape(str(v if v is not None else "—"))


def num(v, d: int = 0) -> str:
    """رقمٌ لاتينيّ بفواصل الآلاف — أو شرطةٌ إن غاب. لا يُختلق صفرٌ لغائب."""
    if v is None:
        return "—"
    try:
        return f"{float(v):,.{d}f}"
    except Exception:
        return "—"


def signed(v, d: int = 0) -> str:
    if v is None:
        return "—"
    try:
        f = float(v)
    except Exception:
        return "—"
    return ("+" if f >= 0 else "−") + f"{abs(f):,.{d}f}"


def stamp() -> str:
    return datetime.now(timezone.utc).astimezone().strftime("%Y-%m-%d · %H:%M")


def rows_block(pairs: list[tuple[str, str]]) -> str:
    """كتلةٌ ثابتة العرض: التسمية يميناً والقيمة تحاذي أخواتها.

    الحشو يُحسب من أطول تسمية، فتقف القيم على عمودٍ واحد مهما اختلفت
    أطوال الأسماء — وهذا ما يجعل الأرقام تُقارَن بالنظر لا بالقراءة.
    """
    if not pairs:
        return ""
    width = max(len(k) for k, _ in pairs)
    lines = [f"{k.rjust(width)}  {v}" for k, v in pairs]
    return "<pre>" + html.escape("\n".join(lines)) + "</pre>"


def card(icon: str, title: str, body: str, foot: str | None = None) -> str:
    """بطاقةٌ موحَّدة: رأسٌ · فصلٌ · متنٌ · ذيلُ لحظةِ القياس."""
    head = f"{icon} <b>{esc(title)}</b>\n{RULE}"
    # «قِيس» فعلٌ ماضٍ مبنيّ للمجهول — صحيحٌ لغةً وغريبٌ في سطر حاشية،
    # قرأه المالك كلمةً مبهمة بجانب التاريخ. والحاشية تُقرأ في لمحة فلا
    # تحتمل كلمةً تُستوقَف عندها. «بيانات» تقول المقصود بلا لَبس.
    tail = f"\n<i>{esc(foot or ('بيانات ' + stamp()))}</i>"
    out = f"{head}\n{body.rstrip()}{tail}"
    if len(out) > MAX_LEN:
        # القصّ بعلامةٍ صريحة: نصٌّ ينتهي فجأةً يُقرأ عطباً، والصمت عن
        # القصّ يجعل المالك يظنّ أنه رأى كل شيء.
        keep = MAX_LEN - len(head) - len(tail) - 40
        out = f"{head}\n{body[:max(0, keep)].rstrip()}\n… <i>(بقيّةُ النصّ في التطبيق)</i>{tail}"
    return out


def reply(body: str, foot: str | None = None) -> str:
    """جوابٌ مباشر: المتن وحده وذيلُ اللحظة — بلا رأسٍ ولا خطّ فصل.

    البطاقة (`card`) لعناوينِ **أقسام**: «الثروة» و«تحليل السوق» و«المفكرة»
    تسمّي محتوىً لم يطلبه السائل بلفظه، فالعنوان فيها يفيد. أمّا جوابُ سؤالٍ
    سأله المالك للتوّ فعنوانه معروف — هو سؤاله. وكان الجواب يُصدَّر بأيقونةِ
    صقرٍ واسمِ «صقر يجيب» وخطٍّ عريض: البوت يُعلن عن نفسه قبل أن يقول شيئاً،
    وثلاثةُ أسطرٍ من المراسم قبل سطرٍ من الفائدة. وصفه المالك بالابتذال.

    والتناسق لا ينكسر بهذا: الذيل نفسه، والتهذيب نفسه، والحدّ نفسه — يسقط
    الرأس وحده.
    """
    out = f"{body.rstrip()}\n<i>{esc(foot or ('بيانات ' + stamp()))}</i>"
    if len(out) > MAX_LEN:
        tail = f"\n<i>{esc(foot or ('بيانات ' + stamp()))}</i>"
        keep = MAX_LEN - len(tail) - 40
        out = (f"{body[:max(0, keep)].rstrip()}"
               f"\n… <i>(بقيّةُ النصّ في التطبيق)</i>{tail}")
    return out


def bullet(items: list[str]) -> str:
    """قائمةٌ نقطية — سطرٌ لكل عنصر بلا فراغٍ بينها."""
    return "\n".join(f"• {i}" for i in items)


def numbered(items: list[str]) -> str:
    return "\n".join(f"{i+1}. {t}" for i, t in enumerate(items))
