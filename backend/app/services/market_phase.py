"""طورُ جلسة تداول — قاعدةٌ واحدةٌ تُقاس.

كانت الأوقاتُ مكتوبةً داخل نقطة `/settings/server-time` ومنسوخةً في
`utils/marketHours.ts`، وكلتاهما خاطئة: الجلسةُ حُسبت ‎10:00–14:30 والإغلاق
‎15:00 — فقال التطبيقُ «قبل الإغلاق» ونصفُ ساعةٍ من الجلسة باقية، و«السوق
مغلق» وعشرون دقيقةً من مزاد الإغلاق قائمة. رآه المالك.

وجدولُ «تداول» الحقيقيّ (الأحد–الخميس، بتوقيت مكة):
    09:30 – 10:00   مزادُ الافتتاح
    10:00 – 15:00   التداولُ المستمرّ
    15:00 – 15:10   مزادُ الإغلاق
    15:10 – 15:20   التداولُ عند سعر الإغلاق
    بعد 15:20       مغلق

فأُخرجت القاعدةُ إلى هنا: دالّةٌ خالصةٌ بلا وقتٍ ولا شبكة، تُستدعى من
النقطة ويقيسها الفحصُ دقيقةً دقيقة. والنسخةُ في الواجهة تبقى (تعمل حين
ينقطع الخادم) ويحرس الفحصُ تطابقَ حدودها معها.
"""
from __future__ import annotations

PRE_OPEN = 9 * 60 + 30      # 09:30 — مزادُ الافتتاح
OPEN = 10 * 60              # 10:00 — التداولُ المستمرّ
PRE_CLOSE = 15 * 60         # 15:00 — مزادُ الإغلاق
CLOSE = 15 * 60 + 20        # 15:20 — انتهاءُ كلّ تداول


def market_phase(dow_sun0: int, minutes: int) -> str:
    """`dow_sun0`: 0=الأحد … 6=السبت. `minutes`: دقائقُ اليوم بتوقيت مكة."""
    if not (0 <= dow_sun0 <= 4):        # الجمعةُ والسبتُ عطلة
        return "closed"
    if PRE_OPEN <= minutes < OPEN:
        return "pre"
    if OPEN <= minutes < PRE_CLOSE:
        return "open"
    if PRE_CLOSE <= minutes < CLOSE:
        return "preclose"
    return "closed"
