"""الخطوطُ الحمراء — وقائعُ تُبطِل الترتيبَ ولا تُخصم منه.

## لماذا مع الترتيب لا بدلاً منه

الترتيبُ في القطاع (‏`peer_distribution`) يحلّ مشكلةَ العتبات المخترَعة،
لكنّه **نسبيّ**: أسوأُ قطاعٍ في السوق يبقى فيه «الأفضل»، فتخرج شركةٌ
خاسرةٌ ثلاثَ سنواتٍ بدرجةٍ عالية لأن أقرانها أسوأ. وذلك أخطرُ من
العتبة المخترَعة، لا أقلّ.

فيلزم بجانبه حفنةٌ من الوقائع **المطلقة**: لا تحتاج معايرةً ولا مقارنةً
ولا رأياً، ولا يختلف عليها اثنان. ومن وقع في واحدةٍ منها **لا يُرتَّب** —
يُستبعد ويُقال السبب. لأن الخصمَ من درجةٍ يذوب في المتوسّط، والاستبعادُ
لا يذوب.

## لماذا هذه بالذات

كلُّ سطرٍ هنا واقعةٌ يقرؤها أيُّ مستثمرٍ حكماً في ذاته لا مؤشّراً يُوزن:

  · **خسارةٌ ثلاثَ سنواتٍ متتالية** — لا يُقيَّم عملٌ لم يثبت أنه عمل.
  · **تدفّقٌ تشغيليّ سالبٌ خمسَ سنوات** — الربحُ المحاسبيّ بلا نقدٍ
    خمسَ سنوات ليس ربحاً، والشركةُ تعيش على تمويلٍ خارجيّ.
  · **تغطيةُ فوائدَ دون الواحد** — الأرباحُ التشغيلية لا تكفي فائدةَ
    الدين. هذه حالةُ إعسارٍ فنّيّ لا ضعفُ أداء.
  · **توزيعٌ يفوق الأموالَ من العمليات سنتين** (للريت) — الصندوق يوزّع
    من دَينه أو من بيع أصوله، أي يوزّع رأسَ مالك عليك ويسمّيه دخلاً.
  · **تخفيفٌ يفوق ‎20٪ في ثلاث سنوات** — حصّتُك في الشركة تتقلّص بلا أن
    تُسأل. وهو أخطرُ ما يصيب حائزاً طويلَ الأجل، ولا يظهر في أيّ نسبةِ
    ربحية.
  · **حقوقُ ملكيةٍ سالبة** — الالتزاماتُ تفوق الأصول.

ولا يُشعَل خطٌّ أحمر على بيانٍ ناقص: من لا تصل سلسلتُه لا يُدان بها.
"""

from __future__ import annotations


# ══ الخطُّ الأحمر يُنسب إلى نموذج العمل ══ (قرارُ مجلس نِصاب)
#
# سلّم المالكُ المجلسَ إطاراً مهنيّاً، ونصُّ الإطار نفسه في صدر ورقة
# الصيغ: «العتباتُ استرشادية وتتغيّر حسب القطاع — استخدم أقرانَ الصناعة
# لا أرقاماً مطلقة». فأخذتُ عتباتِه موحَّدةً على الأنماط كلِّها، وذلك
# خلافُه لا اتّباعُه. والإطارُ وسيلةٌ للمجلس لا بديلٌ عنه: هو عامّ،
# والمجلسُ يضع كلَّ قطاعٍ حيث يليق به.
#
# وقِيس الأثر:
#   · **بنكٌ سليمٌ نامٍ** خرج بثلاثة خطوطٍ حمراء. ونموُّ دفتر القروض
#     يظهر تدفّقاً تشغيليّاً **سالباً** وهو نموٌّ صحّيّ لا ضعف — وهو
#     الدرسُ نفسه الذي تعلّمه محرّكُ التقييم من قبل (‏D031) ثم أعدتُه
#     هنا. ورافعةُ البنك نموذجُه لا عيبُه.
#   · **ريتٌ سليم برافعة ‎6.3×** أُدين، والصناديقُ العقارية تعمل عند
#     ‎5–7× مقابل إيجاراتٍ متعاقدة. والإطارُ نفسه يقول «‎3–4× مرتفع
#     **حسب القطاع**».
#
# فما يُستثنى يُستثنى لسببٍ بنيويّ في القائمة لا تساهلاً:

# خطوطٌ لا تُستثنى لأحد — وقائعُ لا يغيّرها نموذجُ عمل
_UNIVERSAL = ("loss_streak", "negative_equity")

# مقامُ التدفّق التشغيليّ مشوّهٌ بنيوياً في هذه الأنماط: نموُّ دفتر
# القروض والأقساط والمخزون العقاريّ يقع كلُّه في القسم التشغيليّ.
_NO_CASHFLOW_LINES = {
    "bank": ("no_cash", "no_fcf", "accruals"),
    "financial": ("no_cash", "no_fcf", "accruals"),
    "insurance": ("no_cash", "no_fcf", "accruals"),
    # المطوّرُ والمقاول: الأرضُ والمشاريعُ تحت التنفيذ أصولٌ تشغيلية،
    # فبناؤها يستهلك النقدَ سنواتٍ وهو عينُ نموذج العمل.
    # والمطوّرُ يُستثنى من «فجوة الربح والنقد» للسبب نفسه: الفجوةُ هي
    # المخزونُ العقاريّ، ونسبةُ الاستحقاق تقيسها فتُدين نموذجَ العمل.
    "re_developer": ("no_cash", "no_fcf", "accruals"),
    "contracting": ("no_fcf",),
}

# تغطيةُ الفوائد بلا معنًى حيث تكون الفائدةُ كلفةَ المُدخَل لا عبءَ دَين
_NO_INTEREST_LINE = ("bank", "financial", "insurance")

# سقفُ الدَّين إلى الأرباح التشغيلية — الإطارُ يقول «حسب القطاع»
_DEBT_CAP = {
    "reit": 8.0,            # إيجاراتٌ متعاقدة تسند رافعةً أعلى
    "capital_infra": 8.0,   # دخلٌ منظَّمٌ أو متعاقَد طويل الأجل
}
_DEBT_CAP_NA = ("bank", "financial", "insurance")   # الرافعةُ نموذجُها


def _val(features: dict, key: str):
    raw = (features or {}).get(key)
    v = raw.get("value") if isinstance(raw, dict) else raw
    return v if isinstance(v, (int, float)) else None


# ══ الخطُّ الأحمر واقعةٌ ثابتة لا لقطةُ سنة ══ (كشفه المسبار — D127)
#
# كلُّ خطٍّ في هذا الملف يشترط ثباتاً: خسارةُ ثلاثِ سنوات · تدفّقٌ سالبٌ
# ثلاثاً · استحقاقٌ ثلاثاً. إلّا خطَّي الرافعة، فكانا يُقرآن من **سنةٍ
# واحدة**: `interest_coverage[-1]` و`net_debt_ebitda` من آخر فترة. فسنةٌ
# دوريّةٌ ضعيفة أو مخصّصٌ لمرّةٍ واحدة يُشعل خطّاً يقول «إعسارٌ فنّيّ»
# ويُبطل الحكمَ كلَّه. وقِيس على السوق: ‎62 شركةً بـ`interest_thin`
# و‎43 بـ`debt_over_six` — ‎105 إشعالاتٍ من أصل ‎212.
#
# فصارا يشترطان الثبات: الحالُ في آخر سنةٍ **وفي أغلب المتاح**.
#
# ══ ولا يُشعَل على تقدير ══
#
# `sector_metrics._ebitda_of` يستبدل الربحَ التشغيليَّ بالأرباح قبل
# الإهلاك حين يغيب الإهلاك، وتبريرُه «أشدُّ تحفّظاً — وعند الشكّ يُخفَّض».
# وذلك صحيحٌ **لدرجةٍ تُرتَّب** وباطلٌ **لخطٍّ يُبطِل**: التحفّظُ يخفض
# تقديراً، أمّا الخطُّ فيوجّه تهمةً لا تُراجَع. ومقامٌ أصغر يرفع النسبةَ
# فوق الحدّ بلا أن يكون الدَّينُ ثقيلاً.
#
# فللخطّ حسابُه الصارم: لا رقمَ إلّا من بندٍ منشور.

_IC_FLOOR = 1.5          # الإطارُ المهنيّ — تغطيةٌ دونها إعسارٌ فنّيّ


def _ebitda_strict(p: dict) -> float | None:
    """أرباحٌ قبل الإهلاك بلا استبدال — للخطّ الأحمر وحده.

    إمّا بندُ `ebitda` كما ورد، أو الربحُ التشغيليّ **مع** إهلاكٍ واصل.
    وحين يغيب الإهلاك يُعاد `None` فلا يُشعَل خطّ — لا لأن الشركة سليمة،
    بل لأنّ الرقمَ الذي يُدينها لم يصل.
    """
    v = p.get("ebitda")
    if isinstance(v, (int, float)):
        return float(v)
    op, dep = p.get("operating_income"), p.get("depreciation")
    if isinstance(op, (int, float)) and isinstance(dep, (int, float)):
        return float(op) + abs(float(dep))
    return None


def _coverage_of(p: dict) -> float | None:
    """تغطيةُ الفوائد لفترةٍ بعينها — من المشتقّ أو من البندين الخامين.

    مصدرُنا يشتقّ `interest_coverage` لبعض الفترات ويتركها لأخرى، والبندان
    (‏الربحُ التشغيليّ · مصروفُ الفائدة) حاضران في الحالتين. فالاعتمادُ
    على المشتقّ وحده يُسقط الخطَّ صامتاً حيث تكون البياناتُ كاملة.
    وشركةٌ بلا فائدةٍ تُعيد `None` فلا تُدان: لا دَينَ فلا تغطية.
    """
    v = p.get("interest_coverage")
    if isinstance(v, (int, float)):
        return float(v)
    op, ie = p.get("operating_income"), p.get("interest_expense")
    if isinstance(op, (int, float)) and isinstance(ie, (int, float)) and ie:
        return float(op) / abs(float(ie))
    return None


def _net_debt(p: dict) -> float | None:
    d = p.get("total_debt")
    if not isinstance(d, (int, float)):
        return None
    c = p.get("ending_cash")
    if not isinstance(c, (int, float)):
        c = p.get("cash") if isinstance(p.get("cash"), (int, float)) else 0
    return abs(float(d)) - float(c)


def _persistent(vals: list[float], bad) -> bool:
    """أهي حالُ الشركة أم سنةٌ عابرة؟

    تُشترط الحالُ في آخر سنةٍ **وفي أغلب المتاح**: من ثلاث سنواتٍ فأكثر
    تلزم اثنتان من آخر ثلاث، ومن سنتين تلزمان معاً. وسنةٌ واحدةٌ لا
    تكفي — لقطةٌ لا واقعة.
    """
    if len(vals) < 2 or not bad(vals[-1]):
        return False
    if len(vals) == 2:
        return bad(vals[0])
    return sum(1 for v in vals[-3:] if bad(v)) >= 2


def check(features: dict, periods: list[dict] | None,
          archetype: str | None = None) -> list[dict]:
    """الخطوطُ التي اشتعلت — كلٌّ برسالته وبالرقم الذي أشعله."""
    periods = periods or []
    fired: list[dict] = []

    skip = set(_NO_CASHFLOW_LINES.get(archetype or "", ()))
    if archetype in _NO_INTEREST_LINE:
        skip.add("interest_thin")
    if archetype in _DEBT_CAP_NA:
        skip.add("debt_over_six")

    def add(kid: str, msg: str):
        if kid in skip and kid not in _UNIVERSAL:
            return
        fired.append({"id": kid, "message": msg})

    # ── خسارةٌ ثلاثَ سنواتٍ متتالية ──
    nis = [p.get("net_income") for p in periods
           if isinstance(p.get("net_income"), (int, float))]
    if len(nis) >= 3:
        streak = 0
        for v in reversed(nis):
            if v < 0:
                streak += 1
            else:
                break
        if streak >= 3:
            add("loss_streak", f"خسارةٌ {streak} سنواتٍ متتالية")

    # ── حقوقُ ملكيةٍ سالبة ──
    eqs = [p.get("total_equity") if p.get("total_equity") is not None else p.get("equity")
           for p in periods]
    eqs = [e for e in eqs if isinstance(e, (int, float))]
    if eqs and eqs[-1] < 0:
        add("negative_equity", "حقوقُ الملكية سالبة — الالتزاماتُ تفوق الأصول")

    # ══ العتباتُ تتبع الإطارَ المؤسسيّ لا اختياري ══
    # كانت أشدَّ تساهلاً من الإطار المهنيّ الذي اعتمده المالك: تدفّقٌ سالب
    # خمسَ سنواتٍ بدل ثلاث، وتغطيةُ فوائدَ دون الواحد بدل ‎1.5. وقاعدةُ
    # الإطار صريحة: «عند الشك يُخفَّض التقييم لا يُرفَع». فأُخذت عتباتُه
    # لأنها معيارٌ مهنيّ منشور، لا رقمٌ اخترتُه.

    # ── تدفّقٌ تشغيليّ سالبٌ ثلاثَ سنوات ──
    ocf = [p.get("operating_cash_flow") for p in periods
           if isinstance(p.get("operating_cash_flow"), (int, float))]
    if len(ocf) >= 3 and all(v < 0 for v in ocf[-3:]):
        add("no_cash", "تدفّقٌ تشغيليّ سالبٌ ثلاثَ سنواتٍ متّصلة")

    # ── تدفّقٌ حرٌّ سالبٌ ثلاثَ سنوات ──
    fcf = [p.get("free_cash_flow") for p in periods
           if isinstance(p.get("free_cash_flow"), (int, float))]
    if len(fcf) >= 3 and all(v < 0 for v in fcf[-3:]):
        add("no_fcf", "تدفّقٌ نقديّ حرٌّ سالبٌ ثلاثَ سنواتٍ متّصلة")

    # ── تغطيةُ فوائدَ دون ‎1.5 سنةً بعد سنة ──
    ics = [c for c in (_coverage_of(p) for p in periods) if c is not None]
    if _persistent(ics, lambda v: v < _IC_FLOOR):
        n_bad = sum(1 for v in ics[-3:] if v < _IC_FLOOR)
        add("interest_thin",
            f"الأرباحُ التشغيلية لا تغطّي فائدةَ الدين — تغطية "
            f"{ics[-1]:.2f}× في آخر سنة، ودون {_IC_FLOOR}× في "
            f"{n_bad} من آخر {min(len(ics), 3)}")

    # ── الدَّينُ فوق سقف نمطه سنةً بعد سنة ──
    _cap = _DEBT_CAP.get(archetype or "", 6.0)
    ndes, dry = [], 0
    for p in periods:
        eb, nd = _ebitda_strict(p), _net_debt(p)
        if eb is None or nd is None:
            continue
        if eb > 0:
            ndes.append(nd / eb)
        elif nd > 0:
            dry += 1          # دَينٌ قائمٌ بلا أرباحٍ تشغيلية أصلاً
    if _persistent(ndes, lambda v: v > _cap):
        n_bad = sum(1 for v in ndes[-3:] if v > _cap)
        add("debt_over_six",
            f"صافي الدين يعادل {ndes[-1]:.1f}× الأرباحَ التشغيلية "
            f"(حدُّ هذا النمط {_cap:.0f}×) — وفوقه في {n_bad} من آخر "
            f"{min(len(ndes), 3)}")
    elif dry >= 3:
        # ══ ثغرةٌ كان يفلت منها الأسوأ ══
        # الحسابُ القديم يشترط `ebitda > 0`، فمن لا أرباحَ تشغيلية له
        # أصلاً لا تُحسب نسبتُه فلا يُشعِل خطّاً — فينجو من الرافعة من
        # هو أعجزُ عن حملها. والدَّينُ القائم بلا أرباحٍ ثلاثَ سنواتٍ
        # واقعةٌ أشدُّ من أيّ نسبة.
        add("debt_over_six",
            f"دَينٌ قائمٌ بلا أرباحٍ تشغيلية {dry} سنواتٍ — لا مصدرَ "
            f"لخدمته من النشاط")

    # ══ فجوةٌ مستمرّة بين الربح والنقد — إنذارٌ محاسبيّ ══
    # نسبةُ الاستحقاق (‏صافي الربح − التدفّق التشغيليّ ÷ الأصول) محسوبةٌ
    # عندنا منذ حين وغائبةٌ عن كل بطاقة. وموضعُها في الإطار المهنيّ ليس
    # مؤشّراً موزوناً بل **إنذاراً محاسبياً**: ربحٌ لا يتبعه نقدٌ سنواتٍ
    # متّصلة ليس ضعفَ أداء بل شكّاً في جودة الأرقام نفسها.
    accr = []
    for p in periods[-3:]:
        ni, o, ta = (p.get("net_income"), p.get("operating_cash_flow"),
                     p.get("total_assets"))
        if all(isinstance(x, (int, float)) for x in (ni, o, ta)) and ta:
            accr.append((ni - o) / ta * 100)
    if len(accr) >= 3 and all(a > 10 for a in accr):
        add("accruals",
            f"الربحُ يفوق التدفّقَ التشغيليّ ثلاثَ سنواتٍ بفارقٍ يعادل "
            f"{sum(accr) / len(accr):.0f}٪ من الأصول")

    # ══ تخفيفُ الحصّة: يُخفض ولا يُبطِل ══ (D127)
    #
    # كان خطّاً أحمر يشتعل على ‎23 شركة. وعددُ الأسهم وحده **لا يُثبت**
    # التخفيف في تداول: أسهمُ المنحة ترفع العدد وحصّتُك كما هي، وحقُّ
    # الأولوية يُعرض عليك قبل غيرك. وبيانُنا لا يميّز المنحةَ من إصدارٍ
    # لطرفٍ ثالث — فهو شاهدٌ لا يقطع.
    #
    # والخطُّ الأحمر يوجّه تهمةً لا تُراجَع، فلا يُبنى على شاهدٍ ظنّيّ.
    # والإشارةُ لا تضيع: `governance_pillar` يعرضها ركناً مقروءاً
    # («تخفيفُ الحصّة ٣ سنوات») فتُخفض الدرجةَ ويراها المستثمر.

    # ── الريت: توزيعٌ يفوق الأموالَ من العمليات ──
    if archetype == "reit":
        over = 0
        for p in periods[-3:]:
            ni = p.get("net_income")
            dep = p.get("depreciation") or 0
            gain = p.get("gain_on_asset_sale") or 0
            dv = p.get("dividends_paid")
            if isinstance(ni, (int, float)) and isinstance(dv, (int, float)) and dv:
                ffo = ni + dep - gain
                # وأموالٌ من العمليات غيرُ موجبة مع توزيعٍ قائم أشدُّ من
                # تجاوزها: الصندوق يوزّع ولا دخلَ تشغيلياً يوزّع منه.
                if ffo <= 0 or abs(dv) > ffo:
                    over += 1
        if over >= 2:
            add("payout_over_ffo",
                "التوزيعُ يفوق الأموالَ من العمليات سنتين — يُموَّل بدَينٍ "
                "أو ببيع أصول")

    return fired
