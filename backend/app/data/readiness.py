"""شروطُ جاهزية القرار الاستثماريّ — مذكّرةُ التفاهم في صورةِ أرقام.

## لماذا ملفٌّ لا فقرةٌ في وثيقة

عقد المجلسُ واللجنةُ المالية مذكّرةَ تفاهمٍ لإنهاء جاهزية القرار
(‏`docs/GOVERNANCE.md` — القسم ٤). ومذكّرةٌ نصّيةٌ وحدها تُقرأ مرّةً ثم
يختلف الطرفان في تفسيرها، فتصير الجاهزيةُ رأياً يُتنازع فيه — وهو ما وقع
مراراً في هذا المشروع: يُسأل «أجاهزٌ القرار؟» فيُجاب بتقديرٍ لا بقياس.

فالشروطُ هنا **أرقامٌ يقرؤها البرنامج**: يقيسها `probe_real.py` على
السوق الحقيقيّ ويطبع لكلّ شرطٍ «اجتاز» أو «أخفق». فلا يبقى للاجتهاد
موضع، ولا تُبنى حزمةٌ على انطباع.

## لماذا هذه الشروط بعينها

كلُّ شرطٍ أدناه وُضع بعد عطبٍ وقع فعلاً وسُجّل في `registry.json`:

  · **نسبةُ الحكم** — أداةٌ تمتنع عن نصف السوق ليست جاهزة مهما صحّت
    أحكامُها في النصف الآخر.
  · **حصّةُ «تجنّب»** — قِيست ‎52٪ ثم ‎43٪. و«تجنّب» حكمٌ يقول إن الشركة
    رديئة، ولا يجوز أن يصيب أربعين بالمئة من سوقٍ منظَّم. (‏D121 · D122)
  · **وجودُ «شراء قوي»** — انهار إلى شركتين حين ضُبطت العتبةُ على توزيعٍ
    مفترَض. وأداةٌ لا تجد أفضلَ عشرين اسماً في السوق لا تُعين على قرار.
    (‏D124)
  · **تماسكُ الحكم مع أرقامه** — لا «شراء» فوق قيمتنا العادلة. وهو أوّلُ
    عطبٍ عرضه المالك في هذا المشروع.
  · **صمتُ الخطّ الأحمر عن السليم** — الخطُّ يُبطِل الحكمَ كلَّه، فإشعالُه
    على نموذج عملٍ سليم يُسقط قطاعاً بأكمله. (‏D109)

والحدودُ أدناه ليست مثالية بل **مقبولةٌ للتسليم**: دونها لا تُبنى حزمة،
وفوقها يبقى التحسينُ مطلوباً ولا يُوقف العمل.
"""

from __future__ import annotations

# ── شروطُ القبول ──────────────────────────────────────────────────────
# لكلّ شرط: (المفتاح، الوصف، الحدّ، الاتّجاه)
# الاتّجاه: "min" الحدُّ أدنى مقبول · "max" الحدُّ أعلى مقبول
ACCEPTANCE = (
    ("verdict_share", "نسبةُ الشركات التي تُنتج حكماً قابلاً للقراءة",
     0.75, "min"),
    ("avoid_share", "حصّةُ «تجنّب» من الأحكام الصادرة",
     0.30, "max"),
    ("strong_buy_count", "عددُ أسماء «شراء قوي» في السوق",
     5, "min"),
    ("buy_share", "حصّةُ «شراء» و«شراء قوي» معاً",
     0.05, "min"),
    ("contradictions", "أحكامُ شراءٍ فوق القيمة العادلة المعروضة معها",
     0, "max"),
    ("red_on_healthy", "خطوطٌ حمراء على أنماطٍ سليمة في فحص الرتبة",
     0, "max"),
)

# ── ما يُقاس ولا يُشترط ──────────────────────────────────────────────
# أرقامٌ تُعرض في كل قياسٍ لأن اتّجاهها يُنذر، ولا يُوقف التسليمَ حدٌّ
# فيها: هي وصفٌ لحال السوق وبياناتِه لا حكمٌ على محرّكنا.
OBSERVED = (
    ("abstain_no_value", "امتناعٌ لتعذّر القيمة العادلة"),
    ("abstain_thin", "امتناعٌ لنقص البيانات"),
    ("quality_median", "وسيطُ درجة الجودة في السوق"),
    ("periods_median", "وسيطُ عدد القوائم المالية المتاحة"),
)


def evaluate(stats: dict) -> tuple[bool, list[dict]]:
    """يقيس شروطَ القبول على إحصاءٍ مقيس، ويعيد (اجتاز، التفصيل)."""
    rows, ok_all = [], True
    for key, label, limit, direction in ACCEPTANCE:
        v = stats.get(key)
        if v is None:
            rows.append({"key": key, "label": label, "limit": limit,
                         "value": None, "ok": False, "note": "لم يُقَس"})
            ok_all = False
            continue
        ok = (v >= limit) if direction == "min" else (v <= limit)
        ok_all = ok_all and ok
        rows.append({"key": key, "label": label, "limit": limit,
                     "value": v, "ok": ok,
                     "note": ("حدٌّ أدنى" if direction == "min" else "حدٌّ أعلى")})
    return ok_all, rows
