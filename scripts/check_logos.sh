#!/bin/sh
# ══════════════════════════════════════════════════════════════════════
#  فحص شعارات الشركات — أيّ رابطٍ لا يردّ؟
#
#  خريطة الشعارات في المشروع سليمة البنية (٣٩٢ مدخلاً، بلا رابطٍ شاذّ ولا
#  مكرَّر)، فإن لم يظهر شعارُ شركةٍ فالسبب عند المصدر: الرابط يردّ ٤٠٤ لأن
#  اسمه المُخمَّن لا يطابق ما عند تريدنغ‑فيو. لا يُعرف ذلك إلا بسؤال الشبكة،
#  وهذا ما يفعله هذا السكربت: يسأل عن كل رابطٍ ويطبع من سقط.
#
#  يُشغَّل على الخادم (حيث الإنترنت):
#      sh scripts/check_logos.sh
#  ثم أرسل لي المخرَج، فتُصحَّح الروابط الساقطة بالدليل لا بالتخمين.
# ══════════════════════════════════════════════════════════════════════
set -u
MAP=frontend/src/data/tradingviewLogos.ts
[ -f "$MAP" ] || { echo "لم يُعثر على $MAP — شغّله من جذر المشروع."; exit 1; }

total=0; bad=0
echo "يفحص شعارات الشركات… (قد يستغرق دقيقة)"
echo
# كل سطرٍ فيه "رمز": "رابط"
grep -oE '"[0-9]{4}": "[^"]+"' "$MAP" | while IFS= read -r line; do
  sym=$(echo "$line" | cut -d'"' -f2)
  url=$(echo "$line" | cut -d'"' -f4)
  code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 8 "$url")
  total=$((total+1))
  if [ "$code" != "200" ]; then
    bad=$((bad+1))
    echo "  ساقط [$code]  $sym  →  $url"
  fi
done

echo
echo "انتهى. الأسطر أعلاه (إن وُجدت) هي الشعارات التي لا تُحمَّل."
echo "لا شيء أعلاه = كل الشعارات تعمل، والمشكلة عندئذٍ في الشبكة لا في الروابط."
