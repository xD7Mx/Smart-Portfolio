#!/usr/bin/env bash
# ══ بوّابةُ الذاكرة (D716) ══
# الخادمُ ‎909‎ م.ب ذاكرةً لا أكثر. قِيس (2026-10-14): اجتمع في دورة النشر بناءُ الواجهة ولجنةٌ كاملةٌ في حاويةٍ ثانية فوق
# حصاد القوائم ومسحة التقييم وإقلاعِ الخادم، فنفدت الذاكرةُ والتبادلُ معاً وقتلت النواةُ ‎uvicorn‎ — وتوقّف التطبيقُ حتى أُعيد
# الخادم. فلا يبدأ عملٌ ثقيلٌ إلا والخادمُ قد أكمل إقلاعَه (يردّ على الصحة) والمتاحُ يتّسع له؛ وإلا قيل ذلك ولم يُشغَّل.
#     bash scripts/ops/mem_gate.sh <أدنى متاحٍ بالميغابايت> <الوصف> [ثواني انتظار الخادم]
need="${1:?أدنى المتاح}"; what="${2:-عملٌ ثقيل}"; wait_s="${3:-900}"
t=0
until curl -sf -m 5 -o /dev/null http://localhost/api/v1/health; do
  if [ "$t" -ge "$wait_s" ]; then
    echo "✘ الخادمُ لم يُكمل إقلاعَه بعد ${wait_s}ث — لا يُشغَّل ${what} (الخادمُ أولى)"; exit 1
  fi
  sleep 10; t=$((t + 10))
done
avail=$(awk '/^MemAvailable:/{print int($2/1024)}' /proc/meminfo 2>/dev/null)
if [ "${avail:-0}" -lt "$need" ]; then
  echo "✘ المتاحُ من الذاكرة ${avail:-?} م.ب دون ${need} — لا يُشغَّل ${what} الآن (الخادمُ أولى)"; exit 1
fi
echo "• الخادمُ يردّ والمتاحُ ${avail} م.ب (≥ ${need}) — يُشغَّل ${what}"
