# تخرج بـ0 إن نظُف كل شيء، وبـ1 إن وُجدت ملاحظة — فتصلح **بوّابةً قبل بناء
# الحزمة**: لا يُسلَّم ما لم يجتز فحص اللجنة.
# ─────────────────────────────────────────────────────────────────────────
set -u
