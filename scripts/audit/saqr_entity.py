#!/usr/bin/env python3
# ─────────────────────────────────────────────────────────────────────────
# D222 — صقرٌ لا ينفي شركةً في يده.
#
# ## ما رآه المالك
# سأل: «ماذا تنصح من كان لديه سهم **العثيم**؟» فأجاب صقر: «لا يوجد سهم
# أسواق عبد الله العثيم ضمن مراكز محفظتك، ولا ضمن بيانات السوق» — والسهمُ
# ظاهرٌ في الشاشة خلف النافذة (‏4001).
#
# ## الجذر
# اختيارُ صفوف السوق للسياق كان مطابقةً **نصّيةً خاماً**: `الاسم in السؤال`،
# فتشترط ورودَ «أسواق عبدالله العثيم» كاملةً. والمالكُ يقول «العثيم» كما
# يقول الناس. فلم تصل الشركةُ إلى صقر أصلاً — ونفيُه صادقٌ عن سياقٍ
# أعميناه نحن. أمّا نفيُه عن **المحفظة** فخطؤه هو: المراكزُ تصل كاملةً،
# لكنّ النموذج يمسح سياقاً طويلاً فينفي ما لم يره.
#
# ## العلاج المقيس هنا
#   ١· مطابقةٌ مُطبَّعةٌ على كلمةٍ مميّزة — لا على الاسم كاملاً
#   ٢· ولا تُطابِق كلمةٌ عامّة شركةً لم تُذكر (الاتّجاه المعاكس)
#   ٣· وتُحسم الشركةُ حتمياً وتُوضع في مفتاحٍ مستقلٍّ لا يُخطئه النموذج
#   ٤· وقاعدةٌ تُحرّم نفيَ وجودها
# ─────────────────────────────────────────────────────────────────────────
from __future__ import annotations

import os as _os, tempfile as _tf
_SANDBOX = _tf.mkdtemp(prefix="sp-audit-")
_os.environ["LASTGOOD_PATH"] = _os.path.join(_SANDBOX, "lastgood.json")
_os.environ["SP_STATE_DIR"] = _SANDBOX

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, "/app")

from app.services.ai_chat import _mentions          # noqa: E402
from app.services.ai_analyst import resolve_company  # noqa: E402

fail = 0


def check(ok: bool, label: str, detail: str = "") -> None:
    global fail
    if not ok:
        fail = 1
    print(f"{'PASS' if ok else 'FAIL'} {label}" + (f" — {detail}" if detail else ""))


Q = "بناء على البيانات المتاحة لديك ماذا تنصح من كان لديه سهم العثيم هل يتخلص منه ؟"

# ── ١ · الاسمُ الجزئيُّ يُطابِق — وهو نصُّ سؤال المالك بعينه ───────────
check(_mentions(Q, "أسواق عبدالله العثيم", "4001"),
      "١ «العثيم» تُطابِق «أسواق عبدالله العثيم»")

# ── ٢ · الاتّجاه المعاكس: لا تُطابَق شركةٌ لم تُذكر ────────────────────
# لولا هذا لصار العلاجُ أسوأ من العطب: سؤالٌ عن شركةٍ يُجاب عن أخرى.
others = [("بنك الرياض", "1010"), ("الأسمنت السعودية", "3030"),
          ("التعدين العربية السعودية", "1211"), ("الصناعات الكهربائية", "1303")]
wrong = [n for n, s in others if _mentions(Q, n, s)]
check(not wrong, "٢ ولا تُطابَق شركةٌ لم تُذكر في السؤال",
      " · ".join(wrong) if wrong else "لا مطابقةَ زائفة")

# ── ٣ · الرمزُ الرقميُّ يُطابِق كما هو ────────────────────────────────
check(_mentions("حلّل لي 4001 من فضلك", "أسواق عبدالله العثيم", "4001"),
      "٣ الرمزُ الرقميُّ يُطابِق")

# ── ٤ · التطبيعُ يتجاوز اختلافَ الهمزة والتاء ─────────────────────────
check(_mentions("رأيك في أسواق عبد الله العثيم", "أسواق عبدالله العثيم", "4001"),
      "٤ «عبد الله» و«عبدالله» شيءٌ واحد")

# ── ٥ · الحسمُ يجد الشركةَ في المراكز ─────────────────────────────────
CTX = {"المحفظة": {"المراكز": [
    {"الشركة": "أسواق عبدالله العثيم", "الرمز": "4001", "الكمية": 500},
    {"الشركة": "بنك الرياض", "الرمز": "1010", "الكمية": 300}]}}
hit = resolve_company(Q, CTX) or {}
check(hit.get("symbol") == "4001" and hit.get("source") == "حيازة",
      "٥ الحسمُ يجدها في المراكز", f"{hit.get('name')} · {hit.get('symbol')}")

# ── ٦ · وتُوضع في مفتاحٍ مستقلٍّ لا يُخطئه النموذج ────────────────────
chat = (ROOT / "backend/app/services/ai_chat.py").read_text(encoding="utf-8")
check("الشركة المقصودة في السؤال" in chat,
      "٦ الشركةُ المحسومةُ تُوضع في مفتاحٍ مستقلّ")

# ── ٧ · وقاعدةٌ تُحرّم نفيَ وجودها ────────────────────────────────────
check("فيحرم أن تقول إنها ليست في محفظته" in chat,
      "٧ التوجيهُ يُحرّم نفيَ وجودِ شركةٍ محسومة")

# ── ٨ · ونقصُ حقلٍ لا يُبطل السؤال كلَّه ──────────────────────────────
# «غير متوفّر» صدقٌ عن حقل، وكذبٌ عن شركةٍ في اليد.
check("ولا تُبطل السؤال كلَّه" in chat,
      "٨ نقصُ حقلٍ يُسمّى ولا يُبطل الجواب")

print()
print("النتيجة:", "فيه ملاحظات ✘" if fail else "نظيف ✔")
raise SystemExit(fail)
