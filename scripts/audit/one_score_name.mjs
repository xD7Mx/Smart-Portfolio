// ─────────────────────────────────────────────────────────────────────────
// D224 — رقمٌ واحدٌ باسمٍ واحد.
//
// قال المالك: «درجة الحوكمة هي نفسها الدرجة المالية وهي نفسها درجة السلامة
// — يجب توحيد الجميع». وكان محقّاً: حقلٌ واحدٌ (`finance_score`) يُعرض بثلاثة
// أسماء في ثماني شاشات. ومن رأى ثلاثة أسماء ظنّها ثلاثة مقاييس، فبحث عن
// الفرق بينها ولا فرق.
//
// وهذا هو الخطُّ الأحمر نفسُه الذي سبق في «القيمة العادلة» (‏D147 · D174):
// اسمٌ يحمل قيمتين، أو قيمةٌ تحمل اسمين — كلاهما يُفقد الثقة بالأرقام كلِّها.
//
// فيُمنع عودةُ الاسمين المهجورين إلى نصٍّ يقرؤه المالك. والتعليقاتُ خارج
// النطاق: توثيقُ العطب يحتاج ذكرَ اسمه القديم.
// ─────────────────────────────────────────────────────────────────────────
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SRC = join(ROOT, "frontend", "src");
/* الاسمُ الموحَّد «درجة الجودة المالية» — لا «الحوكمة».
   جرّبتُ توحيدَها على «الحوكمة» فأوقفني الحارسُ الأقدم ‏S-GOVNAME، ومعه
   حقّ: القرارُ ‏D096 فصل «الحوكمة» عمداً — وهي ركنٌ حقيقيٌّ مستقلّ (تركّزُ
   الملكية · التداولُ الحرّ · تخفيفُ الحصّة · تمويلُ التوزيع) — وتسميةُ
   الدرجة المالية بها تُعيد الخلطَ الذي عولج. فالاسمُ الواحدُ يُختار من
   جنس ما يقيسه، لا من جنس القسم الذي يعرضه. */
const RETIRED = ["درجة السلامة"];

function walk(dir) {
  return readdirSync(dir).flatMap(n => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : (/\.tsx?$/.test(p) ? [p] : []);
  });
}

/* التعليقاتُ تُنزع قبل الفحص: الحارسُ يمنع الاسمَ في **ما يُعرض**، لا في
   شرحِ سببِ منعه — وإلّا استحال توثيقُ العطب في موضعه. */
const strip = (s) => s
  .replace(/\/\*[\s\S]*?\*\//g, " ")
  .replace(/^\s*\/\/.*$/gm, " ");

let fail = 0;
const hits = [];
for (const f of walk(SRC)) {
  const body = strip(readFileSync(f, "utf8"));
  for (const w of RETIRED) {
    if (body.includes(w)) hits.push(`${f.replace(ROOT + "/", "")}: «${w}»`);
  }
}
if (hits.length) fail = 1;
console.log(`${hits.length ? "FAIL" : "PASS"} ١ لا اسمَ مهجوراً لدرجة الجودة المالية في نصٍّ معروض`
            + (hits.length ? ` — ${hits.slice(0, 4).join(" · ")}` : ""));

// والاتّجاه المعاكس: الاسمُ الموحَّد **موجودٌ فعلاً** — لا أن تُحذف الأسماء
// الثلاثة فيبقى الرقمُ بلا اسم، فيمرّ الحارسُ على شاشةٍ صامتة.
const all = walk(SRC).map(f => readFileSync(f, "utf8")).join("\n");
const present = (all.match(/درجة الجودة المالية/g) || []).length;
if (present < 5) fail = 1;
console.log(`${present >= 5 ? "PASS" : "FAIL"} ٢ والاسمُ الموحَّد معروضٌ في الشاشات — ${present} موضعاً`);

console.log();
console.log("النتيجة:", fail ? "فيه ملاحظات ✘" : "نظيف ✔");
process.exit(fail);
