#!/bin/sh
# ══════════════════════════════════════════════════════════════════════
#  نسخٌ احتياطيّ تلقائيّ — المحفظة الذكية
#
#  يأخذ نسختين في كل تشغيل:
#    ١) قاعدة البيانات كاملةً (كل ما في المحفظة: العمليات، التوزيعات،
#       اللقطات التاريخية، الأهداف، خطّة السيولة… ).
#    ٢) ملفات المستخدم التي لا تعيش في القاعدة: المكتبة، الصور، الإعدادات.
#
#  ثلاث قواعد تحكمه:
#    • كلمة السرّ لا تخرج من الحاوية أبداً — تُقرأ داخلها ولا تظهر في أمرٍ
#      ولا في سجلّ ولا في قائمة العمليات.
#    • لا يُحذف نسخةٌ قديمة إلّا بعد أن تنجح الجديدة ويثبت أنها غير فارغة.
#      نسخةٌ فاشلة تمسح ما قبلها أسوأ من لا نسخة.
#    • كل تشغيلٍ يُسجَّل بنتيجته، فتُعرف الأعطال قبل أن تُحتاج النسخة.
# ══════════════════════════════════════════════════════════════════════
set -u

APP=/home/ubuntu/Smart-Portfolio
DEST=/home/ubuntu/sp_backups
KEEP_DAYS=30
LOG="$DEST/backup.log"

DB_CONTAINER=sp_postgres
STAMP=$(date +%F_%H%M)

mkdir -p "$DEST" || exit 1
say() { echo "$(date '+%F %T')  $*" >> "$LOG"; }

# ── ١) قاعدة البيانات ────────────────────────────────────────────────
DB_FILE="$DEST/db_$STAMP.sql.gz"
if ! docker exec "$DB_CONTAINER" sh -c \
      'PGPASSWORD="$POSTGRES_PASSWORD" pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB"' \
      2>>"$LOG" | gzip > "$DB_FILE"; then
  say "فشل: تعذّر أخذ نسخة قاعدة البيانات — لم يُحذف شيء."
  rm -f "$DB_FILE"
  exit 1
fi

# نسخةٌ فارغة أو مبتورة ليست نسخة. عتبة ١٠ كيلوبايت تكشف الانقطاع.
SIZE=$(wc -c < "$DB_FILE")
if [ "$SIZE" -lt 10240 ]; then
  say "فشل: ملف القاعدة صغيرٌ بشكلٍ مريب ($SIZE بايت) — حُذف، ولم تُمَسّ النسخ القديمة."
  rm -f "$DB_FILE"
  exit 1
fi

# سلامة الضغط: نتأكّد أن الملف يُفكّ فعلاً قبل الاعتماد عليه.
if ! gzip -t "$DB_FILE" 2>>"$LOG"; then
  say "فشل: ملف القاعدة تالف (فشل فحص الضغط) — حُذف."
  rm -f "$DB_FILE"
  exit 1
fi

# ── ٢) ملفات المستخدم ────────────────────────────────────────────────
# المجلدات تُنشأ على الخادم عبر Docker وقد لا توجد كلّها؛ نأخذ الموجود منها
# فقط بدل أن يسقط الأمر كلّه بسبب مجلدٍ غائب.
# **أسبوعيّاً لا يوميّاً.** `storage` يحمل كتب المكتبة (سقفها ١٫٢ج)، فأرشفتها
# كل يوم مع الاحتفاظ بثلاثين نسخة قد تبتلع عشرات الجيجابايت وتملأ القرص —
# وامتلاء القرص يوقف قاعدة البيانات عن الكتابة. والملفّات نادرة التغيّر
# بخلاف القاعدة، فنسخةٌ أسبوعية تكفيها. (يُجبَر بـ FILES=1 عند الحاجة.)
FILE_FILE="$DEST/files_$STAMP.tar.gz"
DOW=$(date +%u)          # ١=الاثنين … ٧=الأحد
if [ "${FILES:-0}" = "1" ] || [ "$DOW" = "5" ] || [ -z "$(ls "$DEST"/files_*.tar.gz 2>/dev/null)" ]; then
  DIRS=""
  for d in data storage config; do
    [ -d "$APP/$d" ] && DIRS="$DIRS $d"
  done
  if [ -n "$DIRS" ]; then
    # shellcheck disable=SC2086
    tar -czf "$FILE_FILE" -C "$APP" $DIRS 2>>"$LOG" || say "تنبيه: تعذّر أرشفة بعض ملفات المستخدم."
  else
    say "تنبيه: لا مجلدات ملفاتٍ للأرشفة."
  fi
else
  FILE_FILE=""
fi

# حارسُ المساحة: لا نُبقي نسخاً على قرصٍ يوشك أن يمتلئ. عند تجاوز ٨٥٪ تُحذف
# أقدم نسخة ملفّاتٍ زائدة ويُسجَّل تنبيه — امتلاء القرص أخطر من فقد نسخةٍ قديمة.
USEPCT=$(df -P "$DEST" | awk 'NR==2{gsub("%","",$5); print $5}')
if [ "${USEPCT:-0}" -ge 85 ]; then
  say "تنبيه: القرص ممتلئ ${USEPCT}٪ — تُحذف أقدم أرشيفات الملفّات."
  ls -1t "$DEST"/files_*.tar.gz 2>/dev/null | tail -n +3 | while IFS= read -r f; do rm -f "$f"; done
fi

# ── ٣) التدوير — بعد النجاح وحده ────────────────────────────────────
find "$DEST" -maxdepth 1 -name 'db_*.sql.gz'    -mtime +$KEEP_DAYS -delete
# أرشيفات الملفّات أثقل وأندر، فتُحفظ ثمانية أسابيع لا ثلاثين يوماً.
find "$DEST" -maxdepth 1 -name 'files_*.tar.gz' -mtime +56 -delete

say "تمّ: $(basename "$DB_FILE") ($((SIZE/1024)) ك.ب) + $(basename "$FILE_FILE" 2>/dev/null)"
exit 0
