#!/bin/sh
# ══════════════════════════════════════════════════════════════════════
#  فاحصُ بنية خريطة الأخبار — قبل الحكم عليها
#
#  الفحصُ السابق أعاد «عناصر: 0»، وهذا **ليس** دليلاً على خلوّ الملفّ.
#  فقد بحثتُ فيه عن وسومٍ افترضتُها (<url> و<news:title>) دون أن أنظر
#  إلى بنيته الحقيقية. والملفّ ١٫٢٥ ميجابايت — لا يكون هذا حجمَ فراغ.
#  الاحتمالاتُ ثلاثة: مضغوطٌ بـgzip · أو وسومُه بأسماءٍ أخرى · أو أنه
#  صفحةُ خطأ. وهذا السكربت يفصل بينها بالنظر لا بالظنّ.
#
#  يقرأ ولا يكتب. يُشغَّل على الخادم:  sh scripts/probe_sitemap.sh
# ══════════════════════════════════════════════════════════════════════
set -u
UA="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36"
F=/tmp/an.xml

# ينزَّل من جديد مع فكّ الضغط تلقائياً (--compressed) — فإن كان مضغوطاً
# سابقاً فهنا يُفكّ، وتظهر البنية التي حجبها الضغط.
curl -sL --compressed --max-time 40 -H "User-Agent: $UA" \
     -o "$F" "https://www.argaam.com/sitemapnews-ar.xml"

echo "══ الهوية ══"
file "$F" 2>/dev/null || echo "(لا أداة file)"
echo "الحجم: $(wc -c < "$F") بايت"
echo
echo "══ أوّل ٤٠٠ حرف — هنا تُقرأ البنية بالعين ══"
head -c 400 "$F" | tr -d '\r'
echo; echo
echo "══ أكثر الوسوم تكراراً ══"
grep -oE '<[a-zA-Z][a-zA-Z0-9:_-]*' "$F" | sort | uniq -c | sort -rn | head -15
echo
echo "══ آخر ٣٠٠ حرف ══"
tail -c 300 "$F" | tr -d '\r'
echo
echo "══════════════════════════════════════"
echo "أرسل المخرَج كما هو. إن ظهرت وسومُ عناوينَ وتواريخ فالطريق سالك،"
echo "وإن ظهرت صفحةُ HTML أو منعٌ فأقولها صراحةً ونمضي إلى البديل."
