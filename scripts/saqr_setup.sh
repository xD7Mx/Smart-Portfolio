#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# استخراج بيانات قناة «صقر» من تلغرام — يُشغَّل على خادم المالك.
#
# ما يفعله:
#   ١. يقرأ رمز البوت **بلا إظهار** (لا يظهر على الشاشة ولا في سجلّ الأوامر
#      ولا في ملفٍ مؤقّت). وهذا شرطٌ صريحٌ من المالك: لا ينكشف مفتاحٌ سرّي.
#   ٢. يسأل تلغرام عن هويّة البوت (getMe) — فيثبت أن الرمز صحيح وحيّ.
#   ٣. يُسقط أي خطّافٍ قديم (deleteWebhook) — البوت المُعاد استخدامه يحمل
#      خطّاف مشروعه السابق، فيسرق التحديثات ويعطي 409 عند الاستطلاع.
#   ٤. يقرأ التحديثات (getUpdates) ويستخرج **معرّف المحادثة** — وهو الرقم
#      الوحيد الذي لا يمكن معرفته إلا بمراسلة البوت.
#   ٥. يطبع أسطر .env المطلوبة — والرمز فيها **مكانٌ فارغ يملؤه المالك بيده**.
#
# ما لا يفعله: لا يكتب في .env، ولا يرسل الرمز إلى أي جهةٍ غير تلغرام، ولا
# يطبعه ولا يحفظه. مسؤوليةُ الرمز تبقى في يد مالكه وحده.
#
#   الاستعمال:   bash scripts/saqr_setup.sh
# ─────────────────────────────────────────────────────────────────────────────
set -u

API="${SAQR_API:-https://api.telegram.org}"

say() { printf '%s\n' "$*"; }
rule() { printf '%s\n' "──────────────────────────────────────────────"; }

# jq ليس مضموناً على كل خادم — استخراجٌ بـsed يكفي لحقولٍ معروفة.
# الفراغ بعد النقطتين اختياريّ في JSON — والتساهل معه يمنع فشلاً صامتاً
# لو غيّر تلغرام تنسيق مخرجاته يوماً.
field() { sed -n 's/.*"'"$1"'":[[:space:]]*"\([^"]*\)".*/\1/p' <<<"$2" | head -1; }
nfield() { sed -n 's/.*"'"$1"'":[[:space:]]*\(-\?[0-9]\+\).*/\1/p' <<<"$2" | head -1; }

rule
say "🦅  إعداد قناة «صقر» — استخراج البيانات من تلغرام"
rule
say "الرمز يُقرأ ولا يُعرض. لن يُطبع ولا يُحفظ في أي ملف."
say ""
printf 'ألصق رمز البوت من BotFather ثم اضغط Enter: '
read -rs TOKEN
printf '\n\n'

if [ -z "${TOKEN:-}" ]; then
  say "✖ لم يُدخَل رمز. أُلغي الإعداد."
  exit 1
fi

# ── ١) هويّة البوت ───────────────────────────────────────────────────────────
ME=$(curl -sS --max-time 20 "$API/bot$TOKEN/getMe")
if ! grep -qE '"ok":[[:space:]]*true' <<<"$ME"; then
  say "✖ تلغرام رفض الرمز."
  say "  السبب كما ورد: $(field description "$ME")"
  say "  راجع BotFather: /mybots ← البوت ← API Token."
  unset TOKEN
  exit 1
fi

BOT_USER=$(field username "$ME")
BOT_NAME=$(field first_name "$ME")
BOT_ID=$(nfield id "$ME")

say "✔ الرمز صحيح."
say "   الاسم:    $BOT_NAME"
say "   المعرّف:  @$BOT_USER"
say "   الرقم:    $BOT_ID"
say ""

# ── ٢) إسقاط إرث المشروع السابق ─────────────────────────────────────────────
HOOK=$(curl -sS --max-time 20 "$API/bot$TOKEN/getWebhookInfo")
HOOK_URL=$(field url "$HOOK")
if [ -n "${HOOK_URL:-}" ]; then
  say "⚠ على هذا البوت خطّافٌ قديم — سيسرق كل تحديثٍ ولن يصل صقر شيء."
  curl -sS --max-time 20 -o /dev/null "$API/bot$TOKEN/deleteWebhook?drop_pending_updates=true"
  say "✔ أُسقط الخطّاف وأُفرغت التحديثات المعلّقة."
  say ""
fi

# ── ٣) معرّف المحادثة ───────────────────────────────────────────────────────
say "افتح تلغرام الآن، ادخل @$BOT_USER، واضغط Start (أو أرسل أي كلمة)."
printf 'ثم اضغط Enter هنا للقراءة… '
read -r _
say ""

UP=$(curl -sS --max-time 25 "$API/bot$TOKEN/getUpdates?limit=20")
# المعرّف يُقرأ من كائن chat لا من كائن from: هما متطابقان في المحادثة
# الخاصّة ومختلفان في المجموعة — ولو قرأناه من from لأرسلنا تقارير المحفظة
# إلى محادثةٍ غير التي طُلبت منها.
CHATS=$(grep -o '"chat":[[:space:]]*{[^}]*}' <<<"$UP" | while IFS= read -r c; do
  id=$(sed -n 's/.*"id":[[:space:]]*\(-\?[0-9]\+\).*/\1/p' <<<"$c")
  ty=$(sed -n 's/.*"type":[[:space:]]*"\([^"]*\)".*/\1/p' <<<"$c")
  nm=$(sed -n 's/.*"first_name":[[:space:]]*"\([^"]*\)".*/\1/p' <<<"$c")
  [ -z "$nm" ] && nm=$(sed -n 's/.*"title":[[:space:]]*"\([^"]*\)".*/\1/p' <<<"$c")
  [ -n "$id" ] && printf '%s|%s|%s\n' "$id" "${ty:-?}" "${nm:-—}"
done | awk '!seen[$0]++')

if [ -z "${CHATS:-}" ]; then
  say "✖ لم يصل تلغرام أيّ رسالة بعد."
  say "  السبب الغالب: لم تُضغط Start، أو ضُغطت قبل إسقاط الخطّاف."
  say "  أرسل للبوت أي كلمة ثم أعد تشغيل هذا الأمر."
  unset TOKEN
  exit 1
fi

say "✔ المحادثات التي راسلت البوت:"
awk -F'|' '{printf "   %-16s %-8s %s\n", $1, $2, $3}' <<<"$CHATS"
say ""

# المحادثة الخاصّة هي المقصودة دائماً — المجموعات والقنوات تحمل معرّفاً
# سالباً وتُرتَّب قبلها في أي فرز، فاختيار «الأول» بلا تمييزٍ كان يعطي
# القناة بدل المالك.
CHAT_ID=$(awk -F'|' '$2=="private"{print $1; exit}' <<<"$CHATS")
if [ -z "${CHAT_ID:-}" ]; then
  CHAT_ID=$(head -1 <<<"$CHATS" | cut -d'|' -f1)
  say "⚠ لا محادثة خاصّة بين ما وصل — أُخذ أول معرّف. راجعه بنفسك."
elif [ "$(awk -F'|' '$2=="private"' <<<"$CHATS" | wc -l)" -gt 1 ]; then
  say "⚠ أكثر من محادثةٍ خاصّة راسلت البوت — أُخذت الأولى. اختر أنت إن أخطأت."
fi

# ── ٤) أسطر .env — بلا رمز ─────────────────────────────────────────────────
rule
say "أضف هذه الأسطر إلى /home/ubuntu/Smart-Portfolio/.env"
rule
say "TELEGRAM_ENABLED=true"
say "TELEGRAM_BOT_TOKEN=<ألصق_الرمز_هنا_بيدك>"
say "TELEGRAM_CHAT_ID=$CHAT_ID"
say "TELEGRAM_BOT_USERNAME=$BOT_USER"
rule
say ""
say "ثم:  docker compose up -d --build backend"
say ""
say "يبقى شيءٌ واحد يدويّ: صورة البوت."
say "واجهة البوتات لا تتيح رفع صورةٍ برمجياً — فمن BotFather:"
say "   /setuserpic  ←  @$BOT_USER  ←  ارفع أيقونة التطبيق."
say "أمّا الاسم والوصف والأوامر فيضبطها صقر وحده عند الإقلاع."
say ""

unset TOKEN
