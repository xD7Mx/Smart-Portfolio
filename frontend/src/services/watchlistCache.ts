import type { QueryClient } from "@tanstack/react-query";

/**
 * إبطال ذاكرة المراقبة بعد أي تغيير على النجمة.
 *
 * الحالة نفسها تُقرأ من ثلاث ذاكراتٍ مستقلّة: قائمة المجموعة `["watchlist", gid]`،
 * وعضويّة السهم `["watchlist-membership", symbol]` (تقرؤها صفحة الشركة)،
 * وقائمة المجموعات. وكانت كل شاشةٍ تُبطل ما تقرؤه هي وحدها: النجمة تُضغط في
 * البحث فيُبطل `["watchlist"]` وحده، وتبقى عضويّة السهم في الذاكرة كما كانت،
 * فتُفتح صفحة الشركة والنجمة فارغة — وهو ما رآه المالك. والذاكرة تُعدّ حديثةً
 * خمس دقائق ولا تُعاد عند العودة للشاشة، فيبدو الأمر «يحتاج تحديث التطبيق».
 *
 * الإبطال هنا يشمل العائلات الثلاث دائماً، من مكانٍ واحد لا يُنسى نصفه.
 */
export function invalidateWatchlist(qc: QueryClient) {
  /* `refetchType: "all"` لا الافتراضي: التطبيق يضبط `refetchOnMount: false`
     (بقرارٍ سابق أوقف إعادة بناء الشاشات عند كل زيارة)، والإبطال الافتراضي
     يعيد جلب النشط وحده ويكتفي بوسم الخامل «قديماً» — والخامل مع ذلك الضبط
     لا يُعاد جلبه عند فتحه. فتبقى صفحة الشركة تعرض نجمةً قديمة حتى يُحدَّث
     التطبيق كلّه. هنا يُعاد الجلب للجميع، فالحالة واحدة أينما ظهرت. */
  const opts = { refetchType: "all" as const };
  qc.invalidateQueries({ queryKey: ["watchlist"], ...opts });
  qc.invalidateQueries({ queryKey: ["watchlist-membership"], ...opts });
  qc.invalidateQueries({ queryKey: ["watchlist-groups"], ...opts });
}
