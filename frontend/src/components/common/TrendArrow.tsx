import React from "react";

/* ══ سهمُ الاتجاه — شكلٌ واحد للتطبيق كلّه ══ (بأمر المالك)

   كان مثلّثاً مرسوماً بحدود CSS (`border` على عنصرٍ بلا أبعاد). وذلك
   أسلوبٌ يرسم **رأساً** فقط: لا ذيلَ له ولا يمكن أن يكون له، لأن الشكل
   كلَّه ناتجُ التقاء ثلاثة حدود. فطلبُ «ذيلٍ للسهم» لم يكن تعديل قيمةٍ
   بل تغييرَ وسيلة الرسم — فانتقل إلى SVG.

   وثلاثة أشكال لا شكلان:
     صاعد  — رأسٌ للأعلى بذيلٍ تحته
     هابط  — رأسٌ للأسفل بذيلٍ فوقه
     تعادل — **بلا ذيل**: رأسان مدمجان، واحدٌ للأعلى وآخر للأسفل، بلونٍ
             برتقاليّ. ومعناه دقيق: لا حركةَ في اتجاهٍ بعينه، لا «حركةٌ
             صفرية» ولا سكون. ولهذا لا يُرسم شرطةً — الشرطة تقول «لا
             قيمة»، والتعادل قيمةٌ معلومة قدرها صفر.
   والحجم يتبع الخطّ (`em`) فيكبر ويصغر مع النصّ المجاور بلا ضبطٍ يدويّ. */
export default function TrendArrow({
  dir, size = 11, color, className = "",
}: { dir: "up" | "dn" | "fl"; size?: number; color?: string; className?: string }) {
  const common = {
    width: size, height: size, viewBox: "0 0 24 24",
    className: "shrink-0 " + className,
    "aria-hidden": true as any,
    style: { color: color || "currentColor", display: "block" as const },
  };
  if (dir === "fl") {
    /* رأسان مدمجان بلا ذيل — يلتقيان في الوسط فيقرأهما النظر شكلاً
       واحداً لا سهمين متجاورين.

       ══ الأصفر وحافّته ══ (بأمر المالك)
       طلب المالك أصفرَ متوسطاً واضحاً بدل البرتقاليّ. وشريط السوق أرضيّته
       **بيضاء** في المظهر الفاتح، وأيُّ أصفرَ متوسط عليها يقيس 1.5–1.9:1
       — أي يختفي، وهو نقيضُ «واضح». وأدكنُ أصفرَ يعبر العتبة على البياض
       (‏#a16207) ذهبٌ داكن لا أصفر.
       فبقي الأصفر أصفر، وانتقل التباين إلى **الحافّة**: حشوٌ #eab308
       وحدٌّ ذهبيّ داكن يرسم الشكل (‏paint-order: stroke fill كي لا يقضم
       الحدُّ الحشوَ من داخله). وهي الحيلة نفسها التي رضيها في أعمدة
       التوزيعات: العين تقرأ الشكل من حدّه واللون يبقى كما أراد. */
    return (
      <svg {...common} fill="currentColor" stroke="var(--flat-edge)"
        strokeWidth={1.4} strokeLinejoin="round"
        style={{ ...common.style, paintOrder: "stroke fill" as any }}>
        <path d="M12 3 L19 11 H5 Z" />
        <path d="M12 21 L5 13 H19 Z" />
      </svg>
    );
  }
  const up = dir === "up";
  return (
    <svg {...common} fill="none" stroke="currentColor"
      strokeWidth={3.2} strokeLinecap="round" strokeLinejoin="round">
      {/* الذيل: خطٌّ رأسيّ يمتدّ من الرأس إلى الطرف المقابل */}
      <line x1="12" y1={up ? 21 : 3} x2="12" y2={up ? 5 : 19} />
      {/* الرأس: ضلعان يلتقيان عند طرف الذيل */}
      <polyline points={up ? "5 12 12 4 19 12" : "5 12 12 20 19 12"} />
    </svg>
  );
}
